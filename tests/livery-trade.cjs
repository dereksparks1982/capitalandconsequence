'use strict';
const assert=require('node:assert/strict'),trade=require('../livery-trade.js');
const clock=require('../washington-time.js'),bridge=require('../calendar-bridge.js');
global.FE_WASHINGTON_TIME=clock;
assert.equal(trade.quote('westLivery','work-horse').priceCents,10000);
assert.equal(trade.quote('eastLivery','work-horse').priceCents,9000,'Brothers compete for working horses');
assert.equal(trade.quote('eastLivery','carriage').priceCents,9500);
assert.equal(trade.quote('bad','work-horse').ok,false);
const save={paused:false,phase:'day',gameDate:'1878-01-02',
 personalCash:300,companyCash:350,characterRoute:'industrialist',
 currentLocation:{locationId:'eastLivery',roomId:'service-desk'}};
bridge.start(save,'1878-01-02',540);
const spend=seconds=>clock.advance(save,seconds,'action').applied?seconds:0;
const a=trade.buy(save,'eastLivery','work-horse','stable:1',spend);
assert.equal(a.ok,true);
assert.equal(a.priceCents,9000);
assert.equal(save.personalCash,210);
assert.equal(save.companyCash,350,'Personal purchase cannot debit workshop money');
assert.equal(save.transport.assets.length,1);
assert.equal(save.transport.assets[0].locationId,'eastLivery','Owned horse does not teleport to factory');
assert.equal(save.transport.assets[0].status,'stabled');
assert.equal(save.liveryTrade.tills.eastLivery,9000,'Seller gets paid');
assert.equal(clock.now(save).time,'9:15 AM');
const snapshot=JSON.stringify(save);
assert.equal(trade.buy(save,'eastLivery','work-horse','stable:1',()=>{throw Error('No duplicate')}).repeated,true);
assert.equal(JSON.stringify(save),snapshot);
assert.equal(trade.buy(save,'westLivery','wagon','stable:2',spend).ok,false,'No remote shopping');
save.currentLocation={locationId:'eastLivery',roomId:'horse-yard'};
assert.equal(trade.buy(save,'eastLivery','wagon','stable:2',spend).ok,false,'Purchases require service desk');
save.currentLocation={locationId:'eastLivery',roomId:'service-desk'};
assert.equal(trade.buy(save,'eastLivery','wagon','stable:2',spend).ok,true);
assert.equal(save.personalCash,150);
assert.equal(save.transport.assets[1].model,'wagon');
assert.equal(save.transport.assets[1].locationId,'eastLivery');
bridge.start(save,'1878-01-06',540);
const held=JSON.stringify(save);
assert.equal(trade.buy(save,'eastLivery','wagon','stable:3',spend).ok,false,'Sunday stable closed');
assert.equal(JSON.stringify(save),held);
bridge.start(save,'1878-01-07',1015);
assert.equal(trade.buy(save,'eastLivery','wagon','stable:3',spend).ok,false,'No 5 PM transaction crossing');
save.personalCash=1;bridge.start(save,'1878-01-07',540);
assert.equal(trade.buy(save,'eastLivery','wagon','stable:3',spend).ok,false,'No counterfeit payment');
console.log('PASS sibling stable price competition, physical asset purchase, personal money, service-desk gate and replay resistance');
