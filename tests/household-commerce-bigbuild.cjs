'use strict';
// Focused offline source regressions. Does not substitute for packaged Linux QA.
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const source=p=>fs.readFileSync(path.join(root,p),'utf8');
const page=source('index.html'),app=source('app.js');
const scripts=[...page.matchAll(/<script src="([^"]+)/g)].map(x=>x[1].split('?')[0]),ix=x=>scripts.indexOf(x);
assert.ok(ix('household-shopping.js')>=0&&ix('household-shopping.js')<ix('app.js'));
assert.ok(ix('household-food-catalog.js')<ix('washington-commerce.js'));
for(const action of ['planRecipe','buyPlan','clearPlan','loadIce','clearSpoiled','storeAll','pack','sell'])
 assert.ok(app.includes(action+':'),'Missing game handler '+action);
const marketUI=source('market-ui.js');
assert.match(marketUI,/button.textContent=food\?'Eat \/ Drink':'Take Home'/,'No destructive Use action for nonfood');
globalThis.FE_FOOD_CATALOG=require('../household-food-catalog.js');
globalThis.FE_WASHINGTON_COMMERCE=require('../washington-commerce.js');
globalThis.FE_RECIPES=require('../household-recipes.js');
globalThis.FE_KITCHEN=require('../household-kitchen.js');
globalThis.FE_COOKERY=require('../household-cooking.js');
globalThis.FE_HOME_DELIVERIES=require('../home-deliveries.js');
globalThis.FE_HOUSEHOLD_SHOPPING=require('../household-shopping.js');
const minute=iso=>Date.parse(iso+'Z')/60000;
const s={gameDate:'1878-01-02',personalCash:20,
 worldCalendar:{worldMinute:minute('1878-01-02T08:30:00')},
 currentLocation:{locationId:'home',roomId:'kitchen'}};
const commerce=FE_WASHINGTON_COMMERCE,kitchen=FE_KITCHEN,planning=FE_HOUSEHOLD_SHOPPING,
 cooking=FE_COOKERY,delivery=FE_HOME_DELIVERIES;
const market=commerce.ensure(s);
assert.ok(commerce.GOODS.length>=190);
assert.equal(planning.choose(s,'white-loaf').ok,false,'Unlearned cookbook recipe cannot be planned');
assert.equal(planning.choose(s,'boiled-eggs').ok,true);
let q=planning.quote(s);assert.equal(q.totalPackages,1);
assert.equal(q.receipt,null,'Planning at home is not a purchase');
const savedBefore=JSON.stringify(s);assert.equal(commerce.purchaseBasket(s,'centerMarket',[{id:'eggs',packages:25}]).ok,false);
assert.equal(JSON.stringify(s),savedBefore,'Bad basket leaves whole save untouched');
s.currentLocation={locationId:'centerMarket',roomId:'market-hall'};
assert.equal(planning.quote(s,'centerMarket').possible,true);
const before=market.siteStocks.centerMarket.eggs,cash=s.personalCash;
const bought=planning.buy(s,'centerMarket');
assert.equal(bought.ok,true);assert.equal(bought.packages,1);
assert.equal(market.siteStocks.centerMarket.eggs,before-1);
assert.equal(s.personalCash,cash-0.24);
assert.equal(planning.quote(s).complete,true,'Carried eggs count against planned deficit');
assert.equal(planning.buy(s,'centerMarket').ok,false,'Cannot automatically rebuy fulfilled plan');
const fresh=JSON.parse(JSON.stringify(s));
assert.equal(planning.quote(fresh).complete,true,'Plan and goods survive reload');
const ban=commerce.quoteBasket(s,'', [{id:'stew-beef',packages:1}]);
assert.equal(ban.ok,false,'Chinatown shopping basket rejects goods not sold locally');
s.currentLocation={locationId:'home',roomId:'kitchen'};
const eggId=market.playerBag[0].id;
assert.equal(kitchen.store(s,eggId,'icebox').ok,true);
assert.equal(cooking.complete(s,'boiled-eggs').ok,true);
assert.equal(kitchen.available(s,{eggs:11}).ok,false);
const icePurchased=commerce.purchase(s,'player','ice-block',{date:s.gameDate,siteId:'easternMarket'});
assert.equal(icePurchased.ok,true);
const iceId=market.playerBag.find(x=>x.good==='ice-block').id;
assert.equal(kitchen.loadIce(s,iceId).ok,true);
assert.equal(market.playerBag.some(x=>x.id===iceId),false,'Consumed physical ice removed');
assert.equal(kitchen.loadIce(s,iceId).ok,false,'Cannot load the same ice twice');
assert.ok(kitchen.ledger(s).k.iceUntil>s.worldCalendar.worldMinute);
const perish=commerce.purchase(s,'player','milk',{date:s.gameDate,siteId:'easternMarket'});
assert.equal(perish.ok,true);
const dairy=market.playerBag.find(x=>x.good==='milk'),expiry=dairy.expiresAt;
assert.equal(kitchen.store(s,dairy.id,'icebox').ok,true);
const stored=kitchen.ledger(s).k.goods.find(x=>x.good==='milk');
assert.equal(stored.expires,expiry,'Bag to icebox never refreshes shelf life');
assert.equal(kitchen.take(s,stored.id).ok,true);
assert.equal(market.playerBag.find(x=>x.good==='milk').expiresAt,expiry,'Taking food home does not refresh shelf life');
assert.equal(kitchen.store(s,stored.id,'icebox').ok,true);
s.worldCalendar.worldMinute=expiry+1;
assert.equal(kitchen.available(s,{milk:1}).ok,false,'Expired dairy cannot be cooked');
assert.equal(kitchen.clearSpoiled(s).ok,true,'Spoiled food can be discarded');
const deliverySave={gameDate:'1878-01-07',personalCash:0,
 worldCalendar:{worldMinute:minute('1878-01-07T17:00:00')},currentLocation:{locationId:'home',roomId:'kitchen'}};
assert.equal(delivery.setOrder(deliverySave,'milk',1).ok,true);
deliverySave.gameDate='1878-01-08';deliverySave.worldCalendar.worldMinute=minute('1878-01-08T08:30:00');
assert.equal(delivery.tick(deliverySave).processed.some(x=>!x.ok),true);
delivery.tick(deliverySave);
assert.equal(delivery.state(deliverySave).failedRounds.length,1,'Same failure logged only once');
const bakerySave={gameDate:'1878-01-09',personalCash:30,
 worldCalendar:{worldMinute:minute('1878-01-09T10:00:00')},currentLocation:{locationId:'home',roomId:'kitchen'}};
const bm=commerce.ensure(bakerySave);
const baked=kitchen.addMeal(bakerySave,'white-loaf',2);
assert.equal(kitchen.packMeal(bakerySave,baked.id,2).ok,true);
assert.equal(commerce.purchaseBasket(bakerySave,'centerMarket',[{id:'bread',packages:6}],{date:bakerySave.gameDate}).ok,true);
bakerySave.currentLocation={locationId:'centerMarket',roomId:'market-hall'};
assert.equal(cooking.sell(bakerySave,kitchen.ledger(bakerySave).k.carriedMeals[0].id,1).ok,true);
assert.equal(bm.accounts['centerMarket:bakery'],6*5-24,'Bakery sale debited the local till');
const distant={...bakerySave,currentLocation:{locationId:'centerMarket',roomId:'market-outside'}};
assert.equal(cooking.atMarket(distant),false,'No sales from an unregistered room');
console.log('PASS big household build: planning, atomic checkout, ice, expiry, deliveries, bakery tills, game bindings');
