'use strict';
const assert=require('node:assert/strict');
const canon=require('../world-canon.js'),dialogue=require('../npc-dialogue.js');
const resident={id:'madamStar',name:'Madam Star',occupation:'Club proprietor',ambition:'keep her staff employed',publicRemark:'Ask what happened, not what was rumored'};
const empty={};
let p=dialogue.prepare({save:empty,npc:resident,utterance:'Who is president?',date:'1878-01-02',weather:'Cold and clear',location:'Star Club',playerName:'Samuel Harlan'});
assert.equal(p.ok,true);
assert.equal(p.messages.length,2);
assert.match(p.messages[0].content,/Samuel J\. Tilden/);
assert.match(p.messages[0].content,/Electoral College was abolished/);
assert.match(p.messages[0].content,/Cold and clear/);
assert.doesNotMatch(canon.forDate('1877-01-02').lines.join(' '),/Samuel J\. Tilden won/);
assert.doesNotMatch(canon.forDate('1890-01-02').lines.join(' '),/Samuel J\. Tilden won/);
assert.match(canon.forDate('1890-01-02').lines.join(' '),/undecided/);
assert.throws(()=>dialogue.prepare({...{},npc:resident,save:empty,date:'1878-01-02',utterance:'x'.repeat(601)}));
let ru=dialogue.prepare({save:empty,npc:{id:'alexiRurik',name:'Alexi',language:'ru',occupation:'Courier'},utterance:'Hello',date:'1878-01-02',playerLanguages:['en']});
assert.equal(ru.ok,false,'No automatic Russian-English translation');
assert.equal(dialogue.prepare({save:empty,npc:{id:'alexiRurik',name:'Alexi',language:'ru',occupation:'Courier'},utterance:'Здравствуйте',date:'1878-01-02',playerLanguages:['ru']}).language,'ru','Earned Russian permits native-language talk');
dialogue.record(empty,resident.id,{date:'1878-01-02',user:'Good morning',reply:'Good morning to you.',place:'star'});
const original=JSON.stringify(empty);
assert.equal(dialogue.history(empty,resident.id).length,1);
assert.equal(dialogue.history({},resident.id).length,0,'Separate saves do not share conversations');
p=dialogue.prepare({save:empty,npc:resident,utterance:'What about tomorrow?',date:'1878-01-03'});
assert.equal(p.messages[1].content,'Good morning');
assert.equal(p.messages[2].content,'Good morning to you.');
assert.equal(p.messages[3].content,'What about tomorrow?');
assert.equal(JSON.stringify(empty),original,'Prompt construction never edits saved memories');
for(let n=0;n<45;n++)dialogue.record(empty,resident.id,{date:'1878-01-03',user:'Question '+n,reply:'Answer '+n});
assert.equal(dialogue.history(empty,resident.id).length,12,'Bounded prompt memory');
assert.equal(empty.npcConversations.byResident[resident.id].length,40,'Bounded disk transcript');
const text=JSON.stringify(empty);
assert.equal(JSON.stringify(JSON.parse(text)),text,'Transcript persists via standard profile JSON');
assert.throws(()=>dialogue.record(empty,resident.id,{date:'1878-01-03',user:'x',reply:''}));
console.log('PASS historical era gates, shared spoken languages, conversation prompts and persisted isolated memory');
