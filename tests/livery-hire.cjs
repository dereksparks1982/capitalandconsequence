'use strict';
const assert=require('node:assert/strict');
const trade=require('../livery-trade.js'),clock=require('../washington-time.js');
const bridge=require('../calendar-bridge.js'),care=require('../horse-care.js'),custody=require('../horse-custody.js');
global.FE_WASHINGTON_TIME=clock;
const s={gameDate:'1878-01-02',paused:false,phase:'day',personalCash:20,companyCash:2500,
 currentLocation:{locationId:'westLivery',roomId:'service-desk'}};
bridge.start(s,'1878-01-02',540);
const spend=seconds=>clock.advance(s,seconds,'action').applied?seconds:0;
assert.equal(trade.HIRES['horse-and-buggy'].priceCents,250);
const hired=trade.hire(s,'westLivery','horse-and-buggy','hire1',spend);
assert.equal(hired.ok,true);assert.equal(hired.ids.length,2);
assert.equal(s.personalCash,17.5);assert.equal(s.companyCash,2500);
assert.equal(s.liveryTrade.tills.westLivery,250);
assert.equal(s.transport.assets[0].locationId,'westLivery');
assert.equal(s.transport.assets[0].owner,'rental');
const snap=JSON.stringify(s);
assert.equal(trade.hire(s,'westLivery','horse-and-buggy','hire1',spend).repeated,true);
assert.equal(JSON.stringify(s),snap);
const firstCare=care.settleDay(s);
assert.equal(firstCare.accruedCents,0,'First day was prepaid at hire');
assert.equal(custody.prepare(s,hired.ids[0],'westLivery',hired.ids[1]).ok,true);
s.transport.journeys.push({id:'trip1',from:'westLivery',to:'home',calendarApplied:true});
assert.equal(custody.onArrival(s,'westLivery','home',true).ok,true);
assert.equal(trade.returnHire(s,hired.ids[0],'return-early',spend).ok,false,'Cannot return remotely');
assert.equal(s.transport.assets.filter(a=>a.owner==='rental').every(a=>a.locationId==='home'),true);
s.gameDate='1878-01-03';
assert.equal(care.settleDay(s).accruedCents,250,'Next calendar day adds actual rental fees');
assert.equal(s.personalCash,17.5,'Rentals accrue debt before weekly settlement');
s.gameDate='1878-01-04';
assert.equal(care.settleDay(s).accruedCents,250);
s.gameDate='1878-01-05';
const sat=care.settleDay(s);
assert.equal(sat.accruedCents,250);
assert.equal(sat.paidCents,750);
assert.equal(sat.arrearsCents,0);
assert.equal(s.personalCash,10);
assert.equal(s.liveryTrade.tills.westLivery,1000,'One $2.50 hire plus three actual $2.50 rental days');
assert.equal(s.companyCash,2500);
s.currentLocation={locationId:'home',roomId:'private-stable'};
assert.equal(custody.prepare(s,hired.ids[0],'home',hired.ids[1]).ok,true);
s.transport.journeys.push({id:'trip2',from:'home',to:'westLivery',calendarApplied:true});
assert.equal(custody.onArrival(s,'home','westLivery',true).ok,true);
s.currentLocation={locationId:'westLivery',roomId:'service-desk'};
bridge.start(s,'1878-01-05',540);
const returned=trade.returnHire(s,hired.ids[0],'return1',spend);
assert.equal(returned.ok,true);assert.equal(returned.assetIds.length,2);
assert.equal(s.transport.assets.length,0,'No ghost hired property retained after return');
const once=JSON.stringify(s);
assert.equal(trade.returnHire(s,hired.ids[0],'return1',spend).repeated,true);
assert.equal(JSON.stringify(s),once);
s.gameDate='1878-01-06';
assert.equal(care.settleDay(s).accruedCents,0,'Returned rental stops next-day billing');
const noFunds={gameDate:'1878-01-02',phase:'day',paused:false,personalCash:0,
 currentLocation:{locationId:'westLivery',roomId:'service-desk'}};
bridge.start(noFunds,'1878-01-02',540);
assert.equal(trade.hire(noFunds,'westLivery','horse','bad',seconds=>seconds).ok,false);
console.log('PASS prepaid livery horse-and-buggy hire, accruing extra days, actual Saturday rent, physical return and replay');
