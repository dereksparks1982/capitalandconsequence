'use strict';
const assert=require('node:assert/strict');
const p=require('../presidential-charter.js');
assert.equal(p.CHARTER.termYears,10);
assert.equal(p.CHARTER.maxTerms,null);
assert.equal(p.CHARTER.reelectionAllowed,true);
assert.equal(p.CHARTER.electoralCollege,false);
assert.equal(p.CHARTER.firstKnownWinner,'Samuel J. Tilden');
assert.equal(p.electionYear(0),1876);
assert.equal(p.electionYear(1),1886);
assert.equal(p.electionYear(5),1926);
assert.equal(p.scheduledElection(1880),false);
assert.equal(p.scheduledElection(1896),true);
assert.deepEqual(p.scheduledTerm(1876),{electionYear:1876,begin:'1877-03-04',end:'1887-03-04',years:10});
assert.deepEqual(p.scheduledTerm(1886),{electionYear:1886,begin:'1887-03-04',end:'1897-03-04',years:10});
assert.throws(()=>p.scheduledTerm(1880),/Not a scheduled/);
assert.equal(p.electionDue('1886-09-01'),true);
assert.equal(p.electionDue('1880-09-01'),false);
console.log('PASS unlimited reelections, 10-year presidential cycle, 1876 and 1886 dates');
