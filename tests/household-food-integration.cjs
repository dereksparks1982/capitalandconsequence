'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8'),app=fs.readFileSync(path.join(root,'app.js'),'utf8');
const scripts=[...html.matchAll(/<script src="([^"]+)/g)].map(m=>m[1].split('?')[0]),ix=n=>scripts.indexOf(n);
assert.ok(ix('household-food-catalog.js')>=0&&ix('household-food-catalog.js')<ix('washington-commerce.js'),'Food SKUs load before market');
for(const name of ['household-recipes.js','household-kitchen.js','household-cooking.js','home-deliveries.js','household-food-ui.js'])
 assert.ok(ix(name)>=0&&ix(name)<ix('app.js'),'Must load '+name+' before app');
assert.ok(app.includes('renderHouseholdFood(place,room,false)')&&app.includes('renderHouseholdFood(location,room,dev)'));
assert.ok(app.includes('FE_HOME_DELIVERIES.tick(S)'),'Single world clock triggers deliveries');
globalThis.FE_FOOD_CATALOG=require('../household-food-catalog.js');
globalThis.FE_WASHINGTON_COMMERCE=require('../washington-commerce.js');
globalThis.FE_RECIPES=require('../household-recipes.js');
globalThis.FE_KITCHEN=require('../household-kitchen.js');
globalThis.FE_COOKERY=require('../household-cooking.js');
globalThis.FE_HOME_DELIVERIES=require('../home-deliveries.js');
const date='1878-01-07',s={gameDate:date,personalCash:30,worldCalendar:{worldMinute:Date.parse(date+'T08:00:00Z')/60000},
 currentLocation:{locationId:'home',roomId:'kitchen'},personalEffects:{items:[]}};
const m=FE_WASHINGTON_COMMERCE,k=FE_KITCHEN,c=FE_COOKERY,d=FE_HOME_DELIVERIES,book=m.ensure(s);
assert.ok(m.GOODS.length>=190,'Real market catalog populated');
const stock=book.siteStocks.easternMarket.milk;
assert.equal(m.purchase(s,'player','eggs',{date,siteId:'centerMarket'}).ok,true);
assert.equal(k.store(s,book.playerBag[0].id,'icebox').ok,true);
assert.equal(book.playerBag.length,0,'No duplicated bag goods');
assert.equal(c.canCook(s,'boiled-eggs').ok,true);
assert.equal(c.complete(s,'boiled-eggs').ok,true);
assert.equal(k.available(s,{eggs:11}).ok,false,'Ingredients consumed');
assert.equal(d.setOrder(s,'milk',2).ok,true);
assert.equal(d.tick(s).processed.filter(x=>x.ok).length,0,'No retroactive delivery');
s.gameDate='1878-01-08';s.worldCalendar.worldMinute=Date.parse('1878-01-08T08:01:00Z')/60000;
assert.equal(d.tick(s).processed.filter(x=>x.ok).length,1);
assert.equal(book.siteStocks.easternMarket.milk,stock-2);
assert.equal(d.tick(s).processed.filter(x=>x.ok).length,0,'No duplicate charge');
const saved=JSON.parse(JSON.stringify(s));
assert.equal(d.tick(saved).processed.filter(x=>x.ok).length,0,'Reload never re-delivers');
saved.currentLocation={locationId:'centerMarket',roomId:'market-hall'};
assert.equal(c.buyBook(saved,'bakers-manual',item=>{saved.personalEffects.items.push({...item,container:'left-pocket'});return {ok:true}}).ok,true);
assert.equal(c.canRead(saved,'bakers-manual').ok,true);
assert.equal(c.learn(saved,'bakers-manual').ok,true);
assert.ok(c.state(saved).known.includes('white-loaf'));
console.log('PASS food loader, shopping, cooking, next morning wagon, merchant stock, physical cookbook and save reload');
