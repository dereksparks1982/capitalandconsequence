'use strict';
const assert=require('node:assert/strict'),works=require('../component-works.js');
const customer=works.CUSTOMERS[2];
const s=works.createState();
const o=works.order(s,{customer,productId:'telegraph-relay',quantity:3,deadline:'1878-01-12'},'agreement:1');
assert.equal(o.ok,true);
assert.equal(works.assemble(s,o.id,3,'build:1').ok,true);
s.date='1878-01-12';
const cash=s.cashCents;
const ontime=works.ship(s,o.id,1,'shipment:1');
assert.equal(ontime.ok,true);assert.equal(ontime.grossCents,760);
assert.equal(ontime.latePenaltyCents,0);assert.equal(ontime.revenueCents,760);
assert.equal(s.orders[0].delivered,1);
s.date='1878-01-19';
const late=works.ship(s,o.id,2,'shipment:2');
assert.equal(late.ok,true);
assert.equal(late.late,true);
assert.equal(late.grossCents,1520);
assert.equal(late.latePenaltyCents,152);
assert.equal(late.revenueCents,1368);
assert.equal(s.orders[0].latePenaltyCents,152);
assert.equal(s.orders[0].status,'delivered');
assert.equal(s.cashCents,cash+760+1368,'Actual cash is discounted not imaginary revenue');
const snapshot=JSON.stringify(s);
assert.equal(works.ship(s,o.id,2,'shipment:2').repeated,true);
assert.equal(JSON.stringify(s),snapshot,'No duplicate payment or penalty on replay');
assert.equal(works.ship(s,o.id,1,'shipment:3').ok,false,'Full order cannot be shipped twice');
const missed=works.createOpeningOrders(works.createState());
missed.date='1878-01-14';
assert.equal(works.renewStandingOrders(missed,'1878-01-14'),false,'Unfinished orders block automatic renewal');
assert.equal(missed.orders.length,3);
console.log('PASS overdue railway discount, partial on-time invoice, actual cash, blocked renewal and shipment idempotence');
