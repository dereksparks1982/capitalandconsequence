'use strict';
const assert=require('node:assert/strict');
const PF=require('../vendor/pathfinding/pathfinding-browser.min.js');
const YUKA=require('../vendor/yuka/yuka.min.js');
assert.ok(PF.Grid&&PF.AStarFinder,'PathFinding browser bundle is usable in Node');
assert.ok(YUKA.Vector3,'Yuka geometry vector is usable');
const road=require('../road-layout.js');
const p=(x,y)=>({x,y}),s=(x,y,u,v)=>({a:p(x,y),b:p(u,v)});
const source={version:1,active:true,segments:[s(.2,.2,.5,.2),s(.5,.2,.8,.2)],blocks:[]};
road.load(source);
assert.equal(road.isActive(),true);
const path=road.route(p(.2,.2),p(.8,.2));
assert.ok(path&&path.length>=2&&path.routeType==='provisional-street-custom');
road.load({...source,blocks:[{x0:.48,y0:.16,x1:.53,y1:.24}]});
assert.equal(road.route(p(.2,.2),p(.8,.2)),null,'Crossing explicitly blocked building is impossible');
road.load({...source,active:false});
assert.equal(road.isActive(),false);
assert.equal(road.route(p(.2,.2),p(.8,.2)),null);
assert.equal(road.sanitize({version:1,active:true,segments:[s(-1,0,.5,0)],blocks:[]}).active,false);
console.log('PASS custom road A*, obstacle denial, saved activation and Yuka');
