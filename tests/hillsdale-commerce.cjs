'use strict';
const assert=require('node:assert/strict');
const shop=require('../washington-commerce.js');
const save={gameDate:'1878-01-03',personalCash:10};
const m=shop.ensure(save);
assert.ok(shop.SITES['hillsdale-market'].has('bread'));
assert.ok(shop.SITES['hillsdale-butcher'].has('stew-beef'));
assert.equal(shop.allowedAt('bacon','hillsdale-market'),false);
assert.equal(shop.allowedAt('bread','hillsdale-butcher'),false);
const marketBefore=m.siteStocks['hillsdale-market'].bread,chinBefore=m.stock.bread;
const purchase=shop.purchase(save,'player','bread',{date:save.gameDate,siteId:'hillsdale-market'});
assert.equal(purchase.ok,true);
assert.equal(purchase.receipt.siteId,'hillsdale-market');
assert.equal(m.siteStocks['hillsdale-market'].bread,marketBefore-1,'Real Hillsdale merchant stock falls');
assert.equal(m.stock.bread,chinBefore,'Chinatown stock cannot silently vanish');
assert.equal(m.accounts['hillsdale-market:bakery'],5);
assert.equal(save.personalCash,9.95);
const rejected=shop.purchase(save,'player','bacon',{date:save.gameDate,siteId:'hillsdale-market'});
assert.equal(rejected.ok,false);
const meatBefore=m.siteStocks['hillsdale-butcher']['stew-beef'];
assert.equal(shop.purchase(save,'player','stew-beef',{date:save.gameDate,siteId:'hillsdale-butcher'}).ok,true);
assert.equal(m.siteStocks['hillsdale-butcher']['stew-beef'],meatBefore-1);
assert.equal(m.accounts['hillsdale-butcher:butcher'],45);
assert.equal(m.stock['stew-beef'],18);
assert.equal(m.playerBag.length,2);
const state=JSON.stringify(save);
assert.equal(shop.purchase(save,'player','bread',{date:save.gameDate,siteId:'hillsdale-market',token:'test'}).ok,true);
assert.equal(shop.purchase(save,'player','bread',{date:save.gameDate,siteId:'hillsdale-market',token:'test'}).repeated,true,'Repeat transaction cannot charge twice');
const issued=shop.deliveryForCalendar(save,'1878-01-03',0);
assert.equal(issued.ok,false,'No fictional Wednesday wholesale delivery');
const thursday=shop.deliveryForCalendar(save,'1878-01-04',0);
assert.equal(thursday.ok,true);
assert.equal(m.siteStocks['hillsdale-market'].bread,marketBefore-2+4,'Hillsdale got its own delivered goods');
assert.equal(m.stock.bread,chinBefore+10,'Independent main market got its usual delivery');
assert.equal(shop.deliveryForCalendar(save,'1878-01-04',0).repeated,true,'No duplicate stock deliveries');
assert.equal(m.playerBag.length,3,'Purchased items persist in one personal bag');
const copy=JSON.parse(JSON.stringify(save));
assert.equal(copy.washingtonCommerce.siteStocks['hillsdale-butcher']['stew-beef'],m.siteStocks['hillsdale-butcher']['stew-beef']);
console.log('PASS Hillsdale neighborhood butcher and market share one map site, not inventory; bought provisions and deliveries are real');
