'use strict';
/* Offline passenger integration checks. Runs against the authoritative saved
 * calendar value; no time is invented or advanced by the passenger module.
 */
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const nav=require('../merchant-navigation.js');
const sea=require('../merchant-passenger-sea.js');
const walk=require('../merchant-harbor-walk.js');
const ROOT=path.join(__dirname,'..');
const read=file=>fs.readFileSync(path.join(ROOT,file),'utf8');
const minute=iso=>Math.floor(Date.parse(iso)/60000);
const make=()=>({characterRoute:'industrialist',gameDate:'1878-03-10',phase:'day',paused:false,
 personalCash:1000,companyCash:2500,
 currentLocation:{locationId:'factory',roomId:'executive-office'},
 worldCalendarStatus:'ready',worldCalendar:{worldMinute:minute('1878-03-10T09:00:00Z')}});
const save=make();
assert(!sea.quote(save,'Liverpool','schooner').ok,'cannot board from the desk');
save.currentLocation={locationId:'potomacFishingBank',roomId:'riverbank'};
assert(!sea.quote(save,'Liverpool','schooner').ok,'must enter the actual passenger-pier room');
save.currentLocation.roomId='passenger-pier';
assert(!sea.quote({...save,paused:true},'Liverpool','schooner').ok);
assert(!sea.quote({...save,worldCalendarStatus:'legacy-unmapped'},'Liverpool','schooner').ok);
assert(!sea.quote({...save,worldCalendar:null},'Liverpool','schooner').ok);
assert(!sea.quote({...save,characterRoute:'wardman'},'Liverpool','schooner').ok);
assert(!sea.quote(save,'Baltimore','schooner').ok);
assert(!sea.quote(save,'Newport','schooner').ok);
assert(!sea.quote(save,'Liverpool','motorboat').ok);
assert(!sea.quote(save,'Liverpool','steamer').ok,'powered ships are not available');
const quote=sea.quote(save,'Liverpool','schooner');
assert(quote.ok,quote.reason);
assert.equal(quote.from,'Baltimore');assert.equal(quote.to,'Liverpool');
assert.equal(quote.seaDays,nav.plan('Baltimore','Liverpool','schooner').days);
assert.equal(quote.days,quote.seaDays+2);
assert(quote.fare>0);
const money=save.personalCash,company=save.companyCash;
const charter=JSON.stringify(sea.ensure(save));
assert(sea.quote(save,'Liverpool','schooner').ok);
assert.equal(save.personalCash,money,'quote cannot charge');
assert.equal(JSON.stringify(sea.ensure(save)),charter,'quote must not store phantom voyage');
const booked=sea.embark(save,'Liverpool','schooner');
assert(booked.ok,booked.reason);
assert.equal(save.currentLocation.locationId,'passengerVessel');
assert.equal(save.currentLocation.roomId,'cabin');
assert.equal(save.companyCash,company,'personal passenger fare cannot affect Federal Electric');
assert(Math.abs(save.personalCash-(money-quote.fare))<.001,'personal fare charged exactly once');
assert(!sea.embark(save,'Hamburg','schooner').ok);
assert(!sea.quote(save,'Hamburg','schooner').ok);
let pos=sea.position(save);
assert.equal(pos.phase,'at-sea');
assert.equal(pos.feeder,true);
assert.equal(pos.progress,0);
const first=save.passengerSea.voyage;
save.worldCalendar.worldMinute=quote.departMinute+24*60;
assert(sea.position(save).feeder);
save.worldCalendar.worldMinute=quote.departMinute+3*24*60;
assert(!sea.position(save).feeder,'coastal transfer ends after two days');
assert(sea.position(save).progress>0);
save.worldCalendar.worldMinute=quote.arrivalMinute-1;
assert(!sea.sync(save).ok);
assert.equal(save.passengerSea.history.filter(x=>x.kind==='arrived').length,0);
save.worldCalendar.worldMinute=quote.arrivalMinute;
save.gameDate=quote.etaDate;
assert(sea.sync(save).ok,'arrives only when elapsed saved minutes reach due arrival');
assert.equal(save.currentLocation.locationId,'foreignHarbor');
assert.equal(save.currentLocation.roomId,'quay');
assert.equal(save.passengerSea.port,'Liverpool');
assert(!sea.sync(save).ok,'arrival settles once');
assert.equal(save.passengerSea.history.filter(x=>x.kind==='arrived').length,1);
const country=save.passengerSea.port;
assert(!sea.canWalk(save,'market',3,5).ok,'cannot leap to arbitrary tile');
assert(!sea.move(save,'quay',999,999).ok,'cannot walk through borders');
assert(sea.move(save,'quay',5,7).ok,'adjacent quay square');
assert.equal(save.passengerSea.position.x,5);
assert(sea.move(save,'warehouse',6,7).ok,'switch local harbour sectors');
assert.equal(save.currentLocation.roomId,'warehouse');
assert.equal(save.passengerSea.port,country);
const unspent=save.personalCash;
const home=sea.quote(save,'Baltimore','schooner');
assert(home.ok,home.reason);assert(home.returning);
assert.equal(save.personalCash,unspent);
assert(sea.embark(save,'Baltimore','schooner').ok);
assert.equal(save.passengerSea.port,null);
assert.equal(save.currentLocation.locationId,'passengerVessel');
assert.equal(save.passengerSea.voyage.returning,true);
assert(!sea.canWalk(save,'market',6,7).ok,'no remote walking while aboard');
save.worldCalendar.worldMinute=home.arrivalMinute;
save.gameDate=home.etaDate;
assert(sea.sync(save).ok);
assert.equal(save.currentLocation.locationId,'potomacFishingBank');
assert.equal(save.currentLocation.roomId,'passenger-pier');
assert.equal(save.passengerSea.port,null);
assert.equal(save.passengerSea.voyage,null);
assert.equal(save.passengerSea.history.filter(x=>x.kind==='arrived').length,2);
assert(Math.abs(save.personalCash-(money-quote.fare-home.fare))<.001);
assert.equal(save.companyCash,company);
assert(!sea.sync(save).ok);
assert(read('city.js').includes("id:'foreignHarbor'"));
assert(read('city.js').includes("id:'passengerVessel'"));
assert(read('city.js').includes("id:'passenger-pier'"));
const app=read('app.js'),html=read('index.html');
assert(app.includes('FE_PASSENGER_ACTIONS'));
assert(app.includes('finish his maritime journey'));
assert(app.includes('FE_PASSENGER_UI?.refresh?.(S,window.FE_PASSENGER_ACTIONS)'));
assert(app.includes('advanceWorldSimulation(span,true,\'sea-passenger\')'));
assert(html.includes('merchant-passenger-sea.js')&&html.includes('merchant-passenger-ui.js'));
assert(html.includes('merchant-passenger-ui.css'));
assert(html.includes('title-map-1938.jpg'),'original Washington map must not change');
assert(read('merchant-world-map.js').includes('ocean-passenger-ship'));
assert(read('merchant-passenger-ui.js').includes('passenger-sea-map'));
console.log('passenger sea: true pier gate, fare, actual minute passage, unique arrival, foreign walking, return, preserved city & treasury passed');
