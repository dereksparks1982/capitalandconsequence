'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const needs=require('../character-needs.js'),alarm=require('../windup-sleep.js');
const app=fs.readFileSync(path.join(__dirname,'../app.js'),'utf8');
const ui=fs.readFileSync(path.join(__dirname,'../sleep-ui.js'),'utf8');
const medical=fs.readFileSync(path.join(__dirname,'../medical-records-ui.js'),'utf8');
const styles=fs.readFileSync(path.join(__dirname,'../styles.css'),'utf8');
const start=Math.floor(Date.parse('1878-01-02T08:00:00Z')/60000);
const save={worldCalendarStatus:'ready',worldCalendar:{worldMinute:start},phase:'day',characterRoute:'industrialist'};
const before=needs.ensure(save);
assert.equal(before.meters.energy,80);
assert.ok(needs.RATES.energy>0);
save.worldCalendar.worldMinute+=60;
needs.sync(save);
assert.ok(Math.abs(save.characterNeeds.meters.energy-74.9)<.000001,'awake energy drains with game clock');
assert.ok(needs.CONFIG.coffee.effects.energy>0,'coffee still adds energy');
const tired=save.characterNeeds.meters.energy;
save.sleepingAtHome=true;
save.worldCalendar.worldMinute+=120;
needs.sync(save);
assert.equal(save.characterNeeds.meters.energy,tired,'sleep itself cannot drain energy');
const rested=needs.finishSleep(save,120);
assert.equal(rested.ok,true);
assert.ok(rested.energy>tired,'sleep actually restores energy');
save.sleepingAtHome=false;
const configured=alarm.configure(save,{enabled:true,hour:7,minute:0});
assert.ok(configured.ok);
assert.ok(alarm.wind(save).ok);
const plan=alarm.plan(save,{hours:2});
assert.ok(plan.ok);
assert.ok(plan.totalMinutes>=30&&plan.totalMinutes<=210);
assert.equal(alarm.plan(save,{hours:13}).ok,false);
assert.equal(alarm.plan(save,{hours:.25}).ok,false);
const settlement=alarm.settle(save,plan,plan.totalMinutes);
assert.equal(settlement.ok,true);
assert.equal(save.sleepHistory.length,1);
assert.match(app,/function sleepAtHome\(options=\{\}\)/);
assert.match(app,/advanceWorldSimulation\(required,true,'sleep'\)/,'one existing clock');
assert.match(app,/FE_CHARACTER_NEEDS\?\.finishSleep/,'sleep duration affects energy');
assert.doesNotMatch(app,/FE_CHARACTER_NEEDS\?\.overnight\?\.\(S\)/,'morning transition cannot refill energy');
assert.match(app,/FE_SLEEP_UI\?\.render/,'real bedroom render has sleep UI');
assert.match(ui,/Sleep Custom Hours/);
assert.match(ui,/Nap · 1 hour/);
assert.match(ui,/Night · 8 hours/);
assert.match(ui,/Wind the Clock/);
assert.match(ui,/classList\.add\('is-black'\)/,'sleep fades to black');
assert.match(med,/FE_SLEEP_UI\?\.render/,'medical UI uses one sleep panel');
assert.match(styles,/:not\(#careerDevToggle\)/,'developer toggle remains visible in rooms');
console.log('PASS awake depletion, custom sleep recovery, 1878 wind-up alarm, bedroom UI and global developer opener');
