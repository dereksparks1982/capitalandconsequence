'use strict';
const assert=require('node:assert/strict');
const missions=require('../mission-engine.js'),history=require('../life-history.js');
const edmund={characterRoute:'wardman',gameDate:'1878-01-02',personalCash:1};
const id='ward:WARD-0001',one={ok:true,assignment:{id:'WARD-0001',date:'1878-01-02',taskId:'linen'}};
assert.equal(missions.syncWard(edmund,'assign',one).status,'created');
assert.equal(missions.syncWard(edmund,'assign',one).status,'existing');
assert.equal(missions.step(edmund,id,'file',{eventId:'fake'}).ok,false,'Cannot skip ward service');
let result=missions.syncWard(edmund,'attend',{ok:true,assignment:{...one.assignment,choiceId:'replace'}});
assert.equal(result.mission.stage,'awaiting-report');
assert.equal(missions.syncWard(edmund,'attend',one).ok,false,'Cannot repeat a completed stage');
result=missions.syncWard(edmund,'file',{ok:true,log:{...one.assignment,choiceId:'replace'}});
assert.equal(result.mission.status,'completed');
assert.equal(missions.ensure(edmund).history.length,1);
assert.equal(missions.syncWard(edmund,'file',{ok:true,log:one.assignment}).status,'duplicate');
assert.equal(edmund.personalCash,1,'Mission bookkeeping never mints a second wage');
history.record(edmund,{id:'ward:WARD-0001:file',date:'1878-01-02',source:'ward duty',text:'Filed service'});
const copy=JSON.parse(JSON.stringify(edmund));
assert.equal(missions.ensure(copy).history.length,1);
assert.equal(missions.pages(copy)[0].items.length,1);
const other={characterRoute:'investigator',gameDate:'1878-01-02'};
assert.equal(missions.start(other,{id:'ward:WARD-0002',templateId:'ward-round'}).ok,false);
const second=missions.start(edmund,{id:'ward:WARD-0002',templateId:'ward-round'});
assert.equal(second.status,'created');
assert.equal(missions.abandon(edmund,'ward:WARD-0002').mission.status,'abandoned');
assert.equal(missions.ensure(edmund).active['ward:WARD-0002'],undefined);
console.log('PASS persistent ward mission assignment, progression, duplicate prevention, and abandonment');
