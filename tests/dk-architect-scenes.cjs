'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const read=p=>fs.readFileSync(path.join(__dirname,'..',p),'utf8');
const core=read('room-builder-core.js'),ui=read('room-builder-ui.js'),scene=read('room-builder-scene.js'),html=read('index.html'),css=read('room-builder.css');
const C=require('../room-builder-core.js');
const office=C.makeRoom('factory','executive-office'),salem=C.makeRoom('salemHarbor','leach-office'),wharf=C.makeRoom('salemHarbor','harbor-walk');
assert.notEqual(C.key(office.locationId,office.roomId),C.key(salem.locationId,salem.roomId));
assert.notEqual(C.key(salem.locationId,salem.roomId),C.key(wharf.locationId,wharf.roomId));
assert(ui.includes('<h2>DK ARCHITECT</h2>'));
assert(ui.includes("function open(target)")&&ui.includes("selectScene(place?.locationId"));
assert(ui.includes("STORAGE=C.key(locationId,roomId)")&&ui.includes("C.makeRoom(locationId,roomId)"));
assert(ui.includes("getSaved:(location=locationId,whichRoom=roomId)"));
assert(ui.includes("C.sanitize(JSON.parse(x),location,whichRoom)"));
assert(ui.includes("Kit.listDrafts(localStorage,locationId,roomId)"));
assert(ui.includes("Kit.openDraft(localStorage,locationId,roomId,name)"));
assert(ui.includes("root.FE_ROOM_BUILDER?.refreshScene?.()"));
assert(scene.includes("launch.textContent='DK Architect · Decorate Scene'"));
assert(scene.includes("api.open({locationId:target.locationId,roomId:target.roomId})"));
assert(scene.includes("api.getSaved(target.locationId,target.roomId)"));
assert(scene.includes("root.FE_CITY?.isDevRoom?.()"));
assert(scene.includes("return isOffice()?layout?.objects"),'non-office desk must not unlock Charles office use');
assert(ui.includes("playerSprite:locationId==='factory'"));
assert(scene.includes("playerSprite:isOffice()?'charles':null"));
assert(html.includes('room-builder-ui.js?v=')&&html.includes('room-builder-scene.js?v='));
assert(css.includes('.dk-architect-room-launch[hidden]'));
assert(core.includes("const key=(location,room)=>'ccRoomLayoutV1:'"));
console.log('PASS DK Architect room identity, saved decorations, scene launch, drafts and office action separation');
