'use strict';
const assert=require('node:assert/strict');
const shop=require('../crowe-butchery.js');
const t=Math.floor(Date.parse('1878-01-02T08:00:00Z')/60000);
function fresh(){return {characterRoute:'criminal',gameDate:'1878-01-02',phase:'day',
 paused:false,personalCash:100,companyCash:50000,worldCalendar:{worldMinute:t},
 currentLocation:{locationId:'croweButcherShop',roomId:'ice-room'}}}
const save=fresh(),store=shop.ensure(save);
const first=shop.summary(save).coldRoom;
assert.equal(first.standardAgingDays,30);
assert.equal(first.sides[0].weightLbs,320);
assert.equal(first.sides[0].ageDays,18);
assert.equal(shop.quote(save,'cutSide',{sideId:1}).ok,false);
assert.equal(shop.quote(save,'cutSide',{sideId:1,early:true}).ok,true);
assert.equal(shop.apply(save,'cutSide',{sideId:1,early:true},0).ok,false);
assert.equal(shop.apply(save,'cutSide',{sideId:1,early:true},1800).ok,true);
assert.equal(store.raw.beef,36);
save.worldCalendar.worldMinute+=12*1440;
shop.sync(save);
let r=shop.summary(save).coldRoom;
assert.equal(r.sides[0].ageDays,30);
assert.equal(r.sides[0].standardReady,true);
assert(r.deliveries>=1,'The cousin arranges paid ice deliveries');
assert(r.spentCents>0);
assert.equal(shop.quote(save,'cutSide',{sideId:1}).ok,true);
assert.equal(shop.apply(save,'cutSide',{sideId:1},1800).ok,true);
const weight=shop.summary(save).coldRoom.sides[0].weightLbs;
save.worldCalendar.worldMinute+=95*1440;
shop.sync(save);
r=shop.summary(save).coldRoom;
assert(r.sides[0].ageDays>=120,'Extended sound aging has no arbitrary expiry');
assert.equal(r.sides[0].weightLbs,weight);
assert.equal(r.condition,'stable');
assert(r.cleanliness>75);
store.coldRoom.iceBlocks=0;store.tillCents=0;store.bookTillCents=0;
save.worldCalendar.worldMinute+=4*1440;
shop.sync(save);
r=shop.summary(save).coldRoom;
assert.equal(r.inspectionHold,true);
assert.equal(r.sides[0].weightLbs,weight,'Do not discard stock automatically');
assert.equal(shop.quote(save,'cutSide',{sideId:1}).ok,false);
store.tillCents=100;store.bookTillCents=100;
assert.equal(shop.apply(save,'iceDelivery',{},0).ok,false);
assert.equal(shop.apply(save,'iceDelivery',{},300).ok,true);
assert.equal(store.tillCents,50);
assert.equal(store.bookTillCents,50);
assert.equal(shop.summary(save).coldRoom.inspectionHold,true);
assert.equal(shop.apply(save,'cleanRoom',{},900).ok,true);
assert.equal(shop.summary(save).coldRoom.inspectionHold,false);
assert.equal(shop.quote(save,'cutSide',{sideId:1}).ok,true);
assert.equal(shop.ensure(fresh()).coldRoom.iceDeliveries,0);
assert.equal(save.companyCash,50000);
assert.doesNotMatch(JSON.stringify(shop.summary(save)),/smother|lover|murdered/i);
console.log('PASS Crowe 30-day hanging beef, early cuts, months of preservation, automatic ice, paid deliveries, inspection holds and shop accounting');
