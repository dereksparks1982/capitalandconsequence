'use strict';
const assert=require('node:assert/strict'),cal=require('../oval-championships.js'),e=require('../championships.js');
assert.equal(cal.isChampionship('dog','1918-10-27'),false);
assert.equal(cal.isChampionship('car','1919-10-26'),false);
assert.equal(cal.isChampionship('dog','1919-10-26'),true);
assert.equal(cal.isChampionship('dog','1919-10-19'),false);
assert.equal(cal.isChampionship('car','1933-10-29'),true);
assert.equal(cal.isChampionship('car','1933-10-22'),false);
assert.equal(cal.isChampionship('dog','1919-02-29'),false);
const s={};
const racers=Array.from({length:12},(_,i)=>String(i+1));
const id=cal.open(s,'dog','1919-10-26',racers,e);
assert.equal(id,'dog-1919-10');
assert.equal(cal.open(s,'dog','1919-10-26',racers,e),id);
assert.equal(cal.open(s,'dog','1919-10-25',racers,e),null);
const r1=cal.result(s,'dog','1919-10-26',id,'D1',[1,2,3,4,5,6],e);
assert.equal(r1.tournament.rounds['heat-a'].result[0],'1');
cal.result(s,'dog','1919-10-26',id,'D2',[7,8,9,10,11,12],e);
const final=cal.result(s,'dog','1919-10-26',id,'DF',[1,7,2,8,3,9],e);
assert.equal(final.tournament.champion,'1');
assert.equal(s.champions.dog.name,'1');assert.equal(s.titleHistory.length,1);
assert.throws(()=>cal.result(s,'dog','1919-10-26',id,'DF',[1,7,2,8,3,9],e),/already finalized/);
const car={};
const cid=cal.open(car,'car','1933-10-29',racers,e);
cal.result(car,'car','1933-10-29',cid,'C1',[1,2,3,4,5,6],e);
cal.result(car,'car','1933-10-29',cid,'C2',[7,8,9,10,11,12],e);
cal.result(car,'car','1933-10-29',cid,'CF',[8,1,2,3,7,9],e);
assert.equal(car.champions.car.name,'8');assert.equal(car.titleHistory.length,1);
console.log('PASS monthly kennels and cars: calendar, heats, title history, no duplicate crown');
