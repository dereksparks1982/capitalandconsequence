'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const tarot=require('../tarot-deck.js'),circus=require('../circus-tour.js'),discover=require('../npc-discovery.js'),sleep=require('../windup-sleep.js');
const now=Math.floor(Date.parse('1878-05-04T20:00:00Z')/60000);
const save={worldCalendarStatus:'ready',worldCalendar:{worldMinute:now},personalCash:15,characterRoute:'industrialist',currentLocation:{locationId:'races'}};
assert.equal(tarot.CARDS.length,78);
assert.equal(new Set(tarot.CARDS.map(c=>c.id)).size,78);
assert.equal(tarot.CARDS.filter(c=>c.arcana==='major').length,22);
assert.equal(tarot.CARDS.filter(c=>c.arcana==='minor').length,56);
for(const shape of Object.keys(tarot.SPREADS)){
 const draw=tarot.draw('private-seed',shape);
 assert.equal(draw.ok,true);
 assert.equal(draw.cards.length,tarot.SPREADS[shape].length);
 assert.equal(new Set(draw.cards.map(c=>c.id)).size,draw.cards.length);
 assert.deepEqual(draw,tarot.draw('private-seed',shape),'a saved draw can be reproduced without re-rolling');
}
assert.equal(tarot.reading(save,{readerId:'wanderingReader',encounterId:'card-1',feeCents:200}).ok,true);
assert.equal(save.personalCash,13);
assert.equal(tarot.reading(save,{readerId:'wanderingReader',encounterId:'card-1',feeCents:200}).replayed,true);
assert.equal(save.personalCash,13,'one fee per reading');
assert.equal(tarot.reading(save,{readerId:'wanderingReader',encounterId:'card-2',feeCents:9999}).ok,false);
assert.equal(tarot.reading(save,{readerId:'wanderingReader',feeCents:100}).ok,false,'no scene-free reading');
assert.equal(circus.active(save),null,'circus is not always in town');
assert.equal(circus.attend(save,'visit-one').ok,false,'no phantom attendance');
global.FederalElectricCity={listLocations:()=>[{id:'races',name:'Racetrack'}]};
global.FE_NPC_MAP_PIN=id=>id==='races'?{x:.65,y:.3}:null;
assert.equal(circus.schedule(save,{id:'visit-one',startMinute:now,endMinute:now+480,locationId:'races'}).ok,true);
assert.equal(circus.active(save).id,'visit-one');
assert.equal(circus.attended(save),false);
assert.equal(circus.attend(save,'visit-one').ok,true,'only an actual event visit records attendance');
assert.equal(circus.attended(save),true);
save.worldCalendar.worldMinute+=480;
assert.equal(circus.active(save),null,'circus disappears on departure');
const before=save.personalCash;
assert.equal(discover.known(save,'samHarlan'),false);
assert.deepEqual(discover.fromText(save,'An unidentified official attended the meeting.','newspaper',[{id:'samHarlan',name:'Samuel Harlan'}]),[]);
assert.deepEqual(discover.fromText(save,'Samuel Harlan appeared at the station.','newspaper',[{id:'samHarlan',name:'Samuel Harlan'}]),['samHarlan']);
assert.equal(discover.known(save,'samHarlan'),true);
assert.equal(discover.known(save,'edmundWardman'),false);
assert.equal(save.personalCash,before);
assert.equal(sleep.configure(save,{enabled:true,hour:7,minute:0}).ok,true);
assert.equal(sleep.wind(save).ok,true);
const plan=sleep.plan(save,{hours:12});
assert.equal(plan.ok,true);
assert.equal(plan.alarmWound,true);
assert.equal(plan.alarmScheduled,true,'a 7am alarm interrupts a 12h sleep started at 4am after event');
assert.equal(plan.alarmRang||plan.overslept,true);
assert.equal(sleep.settle(save,plan,plan.totalMinutes).ok,true);
assert.equal(save.windupAlarm.woundAt,null,'clock must be wound again after ringing');
const app=fs.readFileSync(path.join(__dirname,'../app.js'),'utf8');
const index=fs.readFileSync(path.join(__dirname,'../index.html'),'utf8');
const npc=fs.readFileSync(path.join(__dirname,'../npc-street-travel.js'),'utf8');
assert.match(npc,/knownToPlayer\(save,a\.id\)/,'map never renders unknown NPCs');
assert.doesNotMatch(npc,/Show destination|traveling toward|approximately.*game minutes/,'no omniscient destination leakage');
assert.match(app,/FE_CIRCUS_TOUR\?\.render/);
assert.match(index,/tarot-deck\.js\?v=/);
assert.match(index,/npc-discovery\.js\?v=/);
console.log('PASS tarot deck, independent readings, discovery, public circus dates/attendance and wind-up clock');
