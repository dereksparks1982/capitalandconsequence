'use strict';
const assert=require('node:assert/strict'),eco=require('../washington-commerce.js');
const works=require('../component-works.js');
const save={gameDate:'1878-01-14',companyCash:100,lastRevenue:0,personalCash:2,componentWorks:works.createState(),
 npcSimulation:{agents:{foremanSullivan:{economy:{balanceCents:600}},eddieDoyle:{economy:{balanceCents:500}}}}};
const market=eco.ensure(save);
assert.equal(market.stock.bread,24);
const player=eco.purchase(save,'player','bread',{date:save.gameDate,token:'market-sale-1'});
assert.equal(player.ok,true);assert.equal(save.personalCash,1.95);
assert.equal(market.stock.bread,23);assert.equal(market.accounts.bakery,5);
assert.equal(market.playerBag.length,1);
assert.equal(eco.purchase(save,'player','bread',{date:save.gameDate,token:'market-sale-1'}).repeated,true);
const nc=eco.purchase(save,'eddieDoyle','bread',{date:save.gameDate,token:'npc-1'});
assert.equal(nc.ok,true);assert.equal(market.stock.bread,22);
assert.equal(save.npcSimulation.agents.eddieDoyle.economy.balanceCents,495);
assert.equal(market.accounts.bakery,10,'Both buyers credit one till');
assert.equal(eco.deliveryForCalendar(save,'1878-01-13',0).ok,false,'Sunday does not deliver');
const del=eco.deliveryForCalendar(save,'1878-01-17',0);assert.equal(del.ok,true);assert.equal(del.repeated,false);
assert.equal(market.stock.bread,32,'Receipt physically adds ten packs');
const branchGoods=Object.values(eco.SITES).reduce((sum,goods)=>sum+goods.size,0);
assert.equal(market.deliveries['1878-01-17'].manifest.length,eco.GOODS.length+branchGoods,'Delivery includes main market and independently stocked neighborhood shops');
assert.ok(market.supplierDebts.bakery>=0);
const paid=market.suppliersPaidCents;
assert.equal(eco.deliveryForCalendar(save,'1878-01-17',0).repeated,true);
assert.equal(market.suppliersPaidCents,paid);
assert.equal(market.stock.bread,32,'Repeated delivery cannot mint goods');
market.stock.bread=0;
const before=save.personalCash;assert.equal(eco.purchase(save,'player','bread',{date:save.gameDate}).ok,false);
assert.equal(save.personalCash,before,'Out-of-stock purchase never charges');
assert.equal(eco.consume(save,market.playerBag[0].id).ok,true);
assert.equal(market.playerBag.length,0);
const restored=JSON.parse(JSON.stringify(save));assert.equal(eco.ensure(restored).stock.bread,0,'Autosave does not restock empty shelves');
assert.equal(restored.washingtonCommerce.deliveries['1878-01-17'].units,10+6*(eco.GOODS.length-1)+4*branchGoods,'Neighborhood branch deliveries are physical additional goods');
console.log('PASS player/NPC shared physical market, stockout, delivery credit, idempotence and profile save');
