'use strict';
/* Source-only checks for independent shipping map, desk miniature and pin study layer.
   Character transit is deliberately NOT represented as implemented by this test. */
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const read=file=>fs.readFileSync(path.join(root,file),'utf8');
const nav=require('../merchant-navigation.js');
const regions=require('../merchant-regions.js');
const commerce=require('../industrial-empire.js');
const src=read('merchant-world-map.js');
const html=read('index.html');
const desk=read('career-shell.js');
const arrange=read('desk-collection.js');
const css=read('merchant-world-map.css');
assert(fs.existsSync(path.join(root,nav.MAP)),'owner-selected Admiralty art must be bundled');
assert(src.includes('FE_MERCHANT_MAP'), 'shipping map API must exist');
assert(src.includes('merchant-world-viewport')&&src.includes('merchant-world-stage'), 'full map viewport missing');
assert(src.includes('onPointerDown')&&src.includes('e.button!==2'), 'right mouse panning must be present');
assert(src.includes('onWheel')&&src.includes("command==='zoom-in'"), 'wheel and button zoom must be present');
assert(html.indexOf('merchant-chart-camera.js')<html.indexOf('merchant-world-map.js')&&html.includes('merchant-chart-camera.js'),'Pure chart camera loads before map UI');
assert(src.includes('function persistView()')&&src.includes('view.zoom='), 'maritime camera settings must persist');
assert(src.includes('focus-port:')&&src.includes('focus-pin:'), 'port and personal mark directory navigation missing');
assert(src.includes('dispatchEvent(new MouseEvent'), 'SVG markers must support keyboard activation');
assert(src.includes('regions.addPin')&&src.includes('regions.rename'), 'saved personal map pin tools missing');
assert(src.includes("root.FE_EMPIRE"),'merchant map must use existing business authority');
for(const name of ['buyShip','dispatch','repairShip','verifyLead','sellElectric'])assert(src.includes(name),'Missing map operation '+name);
assert(src.includes('portPanel(')&&src.includes('ocean-port-scene'), 'compact port region viewer missing');
assert(src.includes('function harborRegister(')&&src.includes('Recorded Federal Electric Cargo'), 'dockside sector register must read real goods');
assert(src.includes('function portMiniScene(')&&src.includes('aria-pressed'), 'compact harbour sections should have an inspectable selected area');
assert(src.includes('Passage estimate from Baltimore'), 'historical-style voyage estimator missing');
assert(!src.includes('S.currentLocation='), 'chart must not teleport a playable character');
assert(desk.includes('careerDeskShippingMap')&&desk.includes('careerDeskShippingButton'), 'accessible desk chart opener missing');
assert(desk.includes(nav.MAP), 'desk art must use the owner-selected Admiralty chart');
assert(arrange.includes("pos('shipping')")&&arrange.includes("shipping:Object.freeze"), 'draggable map position must save');
assert(html.includes('merchant-world-map.js')&&html.includes('merchant-world-map.css')&&html.includes('merchant-regions.js'));
assert(html.includes('title-map-1938.jpg'), 'original Washington map must not be swapped out');
assert(css.includes('.career-desk .career-desk-shipping'));
assert.equal(typeof commerce.dispatch,'function');
const a={characterRoute:'industrialist',gameDate:'1878-05-10'};
let m=regions.ensure(a);
assert.equal(m.version,1);assert.equal(m.pins.length,0);
const first=regions.addPin(a,200.25,411.1);assert.equal(first.ok,true);
assert.deepEqual(m.pins[0],{id:1,x:200.3,y:411.1,name:'Chart Mark 1',kind:'study'});
assert.equal(regions.rename(a,1,'South Atlantic Route').ok,true);
assert.equal(m.pins[0].name,'South Atlantic Route');
assert.equal(regions.move(a,1,220,406).ok,true);
assert.equal(regions.classify(a,1,'harbor').ok,true);
assert.equal(m.pins[0].kind,'harbor');
assert.equal(regions.classify(a,1,'unknown').ok,false);
assert.equal(regions.ensure({}).pins.length,0,'a different save must not inherit the active profile marks');
assert.equal(regions.addPin(a,900,5).ok,false);
assert.equal(regions.rename(a,1,'').ok,false);
assert.equal(regions.port('Havana')?.zones.length,6);
assert.equal(regions.inspectZone('Liverpool','warehouse').name,'Storehouse');
assert.equal(regions.port('Unknown'),null);
assert.equal(regions.remove(a,1).ok,true);
assert.equal(regions.remove(a,1).ok,false);
assert.equal(m.pins.length,0);
const s=JSON.stringify(a);
assert.equal(regions.ensure(a),m);
assert.equal(JSON.stringify(a),s,'reading pin state should not generate entries');
assert.deepEqual(Object.keys(nav.PORTS).sort(),Object.keys(commerce.PORTS).sort());
console.log('merchant world map: desk miniature, map controls, port sectors, fleet API and 1-profile pin actions verified');
