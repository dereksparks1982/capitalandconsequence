'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const rails=require('../railway-network.js'),symbols=require('../location-icons.js');
const point=(x,y)=>({x,y});
const S={worldCalendarStatus:'ready',worldCalendar:{worldMinute:45100},characterRoute:'industrialist'};
assert.deepEqual(rails.sanitize(null),{version:1,segments:[],stations:[],trains:[]});
assert.equal(rails.addStation(S,point(.2,.2),'Premature Station').ok,false,'station requires track');
assert.equal(rails.addSegment(S,point(.2,.2),point(.3,.2)).ok,true);
assert.equal(rails.addSegment(S,point(.3,.2),point(.4,.3)).ok,true);
assert.equal(rails.addSegment(S,point(-.5,.2),point(.7,.3)).ok,false,'off-map construction rejected');
const first=rails.addStation(S,point(.2,.2),'Potomac Station');
const second=rails.addStation(S,point(.4,.3),'Eastern Station');
assert.ok(first.ok&&second.ok);
assert.equal(rails.addStation(S,point(.4,.3),'Overlapping Station').ok,false);
const route=rails.path(S.railwayPlanner,first.station.id,second.station.id);
assert.equal(route.points.length,3,'locomotive follows the painted corners');
assert.ok(route.distancePixels>150);
assert.equal(rails.startTrain(S,first.station.id,'nonexistent').ok,false,'no phantom train to nonstation');
assert.equal(rails.startTrain(S,second.station.id,first.station.id).ok,true,'both directions are possible');
const dispatch=rails.startTrain(S,first.station.id,second.station.id);
assert.equal(dispatch.ok,true);
assert.equal(dispatch.train.departure,S.worldCalendar.worldMinute,'one authoritative clock');
assert.equal(S.railwayPlanner.trains.length,1,'only one demo train, no duplicate sprites');
const before=rails.trainPosition(S.railwayPlanner,S.worldCalendar.worldMinute,dispatch.train);
const mid=rails.trainPosition(S.railwayPlanner,S.worldCalendar.worldMinute+dispatch.minutes/2,dispatch.train);
const after=rails.trainPosition(S.railwayPlanner,S.worldCalendar.worldMinute+dispatch.minutes,dispatch.train);
assert.ok(before.x<mid.x&&mid.x<after.x);
assert.equal(before.arrived,false);assert.equal(after.arrived,true);
assert.equal(rails.trainPosition(S.railwayPlanner,S.worldCalendar.worldMinute,dispatch.train).x,before.x,'render cannot move without game-time change');
assert.equal(rails.eraseAt(S,point(.35,.25)).ok,true,'erase a selected section');
assert.equal(rails.path(S.railwayPlanner,first.station.id,second.station.id),null,'disconnected rail cannot run');
assert.equal(S.railwayPlanner.trains.length,0,'remove route-invalidated locomotive');
const copy=rails.sanitize(JSON.parse(JSON.stringify(S.railwayPlanner)));
assert.equal(copy.segments.length,1,'segments persist across save serialization');
assert.equal(copy.stations.length,2);
assert.equal(symbols.selected(S,'factory'),'number','numbered markers remain the default');
assert.equal(symbols.choose(S,'factory','factory').ok,true);
assert.equal(symbols.selected(S,'factory'),'factory','a selected physical icon replaces the numbered pin');
assert.equal(symbols.choose(S,'factory','invented').ok,false);
assert.equal(symbols.choose(S,'factory','number').ok,true);
assert.equal(symbols.selected(S,'factory'),'number','numbered marker can be restored');
assert.equal(Object.keys(symbols.ICONS).length>=8,true);
const app=fs.readFileSync(path.join(__dirname,'../app.js'),'utf8');
const html=fs.readFileSync(path.join(__dirname,'../index.html'),'utf8');
const css=fs.readFileSync(path.join(__dirname,'../styles.css'),'utf8');
assert.match(app,/FE_RAIL_EDITOR\?\.sync/);
assert.match(app,/FE_LOCATION_ICONS\?\.decorate/);
assert.match(app,/FE_RAIL_EDITOR_SETUP=/);
assert.match(html,/titleMapRailCanvas/);
assert.match(html,/titleMapRailFrom/);
assert.match(html,/titleMapPhysicalIcon/);
assert.match(css,/title-map-marker\[data-physical-icon\]/);
for(const file of ['railway-network.js','railway-editor.js','location-icons.js'])
 assert.ok(html.includes(file+'?v='),file+' must load in the game');
assert.ok(html.includes('assets/artwork/maps/title-map-1938.jpg'),'the approved fixed map artwork is retained');
console.log('PASS saved rail painting, real connected station routing, timed train movement, erase, and physical pin replacements');
