'use strict';
/* Federal Electric source-only regression tests, no Electron/downloads needed. */
const fs=require('fs');
const path=require('path');
const vm=require('vm');
const assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const read=rel=>fs.readFileSync(path.join(root,rel),'utf8');
const pkg=JSON.parse(read('package.json'));
const citySource=read('city.js'),appSource=read('app.js');
const housingSource=read('housing.js'),effectsSource=read('personal-effects.js'),venuesSource=read('venue-opportunities.js');
const dollSource=read('paper-doll.js'),index=read('index.html');
let checks=0;
function check(condition,message){assert.ok(condition,message);checks++;}
for(const rel of ['city.js','app.js','housing.js','personal-effects.js','venue-opportunities.js','paper-doll.js','desktop/main.cjs']){
 new vm.Script(read(rel),{filename:rel});
 checks++;
}
check(pkg.version==='0.6.12','Current package version is v0.6.12');
check(appSource.includes("APP_VERSION='v0.6.12-dev'"),'Game masthead uses v0.6.12');
check(read('build-linux.sh').includes('0.6.12'),'Local packaging uses the same number');
const workflow=read('.github/workflows/linux-build.yml');
check(workflow.includes('workflow_dispatch:')&&!/^\s*push:/m.test(workflow),'No packaging on push');
check(workflow.includes('npm run test:source'),'Future manual workflow runs this test');
check(workflow.includes('0.6.12-linux-x64.tar.gz'),'Manual workflow archives v0.6.12');
const image='assets/artwork/characters/paperdolls/paperdoll.png';
check(fs.statSync(path.join(root,image)).size>0,'Approved original paper doll is tracked');
check(dollSource.includes(image),'Paper doll uses uploaded approved artwork');
check(index.indexOf('app.js?v=')<index.indexOf('personal-effects.js?v='),'Personal effects load after app state');
check(index.indexOf('personal-effects.js?v=')<index.indexOf('housing.js?v='),'Housing follows game state');
check(index.indexOf('housing.js?v=')<index.indexOf('paper-doll.js?v='),'Pocket UI loads after container API');
const oldLoose=fs.readdirSync(path.join(root,'assets')).filter(n=>/\.(png|webp|gif|svg|jpg|jpeg)$/i.test(n));
check(oldLoose.length===0,'No loose image assets at root');
const cityCtx={window:{}};
vm.runInNewContext(citySource,cityCtx,{filename:'city.js'});
const city=cityCtx.window.FederalElectricCity;
const pins=city.mapLocations();
const ids=pins.map(p=>p.id),nums=pins.map(p=>p.n);
check(pins.length===12,'Twelve distinct Washington map pins');
check(new Set(ids).size===12,'No duplicate map location identifiers');
check(new Set(nums).size===12&&Math.max(...nums)===12,'Map marker numbers 1-12');
check(city.getLocation('home').map.n===12,'Home is marker 12');
check(city.getLocation('home').rooms.length===4,'Home has four internal rooms');
check(city.getRoom('home','bedroom').id==='bedroom','Home bedroom address is stable');
check(city.getRoom('home','storage').id==='storage','Home storage address is stable');
const before=city.getLocation('star').name;
city.getLocation('star').name='changed outside registry';
check(city.getLocation('star').name===before,'City data returns defensive copies');
const game={housing:{version:1,primaryResidenceId:'capitol-hill-rowhouse',tenure:'undetermined',properties:[],staff:[],improvements:[]},
 personalEffects:{version:1,items:[]}};
let current={locationId:'home',roomId:'storage'},profile='test-profile';
const elements={};
for(const id of ['cityRoomHouseholdRecord','cityRoomHousingName','cityRoomHousingTenure','cityRoomHousingFeatures','cityRoomPersonalStorage','cityRoomPersonalStorageContents'])
 elements[id]={hidden:true,textContent:'',children:[],replaceChildren(){this.children=[];this.textContent=''},appendChild(v){this.children.push(v)}};
const doc={getElementById:id=>elements[id]||null,createElement:tag=>({tagName:tag,textContent:'',children:[],appendChild(v){this.children.push(v)}})};
const ctx={window:{},document:doc,S:game,activeProfileId:()=>profile,currentCityLocation:()=>current};
vm.runInNewContext(effectsSource,ctx,{filename:'personal-effects.js'});
vm.runInNewContext(housingSource,ctx,{filename:'housing.js'});
const effects=ctx.window.FE_PERSONAL_EFFECTS,housing=ctx.window.FE_HOUSING;
check(effects.list('left-pocket').length===0&&effects.list('right-pocket').length===0,'New pockets start empty');
check(effects.isAccessible('home-storage'),'Home storage accessible from storage room');
game.personalEffects.items=[{id:'a',name:'Test Letter',kind:'letter',container:'home-storage'}];
check(effects.list('home-storage')[0].name==='Test Letter','Stored item appears locally');
current={locationId:'home',roomId:'bedroom'};
check(!effects.isAccessible('home-storage')&&effects.list('home-storage').length===0,'No remote household inventory');
check(game.personalEffects.items[0].container==='home-storage','Leaving storage does not teleport items');
check(effects.isAccessible('left-pocket')&&effects.isAccessible('right-pocket'),'Pockets are carried into other rooms');
check(!effects.isAccessible('office-storage'),'Office storage unavailable from home');
current={locationId:'factory',roomId:'executive-office'};
check(effects.isAccessible('office-storage')&&!effects.isAccessible('home-storage'),'Office and home storage stay separate');
current={locationId:'home',roomId:'storage'};
effects.renderRoomStorage('home','storage');
check(!elements.cityRoomPersonalStorage.hidden,'Storage room shows its panel');
effects.renderRoomStorage('home','bedroom');
check(elements.cityRoomPersonalStorage.hidden,'Other home rooms hide storage panel');
check(housing.listTiers().length===4,'Four planned housing tiers');
check(housing.listTiers().every(t=>t.purchasePrice===null&&t.upkeep===null),'No invented real estate prices');
check(housing.currentHousehold().tenure==='undetermined','No unsupported home ownership claim');
housing.renderHouseholdRecord('home','front-room');
check(!elements.cityRoomHouseholdRecord.hidden&&elements.cityRoomHousingName.textContent==='Capitol Hill Rowhouse','Home front room shows property register');
housing.renderHouseholdRecord('home','bedroom');
check(elements.cityRoomHouseholdRecord.hidden,'Bedroom hides property register');
check(appSource.includes('fresh.personalEffects={version:1,items:[]}')&&appSource.includes('fresh.housing={'),'Save migrations preserve personal systems');
check(appSource.includes('function initMapShortcut()')&&appSource.includes('function closeTitleMapOrReturnToLocation()'),'M key map and return flow installed');
const vc={window:{FederalElectricCity:city},S:{gameDate:'1890-01-02',underworld:{privateFightsUnlocked:false,cockfightsUnlocked:false}},activeProfileId:()=>profile,currentCityLocation:()=>current,document:doc};
vm.runInNewContext(venuesSource,vc,{filename:'venue-opportunities.js'});
current={locationId:'races',roomId:'grounds'};
check(vc.window.FE_VENUES.canUse('horse-racing'),'Must attend racetrack to enter races');
current={locationId:'home',roomId:'bedroom'};
check(!vc.window.FE_VENUES.canUse('horse-racing'),'No remote horse racing');
check(!vc.window.FE_VENUES.canEnterLocation('licensedGamingHall'),'Unapproved casino locked');
check(!vc.window.FE_VENUES.canEnterLocation('cockfightingDen'),'Undiscovered illegal site locked');
check(!vc.window.FE_VENUES.canEnterLocation('capitalSpeedway'),'Motor track closed in 1890');
console.log('SOURCE_CONTRACTS_OK: '+checks+' checks');
