'use strict';
const assert=require('node:assert/strict');
const shop=require('../crowe-butchery.js');
const story=require('../main-story.js');
const minute=Math.floor(Date.parse('1878-01-02T08:00:00Z')/60000);
const fresh=()=>({characterRoute:'criminal',phase:'day',paused:false,gameDate:'1878-01-02',
 personalCash:10,companyCash:9000,worldCalendar:{worldMinute:minute},
 currentLocation:{locationId:'croweButcherShop',roomId:'shop-floor'}});
const save=fresh();
const state=shop.ensure(save);
assert.equal(state.tillCents,2400);
assert.equal(shop.ensure(save),state);
assert.deepEqual(Object.keys(shop.GOODS),['beef','pork','mutton']);
assert.equal(shop.quote({...save,characterRoute:'industrialist'},'cut',{key:'beef'}).ok,false);
assert.equal(shop.quote({...save,currentLocation:{locationId:'factory',roomId:'production-floor'}},'cut',{key:'beef'}).ok,false);
assert.equal(shop.apply(save,'cut',{key:'beef'},0).ok,false,'No free prep');
const rawBefore=state.raw.beef,readyBefore=state.prepared.beef;
assert.equal(shop.apply(save,'cut',{key:'beef'},900).ok,true);
assert.equal(state.raw.beef,rawBefore-3);
assert.equal(state.prepared.beef,readyBefore+3);
assert.equal(shop.apply(save,'counter',{key:'beef'},900).ok,true);
assert.equal(shop.summary(save).sales,1);
assert.equal(story.inspect(save).acts[0].status,'milestone-recorded','Real preparation and sale unlock chapter I');
assert.equal(story.inspect(save).acts[1].status,'available');
const shopCash=state.tillCents,personal=save.personalCash,company=save.companyCash;
assert.equal(shop.apply(save,'draw',{cents:100},120).ok,true);
assert.equal(state.tillCents,shopCash-100);
assert.equal(save.personalCash,personal+1);
assert.equal(state.bookTillCents,state.tillCents,'Recorded owner draw reconciles');
assert.equal(save.companyCash,company,'Federal Electric never pays the butcher');
assert.equal(shop.apply(save,'unrecordedDraw',{cents:75},0).ok,false);
assert.equal(shop.apply(save,'unrecordedDraw',{cents:75},120).ok,true);
assert.equal(shop.apply(save,'audit',{},600).audit.differenceCents,-75);
assert.equal(story.inspect(save).acts[1].status,'milestone-recorded','Till audit unlocks chapter II');
assert.equal(story.inspect(save).acts[2].status,'planned','Future secret investigation not fabricated');
assert.equal(shop.quote({...save,currentLocation:{locationId:'croweButcherShop',roomId:'loft'}},'restock',{key:'beef'}).ok,false,'Cousin loft is not a shop counter');
assert.equal(shop.quote({...save,phase:'night'},'counter',{key:'beef'}).ok,false,'Meat counter closes overnight');
assert.equal(shop.apply(save,'price',{key:'pork',cents:2},120).ok,false,'Pricing below cost refused');
assert.equal(shop.apply(save,'price',{key:'pork',cents:35},120).ok,true);
assert.equal(shop.summary(save).prices.pork,35);
const beforeResentment=shop.summary(save).cousin.resentment;
assert.equal(shop.apply(save,'confront',{},300).ok,true);
assert(shop.summary(save).cousin.resentment>beforeResentment,'Confronting the cousin affects their relationship');
assert.equal(shop.apply(save,'listen',{},300).ok,true);
assert(shop.summary(save).cousin.resentment<beforeResentment+8,'Listening reduces resentment');
assert.equal(shop.apply(save,'restock',{key:'mutton'},600).ok,true);
const priorSales=state.sales;
save.currentLocation={locationId:'hillsdale',roomId:'neighborhood-street'};
save.worldCalendar.worldMinute+=4*1440;
shop.sync(save);
assert(state.sales>priorSales,'Competent assistant continues serving customers during owner absence');
const afterTick=state.sales,afterTill=state.tillCents;
shop.sync(save);
assert.equal(state.sales,afterTick,'Same-world-minute catchup must not duplicate sales');
assert.equal(state.tillCents,afterTill);
const snap=JSON.parse(JSON.stringify(save));
assert.equal(shop.summary(snap).tillCents,shop.summary(save).tillCents,'Current-build saves preserve business finances');
assert.equal(shop.ensure(fresh()).sales,0,'New profile does not inherit another profile’s sales');
assert.doesNotMatch(JSON.stringify(shop.summary(save)),/smother|lover|murder|disposed.*will/i,'Player-facing shop state never leaks hidden culprit');
console.log('PASS Elias inherited shop, separate cash, cutting, stocking, customer trade, cousin offsite work, recorded/unrecorded draws, no spoilers');
