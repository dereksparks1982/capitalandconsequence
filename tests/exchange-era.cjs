'use strict';
/* 1878 founding-era quotation regression, executed from the actual app source without Electron. */
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const source=fs.readFileSync(path.join(__dirname,'..','app.js'),'utf8');
const cut=source.indexOf('const initial=()=>');
const indexDefinition=source.match(/^function marketIndex\(\).*$/m);
assert.ok(cut>0&&indexDefinition,'Found era and market index functions in the live game');
const context=vm.createContext({window:{}});
vm.runInContext(source.slice(0,cut)+'\n'+indexDefinition[0]+
 '\nlet S={gameDate:"1878-01-02",stocks:{}};globalThis.marketTests={makeStocks,makePortfolio,stockAvailableInYear,stockUniverse,marketIndex,set(stocks,date){S={stocks,gameDate:date}}};',context);
const {makeStocks,makePortfolio,stockAvailableInYear,marketIndex,set}=context.marketTests;
const founding=makeStocks('1878-01-02',1878);
const eligible=Object.entries(founding).filter(([ticker,x])=>stockAvailableInYear(ticker,x.sector,1878));
assert.equal(eligible.length,8,'Eight fictional founding-era listings are available in 1878');
assert.ok(eligible.some(([ticker])=>ticker==='DTC'),'1878 telegraph security can be traded');
assert.ok(eligible.every(([,x])=>!['Automotive','Aviation'].includes(x.sector)),'No cars or aircraft on the 1878 quotation sheet');
assert.equal(founding.AMW.history.length,0,'Not-yet-listed motor works has no 1877 quotation history');
assert.equal(founding.NAC.history.length,0,'Not-yet-listed aviation firm has no fake 1877 prices');
assert.ok(founding.PWR.history.length>0,'Founding-era railway has legitimate fictional preopening quotations');
assert.equal(stockAvailableInYear('AMW','Automotive',1878),false);
assert.equal(stockAvailableInYear('NAC','Aviation',1890),false);
assert.equal(stockAvailableInYear('HHA','Consumer',1899),false);
assert.equal(stockAvailableInYear('NRT','Communications',1919),false);
assert.equal(stockAvailableInYear('NRT','Communications',1920),true);
assert.equal(stockAvailableInYear('DTC','Communications',1878),true);
assert.deepEqual(Object.keys(makePortfolio(1878)).sort(),Object.keys(founding).sort(),'1878 portfolio covers every seeded security');
set(founding,'1878-01-02');
assert.ok(Math.abs(marketIndex()-100)<1e-8,'1878 index starts from listed securities only');
founding.AMW.price=100000;
assert.ok(Math.abs(marketIndex()-100)<1e-8,'Future industrial quote cannot distort the 1878 index');
founding.PWR.price=+(founding.PWR.price*1.2).toFixed(2);
assert.ok(marketIndex()>100,'Changing a listed railway affects the index');
const legacy=makeStocks('1890-01-02',1890);
assert.equal(Object.hasOwn(legacy,'PWR'),false,'Older 1890 campaign does not acquire an invented 1878 listing');
assert.equal(Object.hasOwn(legacy,'AMW'),true,'1890 campaign retains its legacy stock symbols');
assert.equal(Object.hasOwn(makePortfolio(1890),'DTC'),false,'Legacy saved portfolio stays in the 1890 universe');
assert.ok(legacy.CTC.history.length>0,'1890 telegraph quotes retain their period history');
assert.ok(!legacy.NAC.history.length,'Aircraft firm cannot have 1889 prelisting quotations');
set(legacy,'1890-01-02');
assert.ok(marketIndex()>0,'Legacy market index remains finite');
assert.ok(source.includes('fresh.stocks=makeStocks(')&&source.includes('fresh.portfolio=makePortfolio(fresh.campaignStartYear)'),'Migration uses the saved campaign starting year');
assert.ok(source.includes('stockAvailableInYear(k,x.sector,+S.gameDate.slice(0,4))'),'Live buy/sell gate continues to check the year');
console.log('PASS 1878 fictional securities, genuine-era UI/index, no premature quotes, legacy 1890 portfolio compatibility');
