'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const ship=require('../merchant-shipboard.js'),sea=require('../merchant-passenger-sea.js');
const journal=require('../merchant-shipboard-journal.js'),domino=require('../merchant-shipboard-dominoes.js');
const now=Math.floor(Date.parse('1878-03-10T09:00:00Z')/60000);
const s={characterRoute:'industrialist',paused:false,phase:'day',gameDate:'1878-03-10',
 personalCash:800,companyCash:3200,currentLocation:{locationId:'potomacFishingBank',roomId:'passenger-pier'},
 worldCalendarStatus:'ready',worldCalendar:{worldMinute:now}};
const ticket=sea.embark(s,'Liverpool','schooner');assert(ticket.ok,ticket.reason);
const p=ship.ensure(s),cash=s.personalCash,company=s.companyCash,minute=s.worldCalendar.worldMinute;
p.deck='lower';p.x=3;p.y=4;
assert(!journal.quote(s,'A note').ok,'must be at passenger berth');
p.x=3;p.y=3;assert(ship.at(s,'rest'));
assert(!journal.quote(s,'     ').ok,'reject empty page');
assert(!journal.quote(s,'x'.repeat(801)).ok,'hard character limit');
assert(journal.quote(s,'  Dear diary, \nStill at sea.  ').ok);
assert(journal.write(s,'  Dear diary, \nStill at sea.  ').ok);
assert.equal(journal.pages(s).length,1);
assert.equal(journal.pages(s)[0].body,'Dear diary, \nStill at sea.');
assert.equal(journal.pages(s)[0].voyageId,s.passengerSea.voyage.id);
assert.equal(journal.pages(s)[0].minute,minute,'stamped from saved world clock');
assert.equal(s.companyCash,company,'not a corporate expense');
assert.equal(s.personalCash,cash,'no personal expenses');
assert.equal(s.worldCalendar.worldMinute,minute,'the journal does not run an extra clock');
const restored=JSON.parse(JSON.stringify(s));
assert.deepEqual(journal.pages(restored),journal.pages(s),'save/reload preserves entry');
restored.passengerSea.voyage=null;restored.passengerSea.port='Liverpool';
restored.currentLocation={locationId:'foreignHarbor',roomId:'quay'};
assert.equal(journal.pages(restored).length,1,'journal remains readable after docking');
assert(!journal.quote(restored,'Another note').ok,'no writing while ashore');
restored.passengerSea.journal.pages[0].body='Different saved copy';
assert.equal(journal.pages(s)[0].body,'Dear diary, \nStill at sea.','read returns independent copy');
p.deck='lower';p.x=3;p.y=4;assert(ship.at(s,'cards'));
assert(domino.act(s,'start').ok);
assert(!ship.cardOffer(s,'start').ok,'twenty-one blocked during dominoes');
assert(!journal.quote(s,'Away from berth').ok,'must remain at berth to write');
assert(!journal.write(s,'Away from berth').ok);
assert(domino.resign(s).ok);
// A page legitimately started with 15 minutes before docking must still
// commit after its 10 minute action, even though only five minutes remain.
p.deck='lower';p.x=3;p.y=3;
const arrival=s.passengerSea.voyage.arrivalMinute;
s.passengerSea.voyage.arrivalMinute=s.worldCalendar.worldMinute+15;
assert(journal.quote(s,'Docking soon.').ok);
s.worldCalendar.worldMinute+=10;
assert(journal.write(s,'Docking soon.').ok,'do not charge a second future 10-minute window');
assert.equal(journal.pages(s).length,2);
s.passengerSea.voyage.arrivalMinute=arrival;
const base=path.join(__dirname,'..'),read=p=>fs.readFileSync(path.join(base,p),'utf8');
const ui=read('merchant-passenger-ui.js'),app=read('app.js'),html=read('index.html');
assert(ui.includes('function journalBook(writable)')&&ui.includes('shipJournalDraft'));
assert(ui.includes("document.activeElement?.id==='shipJournalDraft'"));
assert(app.includes('shipJournalWrite:(text)=>')&&app.includes("advanceWorldSimulation(offer.seconds,true,'passenger-shipboard')"));
assert(html.indexOf('merchant-shipboard-journal.js')<html.indexOf('merchant-passenger-ui.js'));
assert(read('merchant-shipboard-checkers.js').includes("game?.round?.status==='playing'"));
assert(read('merchant-shipboard.js').includes("FE_SHIP_CHECKERS?.ensure?.(s)?.active"));
console.log('shipboard journal PASS: physical berth, validation, persistence ashore, clock/cash integrity, app/UI wiring');