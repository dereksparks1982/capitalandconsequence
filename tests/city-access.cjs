'use strict';
const assert=require('node:assert/strict'),fs=require('fs'),vm=require('vm'),path=require('path');
const cityCtx={window:{}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../city.js'),'utf8'),cityCtx);
const city=cityCtx.window.FederalElectricCity,access=require('../city-access.js'),mobility=require('../npc-mobility.js');
const day='1890-01-03',employee={kind:'npc',id:'foremanSullivan',workplaceId:'factory',onDuty:true};
assert.equal(city.listLocations().length,26);
assert.equal(city.mapLocations().length,26);
assert.equal(access.canRoom(city,{route:'industrialist'},'factory','executive-office',day).ok,true);
assert.equal(access.canRoom(city,{route:'industrialist'},'factory','production-floor',day).ok,true);
assert.equal(access.canRoom(city,{route:'investigator'},'factory','executive-office',day).ok,false);
assert.equal(access.canRoom(city,{route:'wardman'},'blackwoodAsylum','patient-ward',day).ok,true);
assert.equal(access.canRoom(city,{route:'wardman'},'blackwoodAsylum','superintendent-office',day).ok,false);
assert.equal(access.canRoom(city,{kind:'npc',id:'visitor'},'blackwoodAsylum','patient-ward',day).ok,false);
assert.equal(access.canRoom(city,employee,'factory','production-floor',day).ok,true);
assert.equal(access.canRoom(city,{kind:'npc',id:'visitor'},'home','front-room',day).ok,false);
assert.equal(access.canLocation(city,{kind:'npc',id:'visitor'},'capitalSpeedway','1878-01-02').ok,false);
assert.equal(access.canLocation(city,{kind:'npc',id:'visitor'},'licensedGamingHall',day).ok,false);
assert.equal(access.canLocation(city,{kind:'npc',id:'visitor'},'privateFightHall',day).ok,false);
assert.equal(access.canLocation(city,{kind:'npc',id:'visitor',invitations:['privateFightHall']},'privateFightHall',day).ok,true);
assert.equal(access.rooms(city,{route:'investigator'},'factory',day).includes('executive-office'),false);
const c={date:day,key:day+'|0',seed:1820,slot:0,defaultLocation:'factory',defaultActivity:'running the factory'};
const result=mobility.visit(city,employee,c);
assert.equal(result.locationId,'factory');
assert.equal(result.roomId,'production-floor');
assert.deepEqual(mobility.visit(city,employee,c),result);
const outsider=mobility.visit(city,{kind:'npc',id:'visitor'},c);
assert.notEqual(outsider.roomId,'executive-office');
for(const loc of city.listLocations())assert.ok(loc.rooms.length,'Addressable room required: '+loc.id);
console.log('PASS city access, 26 locations, staff workrooms and deterministic NPC presence');
