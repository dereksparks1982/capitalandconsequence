'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const med=require('../medical-records.js'),needs=require('../character-needs.js');
const start=Math.floor(Date.parse('1878-01-02T08:00:00Z')/60000);
function game(route='industrialist'){
 return {worldCalendarStatus:'ready',worldCalendar:{worldMinute:start},characterRoute:route,
  personalCash:100,companyCash:200,lastExpenses:0,
  componentWorks:{cashCents:20000},currentLocation:{locationId:'home',roomId:'bedroom'}};
}
function exhaust(s){needs.ensure(s).meters.energy=0}
const home=game();
exhaust(home);
const faint=med.collapse(home,'home');
assert.equal(faint.ok,true);
assert.equal(faint.event.setting,'home');
assert.equal(faint.event.feeCents,0);
assert.equal(faint.event.minutesLost,90);
assert.equal(home.personalCash,100);
assert.equal(med.collapse(home,'home').ok,false,'cannot collapse twice while unconscious');
assert.equal(med.wake(home,90*60).energy,12);
assert.equal(med.pending(home),null);
assert.equal(home.currentLocation.locationId,'home');
assert.equal(med.viewOwn(home).collapses,1);
assert.equal(med.viewOwn(home).severity,'normal');
home.worldCalendar.worldMinute+=1440;
exhaust(home);assert.equal(med.collapse(home,'home').ok,true);
assert.equal(med.viewOwn(home).collapses,2);
assert.equal(med.viewOwn(home).severity,'chronic');
med.wake(home,90*60);
assert.equal(med.energyCap(home),80);
needs.overnight(home);assert.equal(home.characterNeeds.meters.energy,80);
needs.overnight(home);assert.equal(home.characterNeeds.meters.energy,90,'recovery nights restore ordinary energy');
assert.equal(med.viewOwn(home).severity,'normal');
home.worldCalendar.worldMinute+=1440;
exhaust(home);assert.equal(med.collapse(home,'home').ok,true);
assert.equal(med.viewOwn(home).severity,'severe','three collapses within 14 days matter');
const factory=game();factory.currentLocation={locationId:'factory',roomId:'executive-office'};exhaust(factory);
const works=med.collapse(factory,'factory');
assert.equal(works.ok,true);
assert.equal(works.event.setting,'work');
assert.equal(works.event.doctorFeeCents,400);
assert.equal(factory.companyCash,196);
assert.equal(factory.componentWorks.cashCents,19600);
assert.equal(factory.lastExpenses,4);
assert.equal(factory.personalCash,100);
assert.equal(factory.medicalRecords.factory.incidents,1);
assert.equal(factory.medicalRecords.factory.doctorFeesCents,400);
med.wake(factory,120*60);
assert.equal(factory.medicalRecords.factory.minutesLost,0,'medical module must not manufacture factory downtime');
const street=game('investigator');street.currentLocation={locationId:'easternMarket',roomId:'market-hall'};exhaust(street);
const hospital=med.collapse(street,'easternMarket');
assert.equal(hospital.event.setting,'street');
assert.equal(street.personalCash,88);
assert.equal(street.companyCash,200);
med.wake(street,180*60);
assert.equal(street.currentLocation.locationId,'governmentHospital');
assert.equal(street.currentLocation.roomId,'reception');
const danger=game('criminal');exhaust(danger);
const priorCash=danger.personalCash;
const risky=med.collapse(danger,'hillsdale');
assert.equal(risky.event.setting,'danger');
assert.ok(danger.personalCash<=priorCash-12,'street hospital charge always applies');
assert.ok(risky.event.stolenCents>=0);
const ward=game('wardman');exhaust(ward);
assert.equal(med.collapse(ward,'blackwoodAsylum').event.setting,'work');
assert.equal(ward.companyCash,200,'unrelated employer does not take company money');
assert.equal(ward.personalCash,96);
const doctor=med.ensurePatient(home,'npc:foremanSullivan','Sullivan','npc');
assert.equal(doctor.history.length,0,'no fabricated diagnoses');
med.record(home,'npc:foremanSullivan',{kind:'exam',description:'Examined after shift'});
assert.equal(doctor.history.length,1);
assert.equal(med.viewOwn(home).history.some(e=>e.description==='Examined after shift'),false,
 'private NPC ledger never contaminates the player medical file');
const app=fs.readFileSync(path.join(__dirname,'../app.js'),'utf8');
const html=fs.readFileSync(path.join(__dirname,'../index.html'),'utf8');
const banner=fs.readFileSync(path.join(__dirname,'../world-banner.js'),'utf8');
assert.ok(app.includes("kind!=='medical'&&window.FE_MEDICAL_RECORDS?.pending?.(S)"));
assert.ok(app.includes("let productive=factoryCollapse?0:delta"),'factory production must stop during emergency');
assert.ok(app.includes('S.medicalRecords.factory.minutesLost+=delta/60'),'measure actual open shift downtime');
assert.ok(app.includes('medical.wake(S,elapsed)'));
assert.ok(app.includes('window.FE_MEDICAL_UI?.render?.(S,recoverMedicalEpisode)'));
assert.ok(banner.includes('Open your personal medical file'));
assert.ok(html.includes('medical-records.js?v='));
assert.ok(html.includes('medical-records-ui.js?v='));
console.log('PASS: medical records, location-sensitive collapses, doctor/hospital cash, exhaustion memory, factory hold and medical file navigation');
