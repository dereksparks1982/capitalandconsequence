sharedApi.attach(sharedSave,snapshot);
check(sharedSave.chessCircuit.active.id==='charlie-table','Original character resumes their own in-progress match');
check(snapshot.lastChessResult==='Chess notice','Public chess bulletin follows the shared world');
console.log('TABLETOP_CHESS_OK: '+tests+' assertions');
