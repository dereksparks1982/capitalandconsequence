'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.join(__dirname,'..');
const api=require('../tabletop-chess.js');
const Chess=require('../vendor/chessjs/chess.js').Chess;
let tests=0;
function check(ok,message){assert.ok(ok,message);tests++}
const hall={locationId:'russianTradeHall',roomId:'meeting-hall',venueName:'Russian Trade Hall'};
const residents=[{id:'alexiRurik',name:'Alexi Rurik',roomId:'meeting-hall'},{id:'guestA',name:'Guest',roomId:'meeting-hall'}];
const player={playerId:'player:p1',playerName:'Charlie'};
const opponent={opponentId:'alexiRurik',opponentName:'Alexi Rurik'};
function fixture(){return {gameDate:'1878-01-02',worldCalendar:{version:1,worldMinute:1000},characterRoute:'industrialist'}}
check(typeof Chess==='function','Licensed chess.js constructor loads without Node package install');
check(new Chess().moves().length===20,'Starting chess board exposes twenty legal moves');
check(api.venue('hillsdale','neighborhood-street'),'Hillsdale has a chess table');
check(api.venue('universityMaryland','engineering-hall'),'University has a chess table');
check(api.venue('russianTradeHall','meeting-hall'),'Russian meeting hall has a chess table');
check(!api.venue('oldChinatown','market-street'),'Chinatown does not automatically get every game');
check(!api.venue('star','star-room'),'Star Club front salon is not the chess parlor');
check(!api.venue('metropolitanPolice','station-duty-room'),'Police workstation is not a parlor');
const s=fixture();
check(!api.start(s,{...hall,...player,...opponent,present:[]}).ok,'No challenge against absent resident');
const opened=api.start(s,{...hall,...player,...opponent,present:residents,at:'1878-01-02T12:00'});
check(opened.ok&&s.chessCircuit.active.opponentId==='alexiRurik','Present named NPC accepts a table challenge');
check(!api.start(s,{...hall,...player,...opponent,present:residents}).ok,'Cannot play simultaneous matches');
check(api.legal(s,'e2').includes('e4')&&!api.legal(s,'e2').includes('e5'),'Legal destinations obey real chess rules');
check(!api.play(s,'e2','e5',{...hall,present:residents}).ok,'Illegal move rejected');
check(s.chessCircuit.active.moves.length===0,'Illegal move does not mutate game');
const move=api.play(s,'e2','e4',{...hall,present:residents,at:'1878-01-02T12:01'});
check(move.ok&&move.player==='e4'&&!!move.opponent,'A legal player move elicits a chess.js validated NPC reply');
check(api.reconstruct(s.chessCircuit.active.moves).history().length===2,'Committed move pair restores from save');
check(s.chessCircuit.results.length===0,'An unfinished match is not called a win');
const surrendered=api.abandon(s,'1878-01-02T12:02');
check(surrendered.winnerId==='alexiRurik'&&surrendered.reason==='forfeit','Player resignation gives opponent the win');
check(api.abandon(s)===null,'A completed match cannot be settled twice');
check(s.chessCircuit.results.length===1&&s.chessCircuit.records['player:p1'].losses===1,'Single result updates permanent win/loss ledger');
check(!!api.start(s,{...hall,...player,...opponent,present:residents}).ok,'Can challenge again after one match ends');
const departed=api.departed(s);
check(departed.winnerId==='player:p1'&&departed.reason==='opponent-left','Opponent departure is not misreported as a player loss');
check(s.chessCircuit.records['player:p1'].wins===1,'Correct recipient receives a win for abandoned NPC match');
// Reconstruct a known Scholar's Mate; no invented outcomes.
const mating=fixture();
check(api.start(mating,{...hall,...player,...opponent,present:residents}).ok,'New matching profile independent');
mating.chessCircuit.active.moves=['e4','e5','Qh5','Nc6','Bc4','Nf6'];
check(api.reconstruct(mating.chessCircuit.active.moves).turn()==='w','Forced fixture has the correct side to move');
const mate=api.play(mating,'h5','f7',{...hall,present:residents,at:'1878-01-02T13:30'});
check(mate.ok&&mate.receipt?.winnerId==='player:p1'&&mate.receipt.reason==='completed','Checkmate derives from genuine legal board state');
check(mating.chessCircuit.active===null,'Checkmate closes match');
const offscreen=fixture();
const presentAt=where=>where==='russianTradeHall'?residents:[];
check(api.tick(offscreen,{now:{date:'1878-01-02',iso:'1878-01-02T08:00'},presentAt}).started===1,'Co-present residents schedule independent competition');
check(offscreen.chessCircuit.results.length===0,'Scheduling never invents a finished match');
check(api.tick(offscreen,{now:{date:'1878-01-02',iso:'1878-01-02T08:00'},presentAt}).started===0,'Same game minute never duplicates fixture');
offscreen.worldCalendar.worldMinute+=15;
check(api.tick(offscreen,{now:{date:'1878-01-02',iso:'1878-01-02T08:15'},presentAt}).settled===1,'Present NPCs finish match after fifteen saved minutes');
check(offscreen.chessCircuit.results[0].moves.length>0,'NPC result is based on actual engine-played chess moves');
const record=JSON.stringify(offscreen.chessCircuit);
check(api.tick(offscreen,{now:{date:'1878-01-02',iso:'1878-01-02T08:15'},presentAt}).settled===0,'Reloaded minute cannot replay outcome');
check(JSON.stringify(offscreen.chessCircuit)===record,'No additional ratings or results on same-minute replays');
const gone=fixture();
api.tick(gone,{now:{date:'1878-01-02',iso:'1878-01-02T08:00'},presentAt});
gone.worldCalendar.worldMinute+=15;
check(api.tick(gone,{now:{date:'1878-01-02',iso:'1878-01-02T08:15'},presentAt:()=>[residents[0]]}).settled===0,'Absent opponent invalidates NPC match');
check(gone.chessCircuit.results.length===0&&gone.chessCircuit.fixtures['1878-01-02:russianTradeHall:meeting-hall'].status==='cancelled','Cancellation is recorded without fictitious victor');
const base=fs.readFileSync(path.join(root,'index.html'),'utf8');
const art=fs.readFileSync(path.join(root,'tabletop-chess.css'),'utf8');
const app=fs.readFileSync(path.join(root,'app.js'),'utf8');
check(base.indexOf('vendor/chessjs/chess.js?')<base.indexOf('tabletop-chess.js?')&&base.indexOf('tabletop-chess.js?')<base.indexOf('app.js?'),'Chess rules load before game code and game save');
check(base.indexOf('tabletop-chess-ui.js?')>base.indexOf('npc-ai.js?'),'Chess parlor renders after NPC attendance service');
check(base.includes('tabletop-chess.css?')&&art.includes('.fe-chess-overhead')&&art.includes('.fe-chess-portrait'),'Overhead table has original CSS character portrait frames');
new vm.Script(fs.readFileSync(path.join(root,'tabletop-chess-ui.js'),'utf8'),{filename:'tabletop-chess-ui.js'});
check(app.includes("FE_CHESS?.tick?.(S,{now:")&&app.includes("FE_CHESS_UI?.refresh?.()"),'Autonomous matches and local-room UI wired into main simulation');
check(app.includes('S.lastChessResult].filter(Boolean)')&&app.includes('S.lastChessResult=null;'),'Real chess results feed newspaper and do not repeat forever');
check(fs.readFileSync(path.join(root,'vendor/chessjs/LICENSE'),'utf8').includes('Jeff Hlywa'),'Exact upstream BSD notice is retained');
const shared=fs.readFileSync(path.join(root,'shared-world.js'),'utf8');
check(shared.includes('chessCircuit:publicChess(save.chessCircuit||world.chessCircuit)')&&shared.includes('save.chessCircuit=publicChess(world.chessCircuit)'), 'Shared campaign transmits public results, not someone else\'s active match');
