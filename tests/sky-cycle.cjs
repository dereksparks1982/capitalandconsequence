'use strict';
const assert=require('node:assert/strict'),sky=require('../sky-cycle.js');
assert.equal(sky.weather('Rain throughout the afternoon').icon,'🌧');
assert.equal(sky.weather('Heavy snow').icon,'❄');
assert.equal(sky.weather('Partly cloudy').icon,'⛅');
assert.equal(sky.weather('Cold and clear').icon,'☀');
const morning=sky.snapshot('1878-01-02T08:00','Cold and clear'),night=sky.snapshot('1878-01-02T23:00','Cold and clear');
assert.equal(morning.sunlight,true,'8 AM winter Washington has risen sun');
assert.equal(night.sunlight,false,'11 PM Washington is night');
assert.equal(morning.date,'1878-01-02');
assert.ok(morning.sunrise<'08:00'&&morning.sunset>'15:30','Astronomy Engine provides a sane winter sunrise/set');
assert.equal(typeof night.moonPhase,'string');
assert.equal(sky.snapshot('1878-01-02T23:00','Cold and clear').moonPhase,night.moonPhase,'Moon phase is reproducible');
assert.throws(()=>sky.snapshot('1878-02-30T10:00','Clear'));
const eclipse=sky.snapshot('1878-07-29T17:42','Clear');
assert.equal(eclipse.eclipse,'Solar eclipse','Actual 1878 local solar eclipse is detected');
assert.equal(sky.snapshot('1878-07-28T17:42','Clear').eclipse,null,'No daily random eclipse invention');
assert.notEqual(sky.snapshot('1878-07-29T08:00','Clear').eclipse,'Solar eclipse','Eclipse only during exact event interval');
assert.equal(sky.snapshot('1878-07-29T17:42','Overcast').eclipse,'Solar eclipse','Actual celestial alignment exists despite clouds');
assert.deepEqual(JSON.parse(JSON.stringify(night)),night,'Astronomy summary is serializable');
console.log('PASS Washington winter sun, lunar phase, deterministic weather glyphs and 1878 local solar eclipse');
