'use strict';
const assert=require('node:assert/strict');
const clk=require('../world-clock.js'),bridge=require('../calendar-bridge.js');
globalThis.FE_WORLD_CLOCK=clk;
globalThis.FE_WASHINGTON_TIME=require('../washington-time.js');
globalThis.FE_SHARED_WORLD=require('../shared-world.js');
globalThis.FE_ASYLUM_INCIDENT=require('../asylum-incident.js');
globalThis.FE_MORGUE_REGISTRY=require('../morgue-registry.js');
globalThis.FE_MISSIONS=require('../mission-engine.js');
globalThis.FE_LIFE_HISTORY=require('../life-history.js');
const story=require('../asylum-story.js');
const create=(route,date)=>{const s={characterRoute:route,sharedWorldId:'w-story',phase:'day',gameDate:date,turnSerial:1,paused:false,npcSimulation:{},otherLives:{}};bridge.start(s,date,9*60);return s;};
const edmund=create('wardman','1878-01-05');
const world=FE_SHARED_WORLD.create('w-story',edmund);
assert.equal(story.advanceWorld(world).status,'reported');
assert.equal(story.advanceWorld(world).status,'reported','Do not create duplicate deaths');
assert.equal(world.events.filter(e=>e.type==='asylum-death').length,1);
const publicCase=story.visible(world);
assert.equal(publicCase.at,story.TIME);
assert.equal(publicCase.culpritRole,undefined);
const before=JSON.stringify(world);
const atWard={locationId:'blackwoodAsylum',roomId:'orderly-station'};
const preview=story.preview(edmund,world,'wardRecord',atWard);
assert.equal(preview.ok,true);
assert.equal(story.apply(edmund,world,'wardRecord',atWard,{spentSeconds:0}).ok,false);
assert.equal(JSON.stringify(world),before);
bridge.spend(edmund,300);
assert.equal(story.apply(edmund,world,'wardRecord',atWard,{spentSeconds:300}).ok,true);
assert.equal(story.seen(edmund,'wardRecord'),true);
assert.equal(story.apply(edmund,world,'wardRecord',atWard,{spentSeconds:300}).ok,false);
assert.equal(FE_MISSIONS.ensure(edmund).active['inquiry:'+story.CASE_ID+':wardman'].status,'active');
const sam=create('investigator','1878-01-05');sam.patrolDuty={reportsFiled:2,onDuty:false};
assert.equal(story.preview(sam,world,'stationMemo',{locationId:'metropolitanPolice',roomId:'station-duty-room'}).ok,true);
assert.equal(story.apply(sam,world,'stationMemo',{locationId:'metropolitanPolice',roomId:'station-duty-room'},{spentSeconds:600}).ok,true);
assert.equal(story.preview(sam,world,'medical',{locationId:'governmentHospital',roomId:'reception'}).ok,false);
const next=create('wardman','1878-01-05');bridge.start(next,'1878-01-05',14*60);
const later=FE_SHARED_WORLD.capture(next,world);
assert.equal(story.advanceWorld(later).status,'examined');
assert.equal(later.morgue.reports[story.BODY_ID].findings.length,3);
assert.equal(story.preview(sam,later,'medical',{locationId:'governmentHospital',roomId:'reception'}).ok,false,'No report from the future');
bridge.start(sam,'1878-01-05',14*60);
assert.equal(story.apply(sam,later,'medical',{locationId:'governmentHospital',roomId:'reception'},{spentSeconds:600}).ok,true);
assert.equal(sam.morgueExaminations.length,1);
assert.equal(edmund.morgueExaminations,undefined,'Private medical report must not leak to Edmund');
assert.equal(story.preview(edmund,later,'wardMemo',{locationId:'blackwoodAsylum',roomId:'orderly-station'}).ok,false,'One clue cannot file an institutional report');
bridge.start(edmund,'1878-01-05',14*60+10);
assert.equal(story.apply(edmund,later,'wardCorridor',{locationId:'blackwoodAsylum',roomId:'patient-ward'},{spentSeconds:300}).ok,true);
assert.equal(story.apply(edmund,later,'wardMemo',{locationId:'blackwoodAsylum',roomId:'orderly-station'},{spentSeconds:300}).ok,false);
assert.equal(story.apply(edmund,later,'passageMark',{locationId:'blackwoodAsylum',roomId:'patient-ward'},{spentSeconds:300}).ok,true);
assert.equal(story.apply(edmund,later,'visitorRegister',{locationId:'blackwoodAsylum',roomId:'reception'},{spentSeconds:300}).ok,true);
assert.equal(story.apply(edmund,later,'wardMemo',{locationId:'blackwoodAsylum',roomId:'orderly-station'},{spentSeconds:300}).ok,true);
assert.equal(FE_MISSIONS.ensure(edmund).history.length,1,'A filed memorandum concludes only the preliminary mission');
assert.equal(edmund.wardmanStanding.workplaceTrust,52);
assert.equal(story.preview(sam,later,'policeMemo',{locationId:'metropolitanPolice',roomId:'station-duty-room'}).ok,false,'Sam must collect real sources before filing');
assert.equal(story.apply(sam,later,'reception',{locationId:'blackwoodAsylum',roomId:'reception'},{spentSeconds:300}).ok,true);
assert.equal(story.apply(sam,later,'statementFolio',{locationId:'metropolitanPolice',roomId:'station-duty-room'},{spentSeconds:600}).ok,true);
assert.equal(story.apply(sam,later,'bellStatement',{locationId:'blackwoodAsylum',roomId:'reception'},{spentSeconds:300}).ok,true);
assert.equal(story.apply(sam,later,'policeMemo',{locationId:'metropolitanPolice',roomId:'station-duty-room'},{spentSeconds:600}).ok,true);
assert.equal(FE_MISSIONS.ensure(sam).history.length,1);

