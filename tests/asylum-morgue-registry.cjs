'use strict';
const assert=require('node:assert/strict');
const worldApi=require('../shared-world.js'),incident=require('../asylum-incident.js'),morgue=require('../morgue-registry.js');
const save={gameDate:'1878-02-01',phase:'day',turnSerial:1,worldCalendar:{version:1,worldMinute:1218,history:[],queue:[],nextSequence:1}};
const world=worldApi.create('wcase-1878',save);
let event=incident.start(world,{id:'asylum-0001',at:'1878-02-01T08:15',victimId:'patient-001'});
assert.equal(event.status,'created');assert.equal(world.events.length,1);
assert.equal(incident.start(world,{id:'asylum-0001',at:'1878-02-01T08:15',victimId:'patient-001'}).status,'existing');
assert.equal(incident.publicFile(world,'asylum-0001').culpritRole,undefined,'No murderer in public incident file');
let result=morgue.admit(world,{bodyId:'body-0001',incidentId:'asylum-0001',arrivedAt:'1878-02-01T10:00'});
assert.equal(result.ok,true);assert.equal(world.events.length,2);
assert.equal(morgue.admit(world,{bodyId:'body-0001',incidentId:'asylum-0001',arrivedAt:'1878-02-01T10:00'}).status,'existing');
result=morgue.examine(world,{bodyId:'body-0001',examinerId:'districtCoroner',examinedAt:'1878-02-01T11:00',findings:['wound']});
assert.equal(result.ok,false,'Medical findings cannot be invented before evidence exists');
assert.equal(morgue.requestReport(world,'body-0001',{route:'investigator'}).ok,false);
world.worldTruth['asylum-0001'].evidenceReady=true;
world.worldTruth['asylum-0001'].verifiedTimeline={medicalFindings:['wound']};
result=morgue.examine(world,{bodyId:'body-0001',examinerId:'districtCoroner',examinedAt:'1878-02-01T11:00',findings:['wound']});
assert.equal(result.status,'recorded');
assert.equal(morgue.requestReport(world,'body-0001',{route:'wardman',permission:{incidentId:'asylum-0001',access:'coroner-report'}}).ok,false);
assert.equal(morgue.requestReport(world,'body-0001',{route:'investigator',permission:{incidentId:'asylum-0001',access:'coroner-report'}}).ok,true);
const edmund={sharedWorldId:'wcase-1878',gameDate:'1878-02-01',characterRoute:'wardman'};
assert.equal(incident.observe(edmund,{incidentId:'asylum-0001',eventId:'seen-1',source:'ward rounds',description:'I discovered an unusual scene'}).status,'recorded');
assert.equal(edmund.incidentObservations.records.length,1);
console.log('PASS shared asylum incident, fixed hidden truth, morgue registration and authorized reports');
