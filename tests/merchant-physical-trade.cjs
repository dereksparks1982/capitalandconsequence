'use strict';
/* Genuine cargo purchasing, scarce port supplies, voyage custody and destination
 * settlement. Only world-clock days trigger arrival, and no projected sale is cash. */
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const empire=require('../industrial-empire.js');
const trade=require('../merchant-trade.js');
const nav=require('../merchant-navigation.js');
const root=path.join(__dirname,'..');
const read=n=>fs.readFileSync(path.join(root,n),'utf8');
const advance=(s,day)=>{s.gameDate=day;s.worldCalendar.worldMinute=Math.floor(Date.parse(day+'T12:00:00Z')/60000);return empire.advance(s)};
const s={gameDate:'1878-03-10',characterRoute:'industrialist',phase:'day',paused:false,
 personalCash:110000,companyCash:680,componentWorks:{warehouse:{'telegraph-key':9}},
 worldCalendarStatus:'ready',worldCalendar:{worldMinute:Math.floor(Date.parse('1878-03-10T09:00:00Z')/60000)}};
assert(empire.buyShip(s,'schooner').ok);
let f=empire.ensure(s).fleet,ship=f.ships[0];
assert.equal(f.cash,2500);
const before=JSON.stringify(s);
const order=trade.quote(s,ship,'Philadelphia','timber',8,true,f);
assert(order.ok,order.reason);
assert.equal(JSON.stringify(s),before,'a trade preview must never debit money or mutate stock');
assert.equal(order.units,8);assert(order.purchase>0);
assert(order.loading>0&&order.cargoInsurance>0&&order.insurance>0);
assert(order.expectedNet>0);assert(Number.isFinite(order.forecastProfit));
assert.equal(order.points.at(0)[0],nav.PORTS.Baltimore[0]);
assert(!trade.quote(s,ship,'Liverpool','timber',8,false,f).ok,'unverified destination');
assert(!trade.quote(s,ship,'Baltimore','timber',8,false,f).ok,'no same-port trading');
assert(!trade.quote(s,ship,'Philadelphia','coffee',8,false,f).ok,'origin is not coffee producer');
assert(!trade.quote(s,ship,'Philadelphia','timber',999,false,f).ok,'hold capacity');
assert(!trade.quote({...s,paused:true},ship,'Philadelphia','timber',8,false,f).ok,'paused');
assert(!trade.quote({...s,characterRoute:'patrolman'},ship,'Philadelphia','timber',8,false,f).ok,'wrong role');
const company=s.companyCash,component=JSON.stringify(s.componentWorks);
const departed=empire.dispatchTrade(s,ship.id,'Philadelphia','timber',8,true);
assert(departed.ok,departed.message);
assert.equal(f.cash,2500-order.due);
assert.equal(ship.status,'at-sea');
assert.equal(ship.trip.cargo,'trade');
assert.equal(ship.trip.tradeLot.units,8);
assert.equal(ship.trip.tradeLot.purchase,order.purchase);
assert.equal(trade.remaining(s,'Baltimore','timber'),trade.stockFor('Baltimore','timber')-8);
assert.equal(s.companyCash,company);
assert.equal(JSON.stringify(s.componentWorks),component,'merchant cargo cannot mint or withdraw FE goods');
assert(!empire.dispatchTrade(s,ship.id,'Philadelphia','timber',8,true).ok,'no second purchase on busy vessel');
const transit=JSON.stringify(f.tradeHold);
assert(!Array.isArray(f.tradeHold.Philadelphia)||!f.tradeHold.Philadelphia.length,'cargo not arrived at departure');
assert.equal(JSON.stringify(f.tradeHold),transit);
const eta=ship.trip.eta;advance(s,eta);
assert.equal(ship.status,'in-port');
assert.equal(ship.port,'Philadelphia');
assert.equal(f.tradeHold.Philadelphia.length,1,'one genuine batch landed');
const lot=f.tradeHold.Philadelphia[0];
assert.equal(lot.units,8);
assert.equal(lot.id,1);
assert.equal(lot.from,'Baltimore');
assert.equal(lot.to,'Philadelphia');
const held=JSON.stringify(f.tradeHold),cash=f.cash;
empire.advance(s);
assert.equal(JSON.stringify(f.tradeHold),held,'a day refresh cannot unload a second time');
assert.equal(f.cash,cash,'no phantom freight or automatic sale after landing');
const localSale=trade.saleQuote(s,'Philadelphia',lot);
assert(localSale.ok);
assert.equal(localSale.gross-localSale.agent-localSale.duty,localSale.net);
const paid=empire.sellTrade(s,'Philadelphia',lot.id);
assert(paid.ok,paid.message);
assert.equal(f.cash,Math.round((cash+localSale.net)*100)/100);
assert.equal(f.tradeHold.Philadelphia.length,0);
assert.equal(s.companyCash,company,'trade income belongs to fleet treasury');
assert(!empire.sellTrade(s,'Philadelphia',lot.id).ok,'no double sale');
assert(f.ledger.some(x=>x.label.includes('Merchant cargo sale')));
assert(f.ledger.some(x=>x.label.includes('Port agent commission')));
assert.equal(trade.ensure(s).purchases.length,1);
const saved=JSON.parse(JSON.stringify(s));
assert.equal(trade.remaining(saved,'Baltimore','timber'),trade.remaining(s,'Baltimore','timber'));
assert.equal(empire.ensure(saved).fleet.tradeHold.Philadelphia.length,0);
assert(!empire.sellTrade({...s,paused:true},'Philadelphia',lot.id).ok);
assert.equal(read('index.html').includes('merchant-trade.js'),true);
assert(read('index.html').indexOf('merchant-trade.js')<read('index.html').indexOf('industrial-empire.js'));
assert(read('merchant-world-map.js').includes('trade-preview:'));
assert(read('merchant-world-map.js').includes('trade-sell:'));
assert(read('industrial-empire.js').includes('dispatchTrade'));
assert(read('merchant-navigation.js').includes(nav.MAP)&&fs.existsSync(path.join(root,nav.MAP)),'Owner-selected chart remains bundled');
assert(read('index.html').includes('title-map-1938.jpg'));
console.log('merchant physical trade: immutable preview, finite weekly goods, paid ship, arrival inventory, insurance, tax, local sale, save isolation passed');
