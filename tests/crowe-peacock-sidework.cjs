'use strict';
const assert=require('node:assert/strict');
const work=require('../doorman-duty.js');
const save={characterRoute:'criminal',phase:'night',gameDate:'1878-02-05',paused:false,personalCash:3.00,
 currentLocation:{locationId:'secondNightclub',roomId:'main-room'}};
assert.equal(work.access(save,'secondNightclub','doorman-post').ok,false,'No automatic nightclub employment');
assert.equal(work.quoteOffer({...save,characterRoute:'industrialist'},'door').ok,false);
assert.equal(work.quoteOffer(save,'door').ok,true);
assert.equal(work.takeOffer(save,'door',0).ok,false,'Meeting consumes five game minutes');
assert.equal(work.takeOffer(save,'door',300).ok,true);
assert.equal(work.quoteOffer(save,'package').ok,false,'Only one assignment is offered per night');
save.currentLocation.roomId='doorman-post';
const first=work.begin(save,{locationId:work.VENUE,roomId:work.ROOM,date:save.gameDate,profileId:'eli',spentSeconds:600});
assert.equal(first.ok,true);
assert.equal(work.respond(save,{locationId:work.VENUE,roomId:work.ROOM,choiceId:first.encounter.choices[0].id,spentSeconds:300}).ok,true);
assert.equal(save.personalCash,3.30);
save.gameDate='1878-02-06';
assert.equal(work.access(save,'secondNightclub','doorman-post').ok,false,'Door work expires without fresh permission next night');
save.currentLocation.roomId='main-room';
assert.equal(work.takeOffer(save,'package',300).ok,true,'Lui issues an optional sealed-parcel errand');
assert.equal(work.takeOffer(save,'door',300).ok,false,'Cannot abandon undelivered parcel for other shift');
assert.equal(work.quoteDelivery(save,'croweButcherShop','shop-floor').ok,false);
save.currentLocation={locationId:'workingPoker',roomId:'card-room'};
assert.equal(work.deliver(save,'workingPoker','card-room',0).ok,false,'No instant free handoff');
const before=save.personalCash;
const paid=work.deliver(save,'workingPoker','card-room',300);
assert.equal(paid.ok,true);
assert.equal(save.personalCash,before+2.00);
assert.equal(work.deliver(save,'workingPoker','card-room',300).ok,false,'No duplicate delivery money');
assert.equal(work.sidework(save).status,'completed');
assert.equal(work.sidework(save).history[0].rewardCents,200);
assert.match(work.sidework(save).history[0].description,/contents remain unknown/);
assert.equal(work.quoteOffer(save,'door').ok,false,'Cannot roll another job on same night');
assert.equal(work.ensure({characterRoute:'criminal',phase:'night',gameDate:'1878-02-06'}).totalSegments,0,'Different profile has own nightwork state');
console.log('PASS Lui optional shifts, one assignment per night, real door wages, sealed parcel travel, exact payout, no criminal omniscience');
