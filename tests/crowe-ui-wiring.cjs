'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const read=f=>fs.readFileSync(path.join(__dirname,'..',f),'utf8');
const cityCtx={window:{}};vm.runInNewContext(read('city.js'),cityCtx);
const city=cityCtx.window.FederalElectricCity,access=require('../city-access.js'),shop=require('../crowe-butchery.js');
const routes=read('character-routes.js'),main=read('app.js'),ui=read('crowe-butchery-ui.js'),index=read('index.html');
const place=city.getLocation(shop.SHOP);
assert.equal(place.name,'Crowe Family Butchers');
assert.equal(place.defaultRoom,'shop-floor');
assert.equal(place.map,null,'Do not invent an unapproved new city pin');
assert.equal(city.mapLocations().length,42,'Existing city map pins are untouched');
for(const room of ['shop-floor','cutting-room','stock-room','back-door','loft'])assert(city.getRoom(shop.SHOP,room));
assert.equal(access.canRoom(city,{route:'criminal'},shop.SHOP,'loft','1878-01-02').ok,true);
assert.equal(access.canRoom(city,{route:'industrialist'},shop.SHOP,'loft','1878-01-02').ok,false,'Private cousin loft inaccessible to strangers');
assert.match(routes,/startingLocationId:'croweButcherShop',startingRoomId:'shop-floor'/);
assert.match(routes,/id:'criminal',name:'Butcher'/);
assert.match(main,/FE_CROWE_BUTCHERY\?\.sync\?\.\(S\)/);
assert.match(main,/FE_CROWE_BUTCHERY_UI\?\.refresh\?\.\(\)/);
assert.match(ui,/root\.advanceWorldTime\(q\.seconds,true\)/);
assert.match(ui,/shop\.apply\(S,action,options,elapsed\)/);
assert.match(ui,/Cousin’s Upstairs Loft|Your cousin lives here permanently/);
assert(index.indexOf('crowe-butchery.js?v=')<index.indexOf('app.js?v='),'Shop model must load before game loop');
assert(index.indexOf('app.js?v=')<index.indexOf('crowe-butchery-ui.js?v='),'Shop UI must load after game runtime');
assert(index.indexOf('crowe-butchery-ui.js?v=')<index.indexOf('doorman-ui.js?v='),'Both local career activity panels load');
assert(index.includes('doorman-duty.js?v=')&&index.includes('peacock-story.js?v='),'Optional night side stories remain present');
assert.doesNotMatch(ui,/smother|romantic relationship|lover|murdered his father/i,'Public UI must not disclose secret');
assert(city.getRoom(shop.SHOP,'ice-room')?.restricted,'Hanging side room has protected shop access');
assert.equal(access.canRoom(city,{route:'criminal'},shop.SHOP,'ice-room','1878-01-02').ok,true);
assert.equal(access.canRoom(city,{route:'industrialist'},shop.SHOP,'ice-room','1878-01-02').ok,false);
assert(index.indexOf('crowe-cold-room.js?v=')<index.indexOf('crowe-butchery.js?v='),'Cooling model loads before butcher model');
assert(ui.includes('Hanging Meat & Ice-Cooled Room'));
assert(ui.includes('early:true'),'Early cutting is explicitly labeled');
assert(ui.includes('iceDelivery')&&ui.includes('cleanRoom'));
const scene=read('crowe-shop-scene.js'),css=read('crowe-shop-scene.css');
assert(index.includes('crowe-shop-scene.css?v='),'Interactive shop floor CSS must load without changing city layout');
assert(index.indexOf('crowe-shop-scene.js?v=')<index.indexOf('crowe-butchery-ui.js?v='),'Scene must load before butcher UI');
assert(index.indexOf('app.js?v=')<index.indexOf('crowe-shop-scene.js?v='),'Shop scene must load after the city runtime');
assert(ui.includes('scene.render(sceneHost'),'Crowe location UI mounts interactive plan');
assert(ui.includes('FE_CITY?.openRoom?.(shop.SHOP,roomId)'),'Room inspection leads to genuine city navigation');
assert(scene.includes('floorPlan(svg,summary,currentRoom)')&&scene.includes('onAction?.('),'Scene uses inventory and dispatches work');
assert(css.includes('.crowe-scene-stage')&&css.includes('aspect-ratio:3/2'),'Plan has responsive styling');
assert.doesNotMatch(scene,/smother|murdered his father|adult relationship/i,'Public scene cannot reveal family plot');
console.log('PASS Crowe rooms, owner-only ice cellar, approved map pins, cold-room script order and hidden story');
