'use strict';
/* Independent room toolkit regression. No GitHub Actions or network. */
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.join(__dirname,'..'),browser={};
const scope={window:browser,globalThis:browser,module:{exports:{}},Date,Math};
for(const file of ['room-builder-catalog.js','room-builder-core.js','room-builder-kit.js'])
 vm.runInNewContext(fs.readFileSync(path.join(root,file),'utf8'),scope,{filename:file});
const C=browser.FE_ROOM_BUILDER_CORE,K=browser.FE_ROOM_BUILDER_KIT;
assert.equal(browser.FE_ROOM_CATALOG.length,69);
assert.ok(K,'editor kit must load after core/catalog');
const office=C.makeRoom('factory','executive-office');
const initial=JSON.stringify(office);
const area=K.apply(office,'rectangle','floors','floor_rug_red',2,2,4,5);
assert.equal(area.ok,true);assert.equal(area.changes,12);
assert.equal(office.floor[C.index(office,4,5)],'floor_rug_red');
assert.equal(K.pick(office,3,3).spriteId,'floor_rug_red');
assert.equal(K.pick(office,0,0).layer,'construction');
assert.equal(K.apply(office,'fill','floors','floor_stone',2,3).changes,12,
 'bucket must stop at the rectangular tile boundary');
assert.equal(office.floor[C.index(office,6,4)],'floor_planks');
const beforeFail=JSON.stringify(office);
const failure=K.apply(office,'rectangle','construction','wall_horizontal',1,1,10,9);
assert.equal(failure.ok,false,'cannot paint a solid wall on Charles spawn');
assert.equal(JSON.stringify(office),beforeFail,'atomic rectangle must leave no partial wall');
assert.equal(K.apply(office,'rectangle','construction','wall_horizontal',3,3,4,4).ok,true);
assert.equal(K.apply(office,'single','construction',null,3,3).ok,true);
assert.equal(office.walls[C.index(office,3,3)],null);
assert.equal(K.apply(office,'single','floors',null,3,3).ok,false);
assert.equal(K.apply(office,'fill','floors','wall_horizontal',3,3).ok,false);
assert.equal(K.apply(office,'rectangle','floors','floor_planks',-1,0,2,2).ok,false);
assert.equal(K.apply(office,'fill','floors','floor_planks',50,50).ok,false);
assert.equal(K.pick(office,100,100),null);
const desk=C.place(office,'desk_oak',6,5);assert.ok(desk);
assert.equal(K.pick(office,6,5).objectId,desk.id);
const descriptor=K.describe('desk_oak');
assert.equal(descriptor.kind,'workstation');assert.equal(descriptor.action,'use-executive-desk');
assert.equal(K.describe('door_closed').kind,'door');assert.equal(K.describe('floor_planks').category,'floors');
const furnished=C.sampleOffice();
const audit=K.auditStations(furnished);
assert.ok(audit.stations.length>=3,'an office has multiple defined work/storage/seating anchors');
assert.ok(audit.reachable>=1,'at least some stations can be approached');
const sealed=C.makeRoom();
const trappedDesk=C.place(sealed,'desk_oak',6,4);assert.ok(trappedDesk);
for(const tile of [[6,3],[7,3],[6,5],[7,5],[5,4],[8,4]])
 assert.equal(C.paint(sealed,tile[0],tile[1],'wall_horizontal'),true);
const inaccessible=K.auditStations(sealed);
assert.equal(inaccessible.stations.find(x=>x.objectId===trappedDesk.id).reachable,false,
 'cannot claim a workstation is usable if no adjacent access tile is reachable');
const storageMap=new Map();
const storage={getItem:k=>storageMap.get(k)||null,setItem:(k,v)=>storageMap.set(k,v)};
assert.equal(K.listDrafts(storage).length,0);
const saved=K.saveDraft(storage,office,'Office Test A');assert.equal(saved,'Office Test A');
assert.equal(K.listDrafts(storage).length,1);
const copy=K.openDraft(storage,'factory','executive-office','Office Test A');
assert.equal(copy.objects.length,1);
assert.notEqual(copy,office);
assert.equal(K.deleteDraft(storage,'factory','executive-office','Not Present'),false);
C.remove(office,desk.id);
assert.equal(K.openDraft(storage,'factory','executive-office','Office Test A').objects.length,1,
 'named draft is deep copied, editing current room cannot mutate saved revision');
assert.equal(K.saveDraft(storage,office,'Office Test A'),'Office Test A');
assert.equal(K.listDrafts(storage).length,1,'reusing name updates draft rather than duplicating it');
assert.equal(K.deleteDraft(storage,'factory','executive-office','Office Test A'),true);
assert.equal(K.listDrafts(storage).length,0);
assert.throws(()=>K.saveDraft(storage,office,'../../../bad'),'invalid names rejected');
assert.throws(()=>K.openDraft(storage,'factory','executive-office','missing'),'unknown draft refused');
const tampered=JSON.stringify([{name:'broken',layout:{...office,objects:[{id:'x',spriteId:'evil',x:2,y:2,rotation:0}]}}]);
storageMap.set(K.libraryKey,tampered);
assert.throws(()=>K.listDrafts(storage),'corrupt draft library refuses to load');
assert.equal(initial.includes('floor_rug_red'),false,'test started with original default office');
console.log('PASS room tile fill, rectangle, atomic collisions, sampled sprites, behavior descriptions and safe named drafts');
