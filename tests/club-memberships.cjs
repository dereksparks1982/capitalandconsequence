'use strict';
const assert=require('node:assert/strict');
const clubs=require('../club-memberships.js');
const profile={personalEffects:{version:1,items:[]}};
assert.equal(clubs.access(profile,'working','1878-01-02',false).status,'open');
assert.equal(clubs.access(profile,'middle','1878-01-02',false).status,'invitation-required');
assert.equal(clubs.access(profile,'elite','1878-01-02',true).status,'trial');
assert.equal(clubs.trial(profile,{tier:'elite',today:'1878-01-02',introduced:true,delta:0,stake:500,hands:0}).status,'trial-pending');
assert.equal(profile.personalEffects.items.length,0);
const granted=clubs.trial(profile,{tier:'elite',today:'1878-01-02',introduced:true,delta:30,stake:500,hands:4,conduct:'courteous'});
assert.equal(granted.status,'member');
assert.equal(granted.hospitality,0);
assert.equal(granted.item,'Embassy Club Membership Card');
assert.equal(clubs.access(profile,'elite','1878-01-04',false).status,'member');
assert.equal(profile.personalEffects.items[0].container,'left-pocket');
assert.equal(clubs.trial(profile,{tier:'elite',today:'1878-01-02',introduced:true,delta:-300,stake:500,hands:5}).status,'member');
assert.equal(profile.personalEffects.items.length,1,'membership cannot be issued twice');
const loser={personalEffects:{items:[]}};
const barred=clubs.trial(loser,{tier:'middle',today:'1878-01-02',introduced:true,delta:0,stake:100,hands:4,conduct:'rude'});
assert.equal(barred.status,'cooldown');
assert.equal(barred.until,'1878-01-09');
assert.equal(clubs.access(loser,'middle','1878-01-08',true).allowed,false);
assert.equal(clubs.access(loser,'middle','1878-01-09',true).allowed,true);
assert.equal(clubs.trial(loser,{tier:'middle',today:'1878-01-09',introduced:true,delta:150,stake:100,hands:4,conduct:'generous'}).status,'member');
assert.equal(loser.personalEffects.items[0].name,'Commerce Club Membership Card');
const poor={personalEffects:{items:[]}};
assert.equal(clubs.trial(poor,{tier:'middle',today:'1878-01-30',introduced:true,delta:90,stake:100,hands:4,conduct:'courteous'}).until,'1878-02-02');
assert.equal(clubs.access(poor,'middle','1878-02-01',true).allowed,false);
