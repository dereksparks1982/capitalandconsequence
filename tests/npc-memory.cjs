'use strict';
const assert=require('node:assert/strict'),memory=require('../npc-memory.js');
const save={};assert.equal(memory.ensure(save).version,1);
const say=(key,kind,text,verified=false)=>memory.remember(save,'madamStar',{date:'1878-01-02',key,kind,withId:'industrialist',place:'star',text,source:verified?'direct-encounter':'player-speech',verified});
assert.equal(say('first','conversation','The player claims to own a television'),true);
assert.equal(say('first','conversation','Duplicate'),false,'one event key is remembered only once');
assert.equal(say('second','greet','Spoke in the Star Club',true),true);
assert.equal(say('third','conversation','Discussed the weather'),true);
assert.equal(memory.reflect(save,'madamStar','1878-01-02','industrialist'),true);
assert.equal(memory.reflect(save,'madamStar','1878-01-02','industrialist'),false,'reflection is one per person per date');
assert.equal(memory.recall(save,'madamStar',{withId:'other'}).length,0,'do not expose another visitor\'s memories');
assert.equal(memory.entries(save,'madamStar')[0].verified,false,'player words are not verified world facts');
assert.ok(memory.entries(save,'madamStar').find(m=>m.kind==='reflection').verified===false);
assert.equal(memory.recall(save,'madamStar',{withId:'industrialist',limit:2}).length,2);
const copy=JSON.parse(JSON.stringify(save));assert.deepEqual(memory.recall(copy,'madamStar'),memory.recall(save,'madamStar'),'persistent per-profile state');
for(let i=0;i<120;i++)memory.remember(save,'madamStar',{date:'1878-01-03',text:'Visit '+i,kind:'greet'});
assert.equal(memory.entries(save,'madamStar').length,80,'bounded disk memory');
assert.deepEqual(memory.recall({},'madamStar'),[],'no cross-profile information leakage');
console.log('PASS NPC bounded private memory, importance recall, reflection and unverified claims');
