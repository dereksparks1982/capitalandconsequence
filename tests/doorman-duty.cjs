'use strict';
const assert=require('node:assert/strict');
const work=require('../doorman-duty.js');
const date='1890-01-02';
const place={locationId:work.VENUE,roomId:work.ROOM};
const life=()=>({characterRoute:'criminal',phase:'night',paused:false,personalCash:7.25});
let save=life();
assert.equal(work.ROOM,'doorman-post');
assert.equal(work.WAGE_CENTS,30);
assert.equal(work.MAX_SEGMENTS,4);
assert.equal(work.ENCOUNTERS.length,5);
for(const encounter of work.ENCOUNTERS)assert.ok(encounter.choices.length>=2&&encounter.choices.every(c=>c.result&&c.label));
assert.equal(work.access({...save,characterRoute:'industrialist'},work.VENUE,work.ROOM).ok,false);
assert.equal(work.access(save,work.VENUE,'proprietor-office').ok,false);
assert.equal(work.access(save,'factory',work.ROOM).ok,false);
assert.equal(work.begin(save,{...place,date,profileId:'eli',spentSeconds:120}).ok,false);
assert.equal(work.summary(save).totalSegments,0,'Uncharged minutes create no payable duty');
const first=work.begin(save,{...place,date,profileId:'eli',spentSeconds:600});
assert.equal(first.ok,true);
assert.equal(work.summary(save).pending.status,'awaiting-response');
assert.equal(work.begin(save,{...place,date,profileId:'eli',spentSeconds:600}).ok,false,'No reroll while visitor waits');
assert.equal(work.respond(save,{...place,choiceId:'bad-choice',spentSeconds:300}).ok,false);
assert.equal(work.respond(save,{...place,choiceId:first.encounter.choices[0].id,spentSeconds:0}).ok,false);
const afterBegin=JSON.parse(JSON.stringify(save));
assert.equal(work.encounter(afterBegin).id,first.encounter.id,'Visitor identity survives save reload');
const response=work.respond(afterBegin,{...place,choiceId:first.encounter.choices[0].id,spentSeconds:300});
assert.equal(response.ok,true);
assert.equal(response.wageCents,30);
assert.equal(afterBegin.personalCash,7.55,'Paid exactly once upon completed segment');
assert.equal(work.summary(afterBegin).wagesEarnedCents,30);
assert.equal(work.summary(afterBegin).totalSegments,1);
assert.equal(work.respond(afterBegin,{...place,choiceId:first.encounter.choices[0].id,spentSeconds:300}).ok,false,'No repeat pay');
assert.equal(afterBegin.personalCash,7.55);
for(let n=0;n<work.MAX_SEGMENTS-1;n++){
 const e=work.begin(afterBegin,{...place,date,profileId:'eli',spentSeconds:600});
 assert.equal(e.ok,true);
 assert.equal(work.respond(afterBegin,{...place,choiceId:e.encounter.choices[0].id,spentSeconds:300}).ok,true);
}
assert.equal(afterBegin.personalCash,8.45);
assert.equal(work.summary(afterBegin).segmentsByDate[date],4);
assert.equal(work.begin(afterBegin,{...place,date,profileId:'eli',spentSeconds:600}).ok,false,'Nightly cap prevents infinite shifts and wages');
assert.equal(work.summary(afterBegin).wagesEarnedCents,120);
const later=work.begin(afterBegin,{...place,date:'1890-01-03',profileId:'eli',spentSeconds:600});
assert.equal(later.ok,true,'New nights can offer new honest work');
assert.equal(work.summary(afterBegin).pending.date,'1890-01-03');
assert.equal(work.respond(afterBegin,{...place,choiceId:later.encounter.choices[1].id,spentSeconds:300}).ok,true);
assert.equal(afterBegin.personalCash,8.75);
const day=life();day.phase='day';
assert.equal(work.begin(day,{...place,date,profileId:'eli',spentSeconds:600}).ok,false,'Closed door during daytime');
const paused=life();paused.paused=true;
assert.equal(work.begin(paused,{...place,date,profileId:'eli',spentSeconds:600}).ok,false);
const other=life();
assert.equal(work.summary(other).totalSegments,0,'Different profile has independent wages');
assert.equal(work.ensure(afterBegin).logs.every(log=>log.wageCents===30),true);
console.log('PASS doorman nighttime shifts, ordinary visitor choices, single-payment wages, locked doors and per-night limits');
