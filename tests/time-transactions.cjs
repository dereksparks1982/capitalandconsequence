'use strict';
const assert=require('node:assert/strict');
const bridge=require('../calendar-bridge.js'),tx=require('../time-transactions.js');
const world=require('../world-clock.js');
const s={paused:false};
bridge.start(s,'1890-01-02');
assert.equal(tx.advance(s,59,'tick').wholeMinutes,0);
assert.equal(bridge.label(s),'8:00 AM');
assert.equal(tx.advance(s,1,'tick').wholeMinutes,1);
assert.equal(bridge.label(s),'8:01 AM');
assert.equal(tx.ensure(s).tickSeconds,60);
assert.equal(tx.advance(s,120,'action','paper-1').status,'applied');
assert.equal(bridge.label(s),'8:03 AM');
assert.equal(tx.advance(s,120,'action','paper-1').status,'duplicate');
assert.equal(bridge.label(s),'8:03 AM');
assert.equal(tx.advance(s,3600,'travel','trip-1').status,'applied');
assert.equal(bridge.label(s),'9:03 AM');
assert.equal(tx.entries(s).length,2);
const serialized=JSON.stringify(s),loaded=JSON.parse(serialized);
assert.equal(tx.advance(loaded,3600,'travel','trip-1').status,'duplicate');
assert.equal(JSON.stringify(loaded),serialized,'Duplicated callback does not modify saved state');
loaded.paused=true;
assert.equal(tx.advance(loaded,3600,'travel','trip-2').status,'paused');
assert.equal(bridge.label(loaded),'9:03 AM');
const legacy={paused:false,worldCalendarStatus:'legacy-unmapped'};
assert.equal(tx.advance(legacy,3600,'action','legacy-1').status,'legacy-unmapped');
assert.equal(bridge.label(legacy),null);
assert.equal(legacy.worldCalendar,undefined);
const fired=[];
world.schedule(s.worldCalendar,world.parseMinute('1890-01-03T10:00'),'arrival',{letter:'one'});
assert.equal(bridge.beginTurn(s,'1890-01-03',480,e=>fired.push(e.type)).status,'advanced');
assert.equal(bridge.label(s),'8:00 AM');
assert.equal(fired.length,0);
const morning=world.parseMinute('1890-01-03T08:00');
assert.equal(bridge.beginTurn(s,'1890-01-02').status,'retained');
assert.equal(s.worldCalendar.worldMinute,morning,'Known time never runs backwards');
assert.equal(bridge.beginTurn(s,'1890-01-04',480,e=>fired.push(e.type)).status,'advanced');
assert.deepEqual(fired,['arrival'],'Future queued event fires once at the next forward rollover');
assert.equal(s.worldCalendar.history.filter(e=>e.type==='arrival').length,1);
const old={worldCalendarStatus:'legacy-unmapped'};
assert.equal(bridge.beginTurn(old,'1890-01-05').status,'mapped');
assert.equal(bridge.label(old),'8:00 AM');
const separate={paused:false};bridge.start(separate,'1890-01-02');
assert.equal(tx.entries(separate).length,0,'Separate profiles have separate transactions');
assert.throws(()=>tx.advance(s,-1,'action'));
assert.throws(()=>tx.advance(s,1,'bad-kind'));
console.log('PASS time transaction ledger, pause, idempotence and non-rewinding turn transition');
