'use strict';
const assert=require('node:assert/strict');
const needs=require('../npc-needs.js');
const weekly=require('../npc-weekly-schedule.js');
const clock=require('../world-clock.js');
const minute=clock.parseMinute;
const worker={id:'foremanSullivan',places:['factory','factory',null,null],
 activities:['preparing','working',null,null],traits:{caution:81}};
const start=minute('1890-01-03T08:00');
const make=()=>({energy:80});
let a=make();
const first=needs.settle(a,worker,start,weekly);
assert.equal(first.changed,true);
assert.equal(first.elapsed,0);
assert.equal(a.needs.lastMinute,start);
assert.equal(a.energy,80);
const work=needs.settle(a,worker,minute('1890-01-03T17:00'),weekly);
assert.equal(work.elapsed,540);
assert.ok(a.energy<80,'Busy workday causes fatigue');
assert.ok(a.needs.activeHours>=8,'Work hours tracked privately');
const tired=a.energy;
needs.settle(a,worker,minute('1890-01-04T08:00'),weekly);
assert.ok(a.energy>tired,'Off-duty night brings real rest');
assert.ok(a.needs.restHours>=9,'Overnight rest contributes to saved personal life');
const before=JSON.stringify(a);
assert.equal(needs.settle(a,worker,minute('1890-01-04T08:00'),weekly).changed,false);
assert.equal(JSON.stringify(a),before,'Repeated clock read cannot alter personal condition');
const fromSave=JSON.parse(before);
assert.equal(needs.settle(fromSave,worker,minute('1890-01-04T08:00'),weekly).changed,false);
assert.equal(JSON.stringify(fromSave),before,'Reload does not duplicate rest');
const full=make(),partial=make();
needs.settle(full,worker,start,weekly);
needs.settle(partial,worker,start,weekly);
needs.settle(full,worker,minute('1890-01-03T17:00'),weekly);
needs.settle(partial,worker,minute('1890-01-03T10:00'),weekly);
needs.settle(partial,worker,minute('1890-01-03T12:00'),weekly);
needs.settle(partial,worker,minute('1890-01-03T17:00'),weekly);
assert.deepEqual(partial.needs,full.needs,'The result must not depend on render frequency');
assert.ok(full.needs.dailyHistory.length>=1,'Daily records persist');
assert.equal(full.needs.dailyHistory.reduce((sum,r)=>sum+r.activeMinutes+r.restMinutes+r.otherMinutes,0),
  540,'The recorded day accounts for every elapsed game minute');
const journalSave=JSON.parse(JSON.stringify(full));
assert.equal(needs.settle(journalSave,worker,minute('1890-01-03T17:00'),weekly).changed,false);
assert.deepEqual(journalSave,full,'Reloading cannot duplicate daily activity');
const history=make();
needs.settle(history,worker,start,weekly);
needs.settle(history,worker,start+20*1440,weekly);
assert.ok(history.needs.dailyHistory.length<=14,'Daily history is bounded after long jumps');
assert.ok(history.needs.dailyHistory.every(r=>r.activeMinutes+r.restMinutes+r.otherMinutes>0));
const clockState=clock.create('1890-01-03T08:00'),minuteBefore=clockState.worldMinute;
needs.settle(a,worker,minute('1890-01-04T12:00'),weekly);
assert.equal(clockState.worldMinute,minuteBefore,'A resident never advances the world clock');
assert.throws(()=>needs.settle({},worker,NaN,weekly),'A saved minute is required');
const long=make();
needs.settle(long,worker,start,weekly);
const distant=needs.settle(long,worker,start+60*24*31,weekly);
assert.equal(distant.approximated,17*1440,'Beyond two weeks is explicitly recorded as approximate');
assert.equal(long.needs.unresolvedMinutes,17*1440);
assert.ok([long.needs.energy,long.needs.hunger,long.needs.mood].every(v=>v>=0&&v<=100));
assert.equal(needs.settle(long,worker,start-10,weekly).changed,false,'No backward time settlement');
console.log('PASS NPC private needs: saved rest, hunger, mood, deterministic steps, no double action or NPC time');
