'use strict';
/* Offline 32px room builder core regression. No Electron / network / GitHub Actions. */
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const base=path.join(__dirname,'..');
const root={};const scope={window:root,globalThis:root,module:{exports:{}},Math,Date};
for(const file of ['room-builder-catalog.js','room-builder-core.js']){
 vm.runInNewContext(fs.readFileSync(path.join(base,file),'utf8'),scope,{filename:file});
}
const C=root.FE_ROOM_BUILDER_CORE;
assert.equal(root.FE_ROOM_CATALOG.length,69,'must reuse all original sprites');
assert.equal(C.TILE,32);
const room=C.makeRoom('factory','executive-office');
assert.equal(room.floor.length,16*12);
assert.equal(room.walls.length,16*12);
assert.equal(C.blocked(room,0,0),true);
assert.equal(C.blocked(room,room.spawns.player.x,room.spawns.player.y),false);
const x=Math.floor(room.widthTiles/2);
assert.equal(room.walls[C.index(room,x,room.heightTiles-1)],'door_open');
assert.equal(C.blocked(room,x,room.heightTiles-1),false);
assert.equal(C.toggleDoor(room,x,room.heightTiles-1),true);
assert.equal(C.blocked(room,x,room.heightTiles-1),true);
assert.equal(C.toggleDoor(room,x,room.heightTiles-1),true);
assert.equal(C.blocked(room,x,room.heightTiles-1),false);
assert.equal(C.paint(room,4,4,'floor_rug_red'),true);
assert.equal(C.paint(room,4,4,'floor_rug_red'),false);
const desk=C.place(room,'desk_oak',4,5);
assert.ok(desk);assert.equal(C.blocked(room,4,5),true);
assert.equal(C.blocked(room,5,5),true);
assert.equal(C.place(room,'safe_iron',5,5),null,'solid furniture cannot overlap desk');
assert.equal(C.place(room,'safe_iron',room.spawns.player.x,room.spawns.player.y),null,'cannot trap player');
assert.equal(C.paint(room,4,5,'wall_horizontal'),false,'wall cannot overwrite solid furniture');
assert.ok(C.relocate(room,desk.id,4,5,1),'rotate a two-tile desk');
assert.equal(C.blocked(room,4,6),true,'rotated footprint is two tall');
const copy=C.relocate(room,desk.id,14,7,1,true);
assert.ok(copy,'rotated duplicate near room edge should fit');
assert.equal(copy.rotation,1);
assert.equal(C.relocate(room,desk.id,15,8,0),null,'unrotated desk cannot exit east border');
assert.deepEqual(Array.from(C.dims(C.asset(copy.spriteId),copy.rotation)),[1,2]);
assert.equal(C.remove(room,copy.id),true);assert.equal(C.remove(room,copy.id),false);
assert.equal(C.setSpawn(room,4,5),false,'blocked player spawn rejected');
assert.equal(C.setSpawn(room,9,8),true);
assert.equal(C.walk(room,{x:4,y:4},0,1).y,4,'desk blocks walking');
const grown=C.resize(room,19,15);
assert.ok(grown,'expansion keeps the room valid');
assert.equal(grown.widthTiles,19);assert.equal(grown.heightTiles,15);
assert.equal(grown.objects.length,1,'resizing never silently discards placed furniture');
assert.equal(grown.floor[C.index(grown,4,4)],'floor_rug_red');
assert.equal(grown.walls[C.index(grown,Math.floor(grown.widthTiles/2),grown.heightTiles-1)],'door_open');
assert.equal(C.resize(room,9,8),null,'shrinking past Charles or furniture is rejected');
const sample=C.sampleOffice();
assert.equal(sample.objects.length,8,'crude reusable example office exists');
assert.equal(C.analyze(sample).reachableDoors,1,'Charles can reach an exit');
assert.equal(C.path(sample,sample.spawns.player,{x:8,y:11})!==null,true,'editor path finder reaches a door');
const clutter=C.makeRoom();
assert.equal(C.place(clutter,'plant_small',0,1),null,'decoration may not be embedded in an exterior wall');
assert.equal(C.paint(clutter,3,3,'wall_horizontal'),true);
assert.equal(C.place(clutter,'sam_front',3,3),null,'NPC cannot occupy a wall');
const furniture=C.place(clutter,'desk_oak',4,4);
assert.ok(furniture);
assert.equal(C.place(clutter,'sam_front',4,4),null,'NPC cannot occupy a solid desk');
assert.equal(C.place(clutter,'sam_front',clutter.spawns.player.x,clutter.spawns.player.y)!==null,false,'NPC may not occupy Charles spawn');
const restored=C.sanitize(JSON.parse(JSON.stringify(room)),'factory','executive-office');
assert.equal(restored.objects.length,1);
assert.equal(restored.floor[C.index(restored,4,4)],'floor_rug_red');
assert.deepEqual(Object.keys(restored.spawns),['player']);
const bad=JSON.parse(JSON.stringify(restored));
bad.objects[0].spriteId='imaginary_cabinet';
assert.throws(()=>C.sanitize(bad),'unknown art references must fail');
assert.throws(()=>C.sanitize(restored,'factory','production-floor'),'wrong room identities rejected');
const off=JSON.parse(JSON.stringify(restored));off.objects[0].x=99;
assert.throws(()=>C.sanitize(off),'off-grid object rejected');
console.log('PASS 32px office build, object placement, rotation, collision, stairs-free walking and persistence contract');
