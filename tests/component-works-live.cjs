'use strict';
const assert=require('node:assert/strict');
const engine=require('../component-works.js'),bridge=require('../calendar-bridge.js'),clock=require('../washington-time.js');
global.FE_WASHINGTON_TIME=clock;
const live=require('../component-works-live.js');
const assistant={status:'present',locationId:'factory'};
const s={paused:false,phase:'day',companyCash:2500,lastRevenue:0,lastExpenses:0,
 componentWorks:engine.createState(),npcSimulation:{agents:{foremanSullivan:assistant}}};
bridge.start(s,'1878-01-02',540);
const spend=seconds=>clock.advance(s,seconds,'action').applied?seconds:0;
const args={customer:engine.CUSTOMERS[0],productId:'telegraph-key',quantity:3,deadline:'1878-01-12'};
const a=live.transact(s,'order',args,'order:1',spend);
assert.equal(a.ok,true);assert.equal(clock.now(s).time,'9:05 AM');
const snapshot=JSON.stringify(s);
assert.equal(live.transact(s,'order',args,'order:1',spend).repeated,true);
assert.equal(JSON.stringify(s),snapshot);
const b=live.transact(s,'assemble',{orderId:a.id,quantity:3},'assembly:1',spend);
assert.equal(b.ok,true);assert.equal(b.units,2,'Only two 3-hour keys fit before close');
assert.equal(b.remainingOnOrder,1);
assert.equal(s.componentWorks.warehouse['telegraph-key'],2);
assert.equal(clock.now(s).time,'3:05 PM');
assert.equal(live.transact(s,'ship',{orderId:a.id,quantity:2},'early',spend).ok,false);
assert.equal(live.transact(s,'assemble',{orderId:a.id,quantity:1},'no-time',spend).ok,false);
assistant.locationId='home';assistant.status='off-duty';
assert.equal(live.transact(s,'assemble',{orderId:a.id,quantity:1},'absent',spend).ok,false);
assistant.locationId='factory';assistant.status='present';
bridge.start(s,'1878-01-03',540);
assert.equal(live.transact(s,'assemble',{orderId:a.id,quantity:1},'assembly:2',spend).ok,true);
bridge.start(s,'1878-01-05',540);
assert.equal(live.transact(s,'assemble',{orderId:a.id,quantity:1},'sat:assemble',spend).ok,false);
const shipped=live.transact(s,'ship',{orderId:a.id,quantity:3},'ship:1',spend);
assert.equal(shipped.ok,true);assert.equal(shipped.revenueCents,3*420);
assert.equal(Math.round(s.companyCash*100),250000+shipped.revenueCents);
const copy=JSON.stringify(s);
assert.equal(live.transact(s,'ship',{orderId:a.id,quantity:3},'ship:1',spend).repeated,true);
assert.equal(JSON.stringify(s),copy);
bridge.start(s,'1878-01-06',540);
assert.equal(live.transact(s,'order',args,'sunday',spend).ok,false);
bridge.start(s,'1878-01-07',539);
assert.equal(live.transact(s,'order',args,'early',spend).ok,false);
console.log('PASS five-day assembly, remaining quantities, assistant presence, Saturday deliveries and no duplicate cash');
