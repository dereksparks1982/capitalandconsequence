'use strict';
const assert=require('node:assert/strict');
const engine=require('../component-works.js'),bridge=require('../calendar-bridge.js'),clock=require('../washington-time.js');
global.FE_WASHINGTON_TIME=clock;
const live=require('../component-works-live.js');
const s={paused:false,phase:'day',companyCash:2500,lastRevenue:0,lastExpenses:0,componentWorks:engine.createState()};
bridge.start(s,'1878-01-02');
const spend=seconds=>clock.advance(s,seconds,'action').applied?seconds:0;
const args={customer:engine.CUSTOMERS[0],productId:'telegraph-key',quantity:4,deadline:'1878-02-10'};
const a=live.transact(s,'order',args,'order:1',spend);
assert.equal(a.ok,true);assert.equal(a.elapsedSeconds,300);
assert.equal(clock.now(s).time,'8:05 AM');
const state=JSON.stringify(s);
assert.equal(live.transact(s,'order',args,'order:1',spend).repeated,true);
assert.equal(JSON.stringify(s),state,'No duplicate time or contract');
const b=live.transact(s,'assemble',{orderId:a.id,quantity:4},'assembly:1',spend);
assert.equal(b.ok,true);assert.equal(b.elapsedSeconds,2160);
assert.equal(clock.now(s).time,'8:41 AM');
assert.equal(s.componentWorks.warehouse['telegraph-key'],4);
const c=live.transact(s,'ship',{orderId:a.id,quantity:4},'ship:1',spend);
assert.equal(c.ok,true);assert.equal(clock.now(s).time,'8:56 AM');
assert.equal(Math.round(s.companyCash*100),250000-b.laborCostCents+c.revenueCents,'Cash compared in exact integer cents');
const d=live.transact(s,'purchase',{materialId:'brass',quantity:10},'purchase:1',spend);
assert.equal(d.ok,true);assert.equal(s.componentWorks.materials.brass,172);
const original=JSON.stringify(s);
assert.equal(live.transact(s,'assemble',{orderId:a.id,quantity:4},'bad:1',spend).ok,false);
assert.equal(JSON.stringify(s),original);
const close={paused:false,companyCash:2500,componentWorks:engine.createState()};
bridge.start(close,'1878-01-02',1019);
const copy=JSON.stringify(close);
assert.equal(live.transact(close,'order',args,'too:late',()=>{throw Error('Cannot advance!')}).ok,false);
assert.equal(JSON.stringify(close),copy);
assert.equal(live.transact(close,'order',{...args,productId:'incandescent-lamp'},'bulbs',spend).ok,false);
assert.equal(engine.verify(JSON.parse(JSON.stringify(s.componentWorks))).orders.length,1);
console.log('PASS component orders, materials, timed assembly, shipments, nonduplicated cash and 1878 gate');
