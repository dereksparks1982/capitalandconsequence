'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const game=require('../murder-cases.js');
const date='1890-01-02';
const create=id=>game.createCase(id,date);
const basic=create('detective-A');
assert.equal(basic.version,1);
assert.equal(basic.suspects.length,4);
assert(game.validate(basic));
assert.notEqual(basic.victim.id,basic.truth.culpritId);
assert(basic.suspects.some(x=>x.id===basic.truth.culpritId));
assert.deepEqual(create('detective-A'),basic,'Same profile, date and serial create same canonical mystery');
assert.notDeepEqual(create('detective-B').truth,basic.truth,'Different profile may have different factual case');
assert.throws(()=>game.createCase('',date));
assert.throws(()=>game.createCase('x','1890-bad-date'));
assert.throws(()=>game.createCase('x',date,[{id:'a'}]));
assert.throws(()=>game.createCase('x',date,game.DEFAULT_ROSTER,0));
const appeared=new Set();
for(let i=0;i<360;i++){
 const c=create('case-'+i);
 assert(game.validate(c),'Every generated case has a unique culprit');
 appeared.add(c.truth.culpritId);
 assert.equal(game.candidateIds(c).length,0,'Unknown evidence does not imply a verdict');
 const publicView=game.publicFile(c);
 assert(!('truth' in publicView));
 assert(!('clues' in publicView));
 assert(!JSON.stringify(publicView).includes('"candidates"'));
 assert.equal(publicView.evidence.length,0);
 assert.equal(publicView.readyToAccuse,false);
}
assert(appeared.size>=8,'Across many profiles, most residents can become the culprit');
const c=create('public-notebook');
assert.equal(game.accuse(c,c.truth.culpritId).ok,false,'Cannot guess without gathering evidence');
assert.equal(game.uncover(c,'bogus').ok,false);
assert.equal(game.uncover(c,'scene').ok,true);
assert.equal(game.uncover(c,'scene').ok,false,'No repeated scene rewards');
assert.equal(game.candidateIds(c).length,0,'One thread cannot solve case');
assert.equal(game.uncover(c,'records').ok,true);
assert.equal(game.candidateIds(c).length,0,'Two threads cannot close a case');
assert.equal(game.uncover(c,'witness').ok,true);
assert.equal(game.publicFile(c).evidence.length,4,'Public file shows three corroborated clues and one rumor');
assert(!game.publicFile(c).evidence.some(x=>'candidates' in x));
assert.deepEqual(game.candidateIds(c),[c.truth.culpritId],'All three routes prove one culprit');
const saved=JSON.parse(JSON.stringify(c));
assert.deepEqual(game.candidateIds(saved),[c.truth.culpritId],'Case replay survives JSON autosave');
const culprit=c.truth.culpritId;
assert.equal(game.interview(c,culprit).ok,true);
assert.equal(game.interview(c,culprit).ok,false,'Witness interview is idempotent');
assert(game.publicFile(c).suspects.find(x=>x.id===culprit).statement);
assert(!JSON.stringify(game.publicFile(c)).includes('"veracity"'));
const wrong=c.suspects.find(x=>x.id!==culprit).id;
assert.equal(game.accuse(c,wrong).solved,false);
assert.equal(c.status,'open');
assert.equal(game.accuse(c,wrong).ok,false,'Same wrong accusation cannot be spammed');
assert.equal(game.accuse(c,culprit).solved,true);
assert.equal(c.status,'solved');
assert.equal(game.uncover(c,'scene').ok,false,'Closed cases are immutable through inquiry');
assert.equal(game.accuse(c,culprit).ok,false,'Closed cases cannot be accused again');
const cold=create('false-arrests');
for(const stage of Object.keys(game.STAGES))assert.equal(game.uncover(cold,stage).ok,true);
for(const suspect of cold.suspects.filter(x=>x.id!==cold.truth.culpritId)){
 assert.equal(game.accuse(cold,suspect.id).ok,true);
}
assert.equal(cold.status,'cold');
assert.equal(game.accuse(cold,cold.truth.culpritId).ok,false);
const alone=create('invalid-proof');
alone.clues.find(x=>x.thread==='motive').candidates=['someone-else'];
assert.equal(game.validate(alone),false,'Contradictory generated cases must be rejected');
assert.equal(game.publicFile(alone),null);
const browserSource=fs.readFileSync(path.join(__dirname,'../murder-cases.js'),'utf8');
const browserCtx={window:{}};
vm.runInNewContext(browserSource,browserCtx,{filename:'murder-cases.js'});
assert.equal(browserCtx.window.FE_MURDER_CASES.validate(JSON.parse(JSON.stringify(basic))),true);

let profile='alpha',saves=0,charges=0;
const saveState={characterRoute:'investigator',gameDate:date,phase:'day',paused:false,
 dayRemaining:3600};
const runtimeSource=fs.readFileSync(path.join(__dirname,'../detective-cases.js'),'utf8');
const panel={children:[],replaceChildren(){this.children=[]},appendChild(child){this.children.push(child)}};
const doc={getElementById:id=>id==='detectiveCasePanel'?panel:null,
 createElement:tag=>({tag,children:[],textContent:'',appendChild(child){this.children.push(child)},
  addEventListener(){},setAttribute(){}})};
const ctx={window:{FE_MURDER_CASES:game,advanceWorldTime(seconds){
 if(ctx.S.dayRemaining<seconds)throw Error('Clock charged outside time budget');
 ctx.S.dayRemaining-=seconds;charges++;return seconds;}},
 S:saveState,document:doc,save(){saves++},activeProfileId(){return profile}};
vm.runInNewContext(runtimeSource,ctx,{filename:'detective-cases.js'});
const app=ctx.window.FE_DETECTIVE_CASES;
const first=app.ensure();
assert.equal(first.id,'washington-case-1');
assert.strictEqual(app.ensure(),first,'Same resident profile gets stable case identity');
assert(saves>=1,'New file autosaved immediately');
assert.equal(app.current().status,'open');
app.render();
assert(panel.children.length>5,'Investigator desk renders a real casebook');
assert.equal(app.pursue('inquiry','scene').ok,true);
assert.equal(charges,1);
const after=ctx.S.dayRemaining;
assert.equal(app.pursue('inquiry','scene').ok,false);
assert.equal(ctx.S.dayRemaining,after,'Duplicate inquiry cannot spend time');
assert.equal(app.pursue('interview',first.suspects[0].id).ok,true);
assert.equal(charges,2);
assert.equal(app.pursue('interview',first.suspects[0].id).ok,false);
ctx.S.paused=true;
assert.equal(app.pursue('inquiry','records').ok,false);
assert.equal(charges,2,'Paused investigation freezes the clock');
ctx.S.paused=false;
ctx.S.phase='report';
assert.equal(app.pursue('inquiry','records').ok,false);
ctx.S.phase='day';
ctx.S.dayRemaining=119;
assert.equal(app.pursue('inquiry','records').ok,false);
assert.equal(charges,2,'No investigation at insufficient game-time budget');
ctx.S.dayRemaining=3600;
assert.equal(app.pursue('inquiry','records').ok,true);
assert.equal(app.pursue('inquiry','witness').ok,true);
assert.equal(app.current().readyToAccuse,true);
assert.equal(app.pursue('accuse',first.truth.culpritId).solved,true);
assert.equal(app.nextCase().ok,true);
assert.equal(app.ensure().serial,2);
assert.equal(ctx.S.detectiveCases.cases.length,2,'Prior solved file archived per profile');
const restored=JSON.parse(JSON.stringify(ctx.S));
ctx.S=restored;
assert.deepEqual(app.current().id,'washington-case-2','Reload preserves the second active case');
profile='beta';
ctx.S={characterRoute:'investigator',gameDate:date,phase:'day',paused:false,dayRemaining:3600};
assert.equal(app.ensure().serial,1,'New profile gets an independent first case');
assert.equal(ctx.S.detectiveCases.cases.length,1);
ctx.S.characterRoute='industrialist';
assert.equal(app.current(),null,'Industrialist cannot read detective case files');
assert.equal(app.pursue('inquiry','scene').ok,false);
console.log('PASS 360 truth-first solvable cases, private evidence, investigator actions, clock guards and autosaves');
