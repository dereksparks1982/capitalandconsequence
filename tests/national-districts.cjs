'use strict';
const assert=require('node:assert/strict');
const nation=require('../national-districts.js');
const {CHARTER}=nation;
assert.equal(CHARTER.country,'United States of America');
assert.equal(CHARTER.historicalCivilWar.began,1861);
assert.equal(CHARTER.historicalCivilWar.ended,1865);
assert.equal(CHARTER.stateBordersRetained,false);
assert.equal(CHARTER.reorganizationDate,null,'No fabricated exact reform date');
assert.equal(CHARTER.campaignDesignStart,'1878-01-02');
assert.equal(CHARTER.currentPrototypeStart,'1890-01-02');
assert.equal(CHARTER.presidentialTermYears,10);
assert.equal(CHARTER.presidentialMaxTerms,null);
assert.equal(CHARTER.presidentialNextElectionYear,1886);
assert.equal(CHARTER.presidentialElectionMethod,'nationwide popular vote');
assert.equal(nation.get('columbia').seat,'Washington');
assert.equal(nation.get('columbia').status,'established');
const list=nation.list();
assert.ok(list.length>=7);
assert.equal(new Set(list.map(x=>x.id)).size,list.length);
const breadbasket=nation.get('husbandry');
assert.ok(breadbasket.role.includes('grain')&&breadbasket.role.includes('livestock'));
assert.equal(breadbasket.status,'working-name');
assert.ok(list.every(x=>Array.isArray(x.regions)&&x.regions.length===0),'No guessed old state boundaries');
assert.ok(list.filter(x=>x.id!=='columbia').every(x=>x.status==='working-name'));
assert.ok(nation.publicDescription().includes('discarded its old state borders'));
assert.ok(nation.registerText().includes('WORKING NAME'));
const mut=nation.get('husbandry');mut.regions.push('Old State');
assert.equal(nation.get('husbandry').regions.length,0,'Callers cannot edit national canon');
const isolated=nation.list();isolated.pop();
assert.equal(nation.list().length,list.length,'Return copies of district listings');
console.log('PASS national district charter, Civil War timeline, proposed roles, and immutable boundaries');
