'use strict';
const assert=require('node:assert/strict');
const clock=require('../world-clock.js'),bridge=require('../calendar-bridge.js');
const tx=require('../time-transactions.js'),time=require('../washington-time.js');
const save={paused:false,gameDate:'1890-01-02',turnConditions:{weather:'Cold and clear'}};
bridge.start(save,'1890-01-02');
assert.equal(time.now(save).iso,'1890-01-02T08:00');
assert.equal(time.now(save).time,'8:00 AM');
assert.equal(time.environment(save).moonPhase!==null,true);
assert.equal(time.environment(save).weather,'Cold and clear');
assert.equal(time.advance(save,59,'tick').wholeMinutes,0,'Sub-minute tick retained');
assert.equal(time.advance(save,1,'tick').wholeMinutes,1,'One minute clocks correctly');
assert.equal(time.now(save).iso,'1890-01-02T08:01');
assert.equal(time.advance(save,5*60,'action','patrol-step').status,'applied');
assert.equal(time.now(save).iso,'1890-01-02T08:06');
assert.equal(time.advance(save,5*60,'action','patrol-step').status,'duplicate');
assert.equal(time.now(save).iso,'1890-01-02T08:06','Duplicate action did not advance world');
assert.equal(time.handoff(save,'close-business','1890-01-02').iso,'1890-01-02T17:00','Day has a real evening boundary');
assert.equal(time.now(save).time,'5:00 PM');
const queued=[];clock.schedule(save.worldCalendar,clock.parseMinute('1890-01-02T19:30'),'mail-arrives',{id:'mail-1'});
assert.equal(time.handoff(save,'close-night','1890-01-02').iso,'1890-01-03T08:00');
assert.equal(time.now(save).date,'1890-01-03','World crosses midnight on the saved clock');
assert.equal(save.worldCalendar.history.filter(x=>x.type==='mail-arrives').length,1,'Scheduled events settle once at the reached boundary');
assert.equal(time.handoff(save,'close-night','1890-01-02').status,'retained','Repeating closing bell cannot rewind');
const copy=JSON.parse(JSON.stringify(save)),snapshot=JSON.stringify(copy);
assert.deepEqual(time.now(copy),time.now(save),'Loaded profile keeps the same absolute calendar');
assert.equal(JSON.stringify(copy),snapshot,'Read-only timeline introspection does not mutate saved state');
assert.equal(time.handoff(copy,'new-day','1890-01-06').iso,'1890-01-06T08:00');
assert.equal(time.now(copy).date,'1890-01-06');
copy.paused=true;assert.equal(time.advance(copy,3600,'tick').status,'paused');
assert.equal(time.now(copy).date,'1890-01-06');
const other={paused:false,turnConditions:{weather:'Heavy snow'}};
bridge.start(other,'1878-07-29',17*60+42);
assert.equal(time.environment(other).eclipse,'Solar eclipse','Real 1878 Washington solar eclipse reaches same world state');
assert.equal(time.environment(save).eclipse,null,'Separate profiles have independent skies');
assert.equal(time.now({worldCalendarStatus:'legacy-unmapped'}),null,'Legacy unmapped save has no fictitious hour');
assert.equal(time.handoff({worldCalendarStatus:'legacy-unmapped'},'new-day','1890-01-03').status,'unmapped');
assert.throws(()=>time.handoff(save,'invalid','1890-01-02'));
assert.equal(time.nextCivilDay('1878-12-31'),'1879-01-01');
console.log('PASS one saved Washington clock gateway, phase milestones, astronomy context, pause, replay and reload');
