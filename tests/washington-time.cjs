'use strict';
const assert=require('node:assert/strict'),bridge=require('../calendar-bridge.js'),time=require('../washington-time.js');
const s={paused:false,phase:'day',turnConditions:{weather:'Cold and clear'}};bridge.start(s,'1878-01-02');
assert.equal(time.rate(s),1);assert.equal(time.now(s).time,'8:00 AM');
assert.equal(time.secondsToBoundary(s),14400);assert.equal(time.secondsUntilMorning(s),86400);
assert.equal(time.advance(s,1,'tick').wholeMinutes,0);
assert.equal(s.worldCalendarRemainder,1);assert.equal(time.secondsToBoundary(s),14399);
assert.equal(time.advance(s,59,'tick').wholeMinutes,1);
assert.equal(time.now(s).time,'8:01 AM');
assert.equal(time.advance(s,18000,'action','club-visit').status,'applied');
assert.equal(time.now(s).time,'1:01 PM','Five-hour club stay means five game hours');
assert.equal(time.advance(s,18000,'action','club-visit').status,'duplicate');
assert.equal(time.now(s).time,'1:01 PM');
const copy=JSON.parse(JSON.stringify(s));assert.deepEqual(time.now(copy),time.now(s));
copy.paused=true;assert.equal(time.advance(copy,100,'tick').status,'paused');
const before=JSON.stringify(s);assert.equal(time.environment(s).weather,'Cold and clear');assert.equal(JSON.stringify(s),before);
const eclipse={paused:false,turnConditions:{weather:'Cloudy'}};bridge.start(eclipse,'1878-07-29',17*60+42);
assert.equal(time.environment(eclipse).eclipse,'Solar eclipse');
assert.equal(time.now({worldCalendarStatus:'legacy-unmapped'}),null);
assert.equal(time.nextCivilDay('1878-12-31'),'1879-01-01');
assert.throws(()=>time.advance(s,-1));
console.log('PASS 1:1 Washington time, five-hour activity, persisted timeline, pause and eclipse');
