'use strict';
const assert=require('node:assert/strict');
const patrol=require('../patrol-duty.js');
const {STREETS,INCIDENTS}=patrol;
const station='metropolitanPolice',date='1890-01-02';
const fresh=()=>({characterRoute:'investigator',phase:'day',paused:false});
assert.equal(STREETS.length,2);
assert.deepEqual(STREETS.map(s=>s.id),['hillsdale','oldChinatown']);
assert.equal(INCIDENTS.length,5);
for(const scene of INCIDENTS){
 assert.ok(scene.choices.length>=2);
 assert.ok(scene.choices.every(c=>c.record&&c.label),'Explicit choices and recorded outcomes');
}
let save=fresh();
assert.equal(patrol.access({characterRoute:'industrialist',phase:'day'},'walk','hillsdale').ok,false);
assert.equal(patrol.access(save,'walk','factory').ok,false);
assert.equal(patrol.access(save,'report','hillsdale').ok,false);
assert.equal(patrol.walk(save,{locationId:'hillsdale',date,profileId:'sam',spentSeconds:0}).ok,false);
assert.equal(patrol.ensure(save).walks,0,'No uncharged patrol credit');
let event=patrol.walk(save,{locationId:'hillsdale',date,profileId:'sam',spentSeconds:600});
assert.equal(event.ok,true);
assert.equal(event.incident.locationId,'hillsdale');
assert.equal(patrol.ensure(save).walks,1);
assert.equal(patrol.ensure(save).beatMinutes,10);
assert.equal(patrol.walk(save,{locationId:'hillsdale',date,profileId:'sam',spentSeconds:600}).ok,false,'Unresolved incident prevents reroll');
assert.equal(patrol.respond(save,{locationId:'oldChinatown',choiceId:'assist',spentSeconds:300}).ok,false);
assert.equal(patrol.respond(save,{locationId:'hillsdale',choiceId:'bogus',spentSeconds:300}).ok,false);
const firstChoice=event.scene.choices[0];
assert.equal(patrol.respond(save,{locationId:'hillsdale',choiceId:firstChoice.id,spentSeconds:0}).ok,false);
assert.equal(patrol.respond(save,{locationId:'hillsdale',choiceId:firstChoice.id,spentSeconds:300}).ok,true);
assert.equal(patrol.respond(save,{locationId:'hillsdale',choiceId:firstChoice.id,spentSeconds:300}).ok,false,'Cannot resolve twice');
assert.equal(patrol.report(save,{locationId:'hillsdale',roomId:'station-duty-room',spentSeconds:300}).ok,false);
const stored=JSON.stringify(save);
save=JSON.parse(stored);
assert.equal(patrol.ensure(save).pending.status,'awaiting-report','Progress survives JSON autosave reload');
assert.equal(patrol.scene(save).id,event.scene.id);
assert.equal(patrol.report(save,{locationId:station,roomId:'station-duty-room',spentSeconds:0}).ok,false);
const filing=patrol.report(save,{locationId:station,roomId:'station-duty-room',spentSeconds:300});
assert.equal(filing.ok,true);
assert.equal(filing.record.status,'filed');
assert.equal(patrol.report(save,{locationId:station,roomId:'station-duty-room',spentSeconds:300}).ok,false,'Station cannot double-file');
assert.equal(patrol.ensure(save).reportsFiled,1);
assert.equal(patrol.access(save,'report',station,'unassigned-room').ok,false,'Station visitors cannot file from the public lobby');
const afterHours={...fresh(),phase:'night'};
assert.equal(patrol.access(afterHours,'report',station,'station-duty-room').ok,true,'End-of-day report writing is allowed at night');
assert.equal(patrol.ensure(save).logs.length,1);
assert.equal(patrol.ensure(save).contacts,1);
assert.equal(patrol.summary(save).pending,null);
const profileB=fresh();
const encounterB=patrol.walk(profileB,{locationId:'hillsdale',date,profileId:'another-profile',spentSeconds:600});
assert.equal(encounterB.incident.id,'PAT-0001','Profiles have independent ledgers');
assert.equal(patrol.summary(profileB).reportsFiled,0);
for(let i=0;i<100;i++){
 const scene=patrol.walk(save,{locationId:'oldChinatown',date:'1890-01-'+String(1+(i%28)).padStart(2,'0'),profileId:'sam',spentSeconds:600});
 assert.equal(scene.ok,true);
 const valid=scene.scene.choices[0];
 assert.equal(patrol.respond(save,{locationId:'oldChinatown',choiceId:valid.id,spentSeconds:300}).ok,true);
 assert.equal(patrol.report(save,{locationId:station,roomId:'station-duty-room',spentSeconds:300}).ok,true);
}
assert.equal(patrol.ensure(save).reportsFiled,101);
assert.equal(patrol.ensure(save).logs.length,80,'History bounded; aggregate total preserved');
const before=JSON.stringify(save);
assert.equal(patrol.walk(save,{locationId:'hillsdale',date:'1890-02-01',profileId:'sam',spentSeconds:42}).ok,false);
assert.equal(JSON.stringify(save),before,'Invalid time charge cannot mutate ledger');
const paused=fresh();paused.paused=true;
assert.equal(patrol.walk(paused,{locationId:'hillsdale',date,profileId:'sam',spentSeconds:600}).ok,false);
const night=fresh();night.phase='night';
assert.equal(patrol.walk(night,{locationId:'hillsdale',date,profileId:'sam',spentSeconds:600}).ok,false);
console.log('PASS patrol beat walking, civilian encounters, summons, station reports, persistence, time guards and no detective authority');
