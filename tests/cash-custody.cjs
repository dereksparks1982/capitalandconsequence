'use strict';
const assert=require('node:assert/strict');
const money=require('../cash-custody.js');
const game=()=>({gameDate:'1878-01-02',characterRoute:'industrialist',companyCash:2500,personalCash:600,
 ownerDistributionsToday:0,divertedToday:0,unaccountedFunds:0,corporateMisuseCount:0});
const s=game();
assert.equal(money.transfer(s,'collectCompany',1000,'districtBank','industrialist').ok,false);
assert.equal(money.transfer(s,'collectCompany',1000,'factory','wardman').ok,false);
assert.equal(money.transfer(s,'collectCompany',1000,'factory','industrialist').ok,true);
assert.equal(s.companyCash,1500);
assert.equal(money.balances(s).companyCarried,1000);
assert.equal(s.personalCash,600,'Company cash in your pocket remains company property');
assert.equal(money.transfer(s,'depositBusiness',650,'districtBank','industrialist').ok,true);
assert.equal(money.balances(s).companyCarried,350);
assert.equal(money.balances(s).businessBank,650);
assert.equal(money.transfer(s,'withdrawBusiness',600,'factory','industrialist').ok,false);
assert.equal(money.transfer(s,'withdrawBusiness',250,'districtBank','industrialist').ok,true);
assert.equal(money.balances(s).businessBank,400);
assert.equal(money.balances(s).companyCarried,600);
assert.equal(money.transfer(s,'depositChecking',180,'districtBank','industrialist').ok,true);
assert.equal(money.transfer(s,'checkingToSavings',100,'districtBank','industrialist').ok,true);
assert.equal(money.balances(s).personalSavings,100);
assert.equal(money.balances(s).personalChecking,80);
assert.equal(s.personalCash,420);
assert.equal(money.transfer(s,'withdrawSavings',50,'districtBank','industrialist').ok,true);
assert.equal(money.balances(s).personalSavings,50);
assert.equal(s.personalCash,470);
assert.equal(money.transfer(s,'depositSavings',30,'factory','industrialist').ok,false);
assert.equal(money.transfer(s,'depositSavings',1.001,'districtBank','industrialist').ok,true);
assert.equal(money.transfer(s,'depositBusiness',2000,'districtBank','industrialist').ok,false);
const beforeCasino={personalCash:s.personalCash,atWorks:s.companyCash,businessBank:money.balances(s).businessBank};
assert.equal(money.stake(s,'company',100,'brokerOffice').ok,false);
const bet=money.stake(s,'company',100,'races');
assert.equal(bet.ok,true);
assert.equal(money.balances(s).companyCarried,500);
assert.equal(s.personalCash,beforeCasino.personalCash,'Company wager cannot take personal cash');
assert.equal(s.companyCash,beforeCasino.atWorks,'Company wallet is carried, not teleported from the office');
assert.equal(money.balances(s).businessBank,beforeCasino.businessBank,'Bank balance never changes on track');
assert.equal(s.unaccountedFunds,100,'Company wager is an unexplained corporate cash exposure');
assert.equal(money.settle(s,bet.ticket,230).ok,true);
assert.equal(money.balances(s).companyCarried,730,'Winnings belong to original company funds');
assert.equal(s.personalCash,beforeCasino.personalCash,'Company winnings never become personal by magic');
assert.equal(s.unaccountedFunds,0,'Repaid principal closes cash exposure');
assert.equal(money.settle(s,bet.ticket,230).ok,false,'A bet cannot pay twice');
const loss=money.stake(s,'company',40,'races');
assert.equal(loss.ok,true);
assert.equal(money.settle(s,loss.ticket,0).ok,true);
assert.equal(s.unaccountedFunds,40,'Lost company money leaves actual shortfall');
assert.equal(money.transfer(s,'ownerDistribution',100,'factory','industrialist').ok,true);
assert.equal(s.ownerDistributionsToday,100);
assert.equal(s.personalCash,beforeCasino.personalCash+100);
assert.equal(money.transfer(s,'irregularDraw',10,'factory','industrialist').ok,true);
assert.equal(s.divertedToday,10);
assert.equal(s.unaccountedFunds,50,'Irregular withdrawals retain unexplained shortfall');
const totalBefore=s.personalCash+money.balances(s).companyCarried;
const checked=money.travelRisk(s,{from:'factory',to:'districtBank',minute:900,night:true},9000);
assert.equal(checked.ok,true);
assert.equal(checked.lost,0,'Large cash risk is not a guaranteed robbery');
const snapshot=JSON.stringify(s);
assert.equal(money.travelRisk(s,{from:'factory',to:'districtBank',minute:900,night:true},0).repeated,true);
assert.equal(JSON.stringify(s),snapshot,'Re-rendering the same trip never re-rolls theft');
const happened=money.travelRisk(s,{from:'districtBank',to:'races',minute:906,night:true},0);
assert.equal(happened.occurred,true,'Risk can sometimes become actual loss');
assert.ok(happened.companyLoss>=0&&happened.personalLoss>=0);
assert.ok(s.personalCash+money.balances(s).companyCarried<totalBefore);
assert.equal(money.travelRisk(s,{from:'districtBank',to:'races',minute:906,night:true},0).repeated,true);
const saved=JSON.parse(JSON.stringify(s));
assert.equal(money.transfer(saved,'depositBusiness',100,'districtBank','industrialist').ok,true);
assert.ok(money.balances(saved).businessBank>money.balances(s).businessBank,'Each profile keeps its own bank ledger');
assert.equal(s.cashCustody.history.at(-1).action,'journey-cash-loss');
console.log('PASS optional physical business/checking/savings accounts, company-funded wagering and ownership-preserving settlement, travel risk');
