'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const read=p=>fs.readFileSync(path.join(__dirname,'..',p),'utf8');
const c={window:{}};vm.runInNewContext(read('city.js'),c);
const city=c.window.FederalElectricCity,access=require('../city-access.js');
const fair=city.getLocation('washingtonFairgrounds'),actor={route:'industrialist'};
assert.equal(city.mapLocations().length,42);assert.equal(fair.map.n,9);
assert.equal(fair.availableFrom,'1878-10-01');assert.equal(fair.storyEvent,'worlds-fair-1878');
assert.equal(access.canRoom(city,actor,fair.id,'public-approach','1878-01-02').ok,true);
assert.equal(access.canRoom(city,actor,fair.id,'fairgrounds','1878-09-30').ok,false);
assert.equal(access.canRoom(city,actor,fair.id,'fairgrounds','1878-10-01').ok,true);
const wc={window:{}};vm.runInNewContext(read('world-canon.js'),wc);
assert.match(wc.window.FE_WORLD_CANON.forDate('1878-01-02').lines.join(' '),/already has electrical service/);
const works=require('../component-works.js'),state=works.createState();
assert.equal(works.eligibility(state,'insulated-wire').ok,true);
assert.equal(works.eligibility(state,'incandescent-lamp').ok,false,'Component workshop does not magically manufacture bulbs');
const decisions=read('DECISIONS.md').slice(0,2000);
assert.ok(decisions.indexOf('First, Charlie manufactures')<decisions.indexOf('Then, Charlie may research'));
assert.ok(decisions.indexOf('streetlighting improvement contract')<decisions.indexOf('World’s Fair follows'));
