const reception=ash('blackwoodAsylum','reception');
const patient=ash('blackwoodAsylum','patient-ward');
perform(edmund,'wardRecord',ward);
perform(edmund,'wardCorridor',patient);
perform(edmund,'passageMark',patient);
perform(edmund,'visitorRegister',reception);
perform(edmund,'wardMemo',ward);
