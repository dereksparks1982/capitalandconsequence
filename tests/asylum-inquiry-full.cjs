const story=globalThis.FE_ASYLUM_STORY=require('../asylum-story.js');
const make=(route,at)=>{const s={characterRoute:route,sharedWorldId:'wcase-integrated',gameDate:'1878-01-05',
 phase:'day',paused:false,turnSerial:1,npcSimulation:{},otherLives:{}};bridge.start(s,'1878-01-05',at);return s};
const edmund=make('wardman',9*60+30);
const first=FE_SHARED_WORLD.create(edmund.sharedWorldId,edmund);
