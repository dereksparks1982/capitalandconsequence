const ash=(locationId,roomId)=>({locationId,roomId});
function perform(save,id,place,worldRecord=world){
 const ready=story.preview(save,worldRecord,id,place);
 assert.equal(ready.ok,true,id+' failed: '+ready.reason);
 const minutes=bridge.spend(save,ready.seconds);assert.ok(minutes>=0);
 const result=story.apply(save,worldRecord,id,place,{spentSeconds:ready.seconds});
 assert.equal(result.ok,true,id+' apply failed: '+result.reason);
 return result;
}
