assert.equal(reloadWorld.worldTruth[story.CASE_ID].culpritRole,world.worldTruth[story.CASE_ID].culpritRole);
assert.equal(edmundCopy.wardmanStanding.familyMeetings.length,1);
assert.equal(FE_ASYLUM_EVIDENCE.roster(reloadWorld).some(p=>p.culpritRole!==undefined),false);
