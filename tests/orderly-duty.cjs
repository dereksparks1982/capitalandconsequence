'use strict';
const assert=require('node:assert/strict'),duty=require('../orderly-duty.js');
const date='1890-01-02',station={locationId:duty.VENUE,roomId:duty.STATION},
 ward={locationId:duty.VENUE,roomId:duty.WARD};
const life=()=>({characterRoute:'wardman',phase:'day',paused:false,personalCash:3.75});
let s=life();
assert.equal(duty.MAX_ASSIGNMENTS,3);
assert.equal(duty.ASSIGNMENTS.length,5);
assert.equal(duty.access({...s,characterRoute:'industrialist'},'assign',...Object.values(station)).ok,false);
assert.equal(duty.access(s,'assign',duty.VENUE,'superintendent-office').ok,false);
assert.equal(duty.access(s,'attend',duty.VENUE,duty.STATION).ok,false);
assert.equal(duty.assign(s,{...station,date,profileId:'edmund',spentSeconds:0}).ok,false);
assert.equal(duty.summary(s).totalAssignments,0);
const opened=duty.assign(s,{...station,date,profileId:'edmund',spentSeconds:300});
assert.equal(opened.ok,true);
assert.equal(duty.assign(s,{...station,date,profileId:'edmund',spentSeconds:300}).ok,false);
assert.equal(duty.file(s,{...station,spentSeconds:300}).ok,false);
assert.equal(duty.attend(s,{...ward,choiceId:'bogus',spentSeconds:600}).ok,false);
assert.equal(duty.attend(s,{...ward,choiceId:opened.task.choices[0].id,spentSeconds:0}).ok,false);
const mid=JSON.parse(JSON.stringify(s));
assert.equal(duty.task(mid).id,opened.task.id,'Assignment survives autosave');
const served=duty.attend(mid,{...ward,choiceId:opened.task.choices[0].id,spentSeconds:600});
assert.equal(served.ok,true);
assert.equal(duty.attend(mid,{...ward,choiceId:opened.task.choices[0].id,spentSeconds:600}).ok,false);
assert.equal(duty.summary(mid).wagesEarnedCents,0,'Attending ward is not yet a payday');
assert.equal(duty.file(mid,{...ward,spentSeconds:300}).ok,false,'Must report in assigned staff room');
const close=duty.file(mid,{...station,spentSeconds:300});
assert.equal(close.ok,true);assert.equal(close.wageCents,35);
assert.equal(mid.personalCash,4.10);
assert.equal(duty.file(mid,{...station,spentSeconds:300}).ok,false,'Repeat pay impossible');
for(let i=1;i<duty.MAX_ASSIGNMENTS;i++){
 const task=duty.assign(mid,{...station,date,profileId:'edmund',spentSeconds:300});
 assert.equal(task.ok,true);
 assert.equal(duty.attend(mid,{...ward,choiceId:task.task.choices[0].id,spentSeconds:600}).ok,true);
 assert.equal(duty.file(mid,{...station,spentSeconds:300}).ok,true);
}
assert.equal(duty.summary(mid).totalAssignments,3);
assert.equal(duty.summary(mid).wagesEarnedCents,105);
assert.equal(mid.personalCash,4.80);
assert.equal(duty.assign(mid,{...station,date,profileId:'edmund',spentSeconds:300}).ok,false,'No infinite repeated shift wage');
assert.equal(duty.assign(mid,{...station,date:'1890-01-03',profileId:'edmund',spentSeconds:300}).ok,true,'New date permits new assignment');
const paused=life();paused.paused=true;
assert.equal(duty.assign(paused,{...station,date,profileId:'edmund',spentSeconds:300}).ok,false);
const night=life();night.phase='night';
assert.equal(duty.assign(night,{...station,date,profileId:'edmund',spentSeconds:300}).ok,false);
const separate=life();assert.equal(duty.summary(separate).totalAssignments,0,'Profile isolation');
const pending=JSON.parse(JSON.stringify(mid));
pending.phase='night';
assert.equal(duty.file(pending,{...station,spentSeconds:300}).ok,false,'Only attended work can be filed');
assert.ok(duty.summary(mid).logs.every(l=>l.result&&!l.result.toLowerCase().includes('diagnosis')),'No fabricated medical files');
console.log('PASS Wardman assigned orderly rounds, ward care, report-gated pay, room/phase restrictions and save stability');
