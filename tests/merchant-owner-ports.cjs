'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const nav=require('../merchant-navigation.js'),regions=require('../merchant-regions.js');
const read=p=>fs.readFileSync(path.join(__dirname,'..',p),'utf8');
const a={characterRoute:'mariner'},b={characterRoute:'industrialist'};
assert.deepEqual(regions.chartPoint(a,'Baltimore'),nav.DISPLAY_PORTS.Baltimore);
assert.equal(regions.movePort(a,'Baltimore',315.3,205.1).ok,true);
assert.deepEqual(regions.chartPoint(a,'Baltimore'),[315.3,205.1]);
assert.deepEqual(regions.chartPoint(b,'Baltimore'),nav.DISPLAY_PORTS.Baltimore,'edits are per-character');
assert.equal(regions.addPort(a,'Owner New Harbor',572.4,278.2).ok,true);
assert.equal(regions.renamePort(a,'Owner New Harbor','Updated Harbor').ok,true);
assert.equal(regions.chartPoint(a,'Owner New Harbor'),null);
assert.equal(regions.movePort(a,'Updated Harbor',588.1,294.8).ok,true);
assert.deepEqual(regions.chartPoint(a,'Updated Harbor'),[588.1,294.8]);
assert.equal(regions.addPort(a,'updated harbor',550,280).ok,false,'case-insensitive duplicate refused');
assert.equal(regions.addPort(a,'constructor',550,280).ok,false,'reserved name refused');
assert.equal(regions.movePort(a,'Baltimore',900,50).ok,false);
assert.equal(regions.deletePort(a,'Baltimore').ok,false,'built-in economic ports cannot be erased');
assert.equal(regions.deletePort(a,'Updated Harbor').ok,true);
assert.equal(regions.chartPoint(a,'Updated Harbor'),null);
assert.deepEqual(regions.chartPoint(JSON.parse(JSON.stringify(a)),'Baltimore'),[315.3,205.1],'saved positions survive JSON roundtrip');
assert.deepEqual(Object.keys(nav.PORTS).sort(),Object.keys(require('../industrial-empire.js').PORTS).sort());
