'use strict';
const assert=require('node:assert/strict'),e=require('../championships.js'),planner=require('../boxing-championship.js');
const s=e.init({}),roster=Array.from({length:15},(_,i)=>({id:i+1,weightClass:['middle','welter','heavy'][i%3],condition:90}));
assert.equal(planner.saturday('1878-01-26'),true);
assert.equal(planner.saturday('1878-01-27'),false);
assert.equal(planner.next(s,'1878-01-27',roster,e),null);
const one=planner.next(s,'1878-01-26',roster,e);assert.equal(one.roundId,'heat-a');
assert.deepEqual(planner.next(s,'1878-01-26',roster,e),one);
assert.equal(new Set(s.tournaments[one.tournamentId].entrants).size,4);
const finish=(v,d)=>e.round(s,{tournamentId:v.tournamentId,roundId:v.roundId,order:v.fighters.map(String),date:d});
finish(one,'1878-01-26');
const two=planner.next(s,'1878-02-02',roster,e);assert.equal(two.roundId,'heat-b');finish(two,'1878-02-02');
const three=planner.next(s,'1878-02-09',roster,e);assert.equal(three.roundId,'final');
assert.deepEqual(three.fighters,[one.fighters[0],two.fighters[0]]);finish(three,'1878-02-09');
assert.equal(s.champions.boxing.name,String(one.fighters[0]));assert.equal(s.titleHistory.length,1);
assert.equal(planner.next(s,'1878-02-16',roster,e),null,'No extra February tournament after February final');
const newTitle=planner.next(s,'1878-03-02',roster,e);
assert.equal(newTitle.roundId,'heat-a');assert.notEqual(newTitle.tournamentId,one.tournamentId);
console.log('PASS licensed boxing weekly bracket across months, stable seeding and monthly season starts');
