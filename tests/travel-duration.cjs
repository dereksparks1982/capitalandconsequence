'use strict';
const assert=require('node:assert/strict');
const bridge=require('../calendar-bridge.js'),tx=require('../time-transactions.js');
global.S={turnSerial:1,paused:false,transport:{journeys:[]}};
bridge.start(S,'1890-01-02');
global.window={FederalElectricCity:{getLocation:id=>['factory','home','races'].includes(id)?{id}:null,getRoom:(id,room)=>['factory','home','races'].includes(id)&&['front','back','office'].includes(room)?{id:room}:null},
 FE_CALENDAR_BRIDGE:bridge,FE_TIME_TX:tx,advanceWorldTime:seconds=>tx.advance(S,seconds,'travel').applied?seconds:0};
require('../journey-planner.js');
const travel=window.FE_TRAVEL;
assert.equal(travel.DEFAULT_TRAVEL_MINUTES,30);
assert.match(travel.notice('factory','home'),/current pin positions/,'Route time is recomputed from pin placement');
assert.match(travel.notice('factory','home'),/1 in-game minute/,'Room movement is not free');
assert.match(travel.notice('factory','factory'),/Already here/);
assert.equal(travel.recordProvisional('factory','factory'),false);
assert.equal(bridge.label(S),'8:00 AM');
assert.equal(travel.recordProvisional('factory','home','trip-1'),true);
assert.equal(bridge.label(S),'8:30 AM');
assert.equal(S.transport.journeys[0].temporaryGameMinutes,30);
assert.equal(S.transport.journeys[0].calendarApplied,true);
assert.equal(S.transport.journeys[0].departedAt,'1890-01-02T08:00');
assert.equal(S.transport.journeys[0].arrivedAt,'1890-01-02T08:30');
assert.equal(travel.recordProvisional('factory','home','trip-1'),false);
assert.equal(bridge.label(S),'8:30 AM','Duplicate travel cannot charge twice');
assert.equal(travel.recordProvisional('home','races','trip-2'),true);
assert.equal(bridge.label(S),'9:00 AM');
assert.equal(travel.recordProvisional('races','races'),false);
assert.equal(travel.recordRoomMove('home','front','front'),false,'Same room is free');
assert.equal(travel.recordRoomMove('home','front','back','room-1'),true);
assert.equal(bridge.label(S),'9:01 AM','Changing rooms costs a minute');
assert.equal(S.transport.journeys.at(-1).kind,'room-move');
assert.equal(S.transport.journeys.at(-1).temporaryGameMinutes,1);
assert.equal(S.transport.journeys.at(-1).departedAt,'1890-01-02T09:00');
assert.equal(S.transport.journeys.at(-1).arrivedAt,'1890-01-02T09:01');
assert.equal(travel.recordRoomMove('home','front','back','room-1'),false,'Room idempotence');
assert.equal(bridge.label(S),'9:01 AM');
S.paused=true;
assert.equal(travel.recordProvisional('races','home','paused-trip'),false);
assert.equal(bridge.label(S),'9:01 AM');
S.paused=false;
console.log('PASS temporary travel, same-building movement and charge idempotence');
