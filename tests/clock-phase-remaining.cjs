'use strict';
const assert=require('node:assert/strict');
const bridge=require('../calendar-bridge.js'),clock=require('../washington-time.js');
const save={paused:false,phase:'day',dayRemaining:3600};
bridge.start(save,'1878-01-02',480);
assert.equal(clock.phaseSecondsRemaining(save),9*3600,'Full morning to closing bell');
clock.advance(save,8*3600+50*60,'action','shift');
assert.equal(clock.now(save).time,'4:50 PM');
assert.equal(clock.phaseSecondsRemaining(save),600,'Ten-minute task permitted at 4:50');
clock.advance(save,60,'action','one-more-minute');
assert.equal(clock.phaseSecondsRemaining(save),540,'Ten-minute task rejected at 4:51');
save.phase='night';bridge.start(save,'1878-01-02',1020);
assert.equal(clock.phaseSecondsRemaining(save),15*3600);
clock.advance(save,9*3600,'action','overnight');
assert.equal(clock.phaseSecondsRemaining(save),6*3600);
save.phase='report';assert.equal(clock.phaseSecondsRemaining(save),0);
save.phase='day';bridge.start(save,'1878-01-03',480);
assert.equal(clock.phaseSecondsRemaining(save),9*3600);
assert.equal(clock.phaseSecondsRemaining({dayRemaining:1200,worldCalendarStatus:'legacy-unmapped'}),1200,'Never invent historic time');
console.log('PASS live phase time derived from saved calendar and shift boundaries');
