'use strict';
const assert=require('node:assert/strict'),bridge=require('../calendar-bridge.js'),time=require('../washington-time.js');
const s={paused:false,phase:'day',dayRemaining:3600};bridge.start(s,'1878-01-02');
assert.equal(time.rate(s),1);assert.equal(time.available(s),Number.MAX_SAFE_INTEGER);
assert.equal(time.debit(s,28800),28800,'Eight-hour cards permitted');
assert.equal(s.dayRemaining,3600,'A player action never touches the retired hourly budget');
assert.equal(time.advance(s,1,'tick').wholeMinutes,0);
assert.equal(s.worldCalendarRemainder,1);
time.advance(s,59,'tick');assert.equal(time.now(s).iso,'1878-01-02T08:01');
time.advance(s,3600,'tick');assert.equal(time.now(s).iso,'1878-01-02T09:01','One hour real idleness equals one hour game time');
time.advance(s,28800,'action','cards-eight-hours');
assert.equal(time.now(s).iso,'1878-01-02T17:01');
const before=JSON.stringify(s);assert.equal(time.advance(s,28800,'action','cards-eight-hours').status,'duplicate');assert.equal(JSON.stringify(s),before);
assert.equal(time.secondsUntilMorning(s),53940,'Resting reaches next actual 8 AM');
const rest=time.secondsUntilMorning(s);time.advance(s,rest,'action','sleep');
assert.equal(time.now(s).iso,'1878-01-03T08:00');
assert.equal(time.rate({...s,phase:'night'}),1);
assert.equal(time.canSpend({...s,paused:true},600),false);
assert.equal(time.debit({...s,paused:true},600),0);
const other={paused:false};bridge.start(other,'1878-01-02');assert.equal(time.now(other).time,'8:00 AM');
const midnight={paused:false};bridge.start(midnight,'1878-01-02',1438);
assert.equal(time.secondsToBoundary(midnight),120);time.advance(midnight,120,'action');
assert.equal(time.now(midnight).iso,'1878-01-03T00:00');
console.log('PASS continuous 1:1 day-night tick, action jumps, no fixed phases, sleep and midnight');
