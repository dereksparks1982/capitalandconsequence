'use strict';
const assert=require('node:assert/strict');
const bridge=require('../calendar-bridge.js'),time=require('../washington-time.js');
const s={paused:false,phase:'day',dayRemaining:3600,phaseBudgetRemainder:0};
bridge.start(s,'1878-01-02');
assert.equal(time.rate(s),9);
assert.equal(time.available(s),32400,'One hour daylight phase has 9h game-time budget');
assert.equal(time.advance(s,1,'tick').wholeMinutes,0,'Nine simulated seconds do not fill a minute');
s.dayRemaining--;
assert.equal(time.now(s).iso,'1878-01-02T08:00');
time.advance(s,3,'tick');s.dayRemaining-=3;
assert.equal(time.now(s).iso,'1878-01-02T08:00');
time.advance(s,3,'tick');s.dayRemaining-=3;
assert.equal(time.now(s).iso,'1878-01-02T08:01','Seven real seconds advance over one game minute');
const before=time.available(s),charged=time.debit(s,600);
assert.equal(charged,600,'Ten-minute duty uses ten real in-game minutes');
assert.equal(time.available(s),before-600,'Action debits exact simulated budget');
time.advance(s,charged,'action','patrol-one');
assert.equal(time.now(s).iso,'1878-01-02T08:11');
assert.equal(time.advance(s,charged,'action','patrol-one').status,'duplicate');
const carryS={paused:false,phase:'day',dayRemaining:2,phaseBudgetRemainder:0};
assert.equal(time.debit(carryS,1),1);assert.equal(carryS.dayRemaining,2);
assert.equal(time.debit(carryS,8),8);assert.equal(carryS.dayRemaining,1);
assert.equal(time.debit(carryS,9),9);assert.equal(carryS.dayRemaining,0);
assert.equal(time.available(carryS),0,'The fraction-preserving ledger spends exactly 18 game seconds');
const saved=JSON.parse(JSON.stringify(s));
assert.equal(time.available(saved),time.available(s),'Budget and remainder persist across reload');
const evening={paused:false,phase:'day',dayRemaining:3600};
bridge.start(evening,'1878-01-02');
time.advance(evening,3600,'tick');
assert.equal(time.now(evening).iso,'1878-01-02T17:00','60 real minutes of daylight = 9h simulated');
evening.phase='night';evening.dayRemaining=3600;
time.advance(evening,3600,'tick');
assert.equal(time.now(evening).iso,'1878-01-03T08:00','60 real minutes of Washington night = 15h simulated');
assert.equal(time.rate(evening),15);
const storm={...evening,worldCalendar:JSON.parse(JSON.stringify(evening.worldCalendar)),turnConditions:{weather:'Storm'}};
assert.equal(time.environment(storm).weather,'Storm');
const paused={paused:true,phase:'night',dayRemaining:3600};
bridge.start(paused,'1878-01-02',17*60);
assert.equal(time.advance(paused,100,'tick').status,'paused');
assert.equal(time.now(paused).iso,'1878-01-02T17:00');
assert.equal(time.debit(paused,500),0);
assert.equal(time.canSpend({phase:'day',dayRemaining:1},9),true);
assert.equal(time.canSpend({phase:'day',dayRemaining:1},10),false);
console.log('PASS 24h daily pacing, actual action durations, exact phase accounting, pause, reload, midnight');
