'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const projection=require('../workshop-presence.js'),operations=require('../workshop-operations.js');
const save={componentWorks:{version:1},npcSimulation:{seed:77}};
const worker={id:'foremanSullivan',locationId:'factory',roomId:'production-floor',status:'present',activity:'assembling relays'};
const test=(date,minute)=>projection.position(save,worker,'foremanSullivan',{date,minuteOfDay:minute});
const d='1878-01-02';
const a=operations.arrival(save,d);
assert.equal(a.absent,false);
assert.equal(test(d,480).locationId,null,'No 8 AM phantom assistant');
assert.equal(test(d,539).status,'off-duty','Work begins at 9 not 8');
assert.equal(test(d,540).locationId,a.arrivalMinute===540?'factory':null);
assert.equal(test(d,1020).locationId,null,'Worker leaves at 5');
assert.equal(test(d,1021).locationId,null);
let late=null,absent=null;
for(let i=0;i<1800;i++){
 const date=new Date(Date.UTC(1878,0,2+i)).toISOString().slice(0,10),wd=new Date(date+'T12:00:00Z').getUTCDay();
 if(wd===0||wd===6)continue;
 const v=operations.arrival(save,date);
 if(!late&&v.delayMinutes)late={date,v};
 if(!absent&&v.absent)absent={date,v};
 if(late&&absent)break;
}
assert.ok(late&&absent,'Schedules exercise late arrivals and absences');
assert.equal(test(late.date,540).locationId,null);
assert.equal(test(late.date,late.v.arrivalMinute-1).locationId,null);
assert.equal(test(late.date,late.v.arrivalMinute).locationId,'factory');
assert.equal(test(absent.date,660).locationId,null);
assert.equal(test('1878-01-05',600).locationId,null,'Saturday is not a manufacturing shift');
assert.equal(test('1878-01-06',600).locationId,null,'Sunday is closed');
const outsider={id:'chenMei',locationId:'oldChinatown',roomId:'market',status:'present'};
assert.equal(projection.position(save,outsider,'chenMei',{date:d,minuteOfDay:480}),outsider,'Other NPCs are unaffected');
const offsite={...worker,locationId:'races',roomId:'track'};
assert.equal(projection.position(save,offsite,'foremanSullivan',{date:d,minuteOfDay:630}),offsite,'Real alternative engagements remain possible');
const snap=JSON.stringify({save,worker});
for(let i=0;i<20;i++)test(d,600);
assert.equal(JSON.stringify({save,worker}),snap,'Merely viewing rooms cannot change the saved character');
const src=fs.readFileSync(path.join(__dirname,'../npc-ai.js'),'utf8');
assert.ok(src.includes('function observedPosition(')&&src.includes('observedPosition(id,actor)')&&src.includes('observedPosition(id,S.npcSimulation?.agents?.[id])'),'Public visitors and both dialogue types use the same physical presence');
console.log('PASS minute-accurate NPC sightings, late/absent work, privacy, talk guards and read-only projections');
