'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const tour=require('../circus-tour.js');
const show=require('../circus-big-top.js');
const peddler=require('../traveling-salesman.js');
const midway=require('../circus-carnival.js');
const noon=Date.UTC(1878,4,4,12)/60000;
global.FederalElectricCity={listLocations:()=>[{id:'races',name:'Capital Race Grounds'}]};
global.FE_CIRCUS_TOUR=tour;
function start(){
 return {worldCalendarStatus:'ready',worldCalendar:{worldMinute:noon},gameDate:'1878-05-04',
  characterRoute:'industrialist',personalCash:8,currentLocation:{locationId:'races',roomId:'grounds'}};
}
const save=start(),event=tour.active(save);
assert.ok(event);
assert.equal(tour.attended(save),false);
const booth=midway.start(save,'rings');
assert.equal(booth.ok,true);
assert.equal(tour.attended(save),false,'playing a midway booth does not count as seeing a circus show');
const ticket=show.slot(save);
assert.equal(ticket.ok,true);
assert.equal(ticket.waitMinutes,0);
assert.equal(ticket.feeCents,20);
assert.equal(show.perform(save,ticket).ok,false,'cannot record attendance before the actual end');
save.worldCalendar.worldMinute=ticket.finish;
assert.equal(show.perform(save,ticket).ok,true);
assert.equal(show.perform(save,ticket).ok,false,'Big Top receipt is not repeatable');
assert.equal(tour.attended(save),true,'actual performance attendance affects future NPC conversations');
assert.equal(save.circusPerformances.length,1);
const merchant=peddler.stock(save);
assert.equal(merchant.length,5);
assert.equal(merchant.some(g=>g.rare&&g.kind==='rare'),true);
assert.equal(merchant.find(g=>g.id==='brass-spyglass').examined,false);
assert.equal(peddler.examine(save,'brass-spyglass').good,false,'fake relic is ordinary junk');
assert.match(peddler.examine(save,'brass-spyglass').truth,/cheap flat glass/i);
assert.equal(peddler.examine(save,'pocket-loupe').good,true,'some goods really are rare');
const cashBefore=Math.round(save.personalCash*100),price=merchant.find(g=>g.id==='brass-spyglass').priceCents;
assert.equal(peddler.buy(save,'brass-spyglass',()=>({ok:false,reason:'Pockets full'})).ok,false);
assert.equal(Math.round(save.personalCash*100),cashBefore,'failed inventory receipt must not spend player money');
let carried=[];
const deal=peddler.buy(save,'brass-spyglass',item=>{carried.push(item);return {ok:true}});
assert.equal(deal.ok,true);
assert.equal(deal.good.kind,'junk');
assert.equal(Math.round(save.personalCash*100),cashBefore-price);
assert.equal(carried.length,1);
assert.equal(peddler.buy(save,'brass-spyglass',()=>{throw Error('double item')}).ok,false);
assert.equal(peddler.stock(save).find(g=>g.id==='brass-spyglass').owned,true);
save.currentLocation={locationId:'home',roomId:'bedroom'};
assert.equal(peddler.present(save),null,'the peddler cannot be shopped from home');
assert.equal(peddler.stock(save).length,0);
assert.equal(peddler.buy(save,'pocket-loupe',()=>({ok:true})).ok,false);
const later=start();later.worldCalendar.worldMinute=Date.UTC(1878,9,10,12)/60000;
assert.equal(tour.active(later),null,'the public circus icon disappears outside its dates');
assert.equal(show.slot(later).ok,false,'show does not run after circus leaves');
const app=fs.readFileSync(path.join(__dirname,'../app.js'),'utf8');
const html=fs.readFileSync(path.join(__dirname,'../index.html'),'utf8');
const source=fs.readFileSync(path.join(__dirname,'../npc-ai.js'),'utf8');
assert.doesNotMatch(app,/FE_CIRCUS_TOUR\?\.attend\?\.\(S,window\.FE_CIRCUS_TOUR/,'booth play cannot masquerade as actual show attendance');
assert.match(app,/function attendCircusShow\(/);
assert.match(app,/FE_CIRCUS_BIG_TOP_UI\?\.render/);
assert.match(app,/FE_TRAVELING_SALESMAN_UI\?\.render/);
assert.match(app,/FE_PERSONAL_EFFECTS\?\.acquire\?\.\(good\)/);
assert.match(source,/FE_CIRCUS_TOUR\.attended\(S\)/,'circus gossip reacts to genuine attendance');
for(const js of ['circus-big-top.js','circus-big-top-ui.js','traveling-salesman.js','traveling-salesman-ui.js']){
 assert.match(html,new RegExp(js.replace(/\./g,'\\.')+'\\?v='));
 assert.ok(html.indexOf(js+'?')<html.indexOf('app.js?'),'load business mechanics before app');
}
console.log('PASS distinct circus performance attendance, real souvenir fees, honest and dishonest merchandise, restricted in-person trade');
