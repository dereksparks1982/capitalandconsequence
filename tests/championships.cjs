'use strict';
const assert=require('node:assert/strict');
const engine=require('../championships.js'),law=require('../gambling-law.js');
const s=engine.init({});
assert.equal(engine.sports.car.earliest,1933);
assert.throws(()=>engine.open(s,{sport:'car',date:'1878-01-28',entrants:Array.from({length:12},(_,i)=>'driver-'+i)}),/unavailable/);
const entrants=Array.from({length:8},(_,i)=>'player-'+i);
const tournament=engine.open(s,{sport:'poker',date:'1878-01-04',entrants});
assert.equal(engine.open(s,{sport:'poker',date:'1878-01-04',entrants}).id,tournament.id);
assert.throws(()=>engine.open({}, {sport:'poker',date:'1878-01-04',entrants:['A','A']}),/distinct/);
const w={betId:'stake-001',tournamentId:tournament.id,market:'champion',selection:'player-2',stake:10,decimalOdds:5,personalCash:35,date:'1878-01-04',law,venueId:'dc-poker-challenge',game:'five-card'};
const placed=engine.placeBet(s,{...w,explicitIllicit:false});
assert.equal(placed.personalCashAfter,25);assert.equal(placed.legal,true);
assert.throws(()=>engine.placeBet(s,{...w,betId:'stake-002',venueId:'embassy-poker'}),/not government-sanctioned/);
assert.throws(()=>engine.placeBet(s,w),/Duplicate/);
assert.throws(()=>engine.round(s,{tournamentId:tournament.id,roundId:'final',order:['player-2'],date:'1878-01-04'}),/Qualifying/);
engine.round(s,{tournamentId:tournament.id,roundId:'heat-a',order:['player-2','player-1','player-3','player-0'],date:'1878-01-04'});
engine.round(s,{tournamentId:tournament.id,roundId:'heat-b',order:['player-4','player-5','player-6','player-7'],date:'1878-01-04'});
const finishers=['player-2','player-4','player-1','player-5'];
const final=engine.round(s,{tournamentId:tournament.id,roundId:'final',order:finishers,date:'1878-01-04'});
assert.equal(final.tournament.champion,'player-2');
assert.equal(final.payout.credit,50);
assert.equal(final.payout.settled,1);
assert.equal(s.wagers[0].settled,true);
assert.equal(engine.view(s,'poker','1878-01-29').champion.name,'player-2');
assert.throws(()=>engine.round(s,{tournamentId:tournament.id,roundId:'final',order:finishers,date:'1878-01-04'}),/already finalized/);
assert.throws(()=>engine.placeBet(s,{...w,betId:'stake-003'}),/already known/);
const horse=engine.open(s,{sport:'horse',date:'1878-02-01',entrants:Array.from({length:12},(_,i)=>'horse'+i)});
assert.equal(horse.rounds['heat-a'].ids.length,6);
console.log('PASS championship lifecycle, historical gates, distinct entrants, authorized bets and exactly-once payout');
