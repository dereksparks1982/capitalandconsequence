'use strict';
const assert=require('node:assert/strict'),works=require('../component-works.js');
const s=works.createState();
assert.equal(s.date,'1878-01-02');
assert.equal(s.ownerRoute,'industrialist');
assert.equal(s.company,'Federal Electric');
assert.equal(s.orders.length,0);
assert.equal(works.eligibility(s,'incandescent-lamp').ok,false,'No bulb line in 1878');
for(const id of ['telegraph-key','telegraph-relay','switch-contact','insulated-wire','battery-fitting','insulator'])
 assert.equal(works.eligibility(s,id).ok,true,'Component product should be initially eligible: '+id);
const customer=works.CUSTOMERS[0],args={customer,productId:'telegraph-key',quantity:20,deadline:'1878-02-15'};
const offered=works.order(s,args,'accept:1');
assert.equal(offered.ok,true);assert.equal(s.orders.length,1);
assert.equal(works.order(s,args,'accept:1').repeated,true);
assert.equal(s.orders.length,1,'Repeated order token does not create a second order');
const before=JSON.stringify(s);
assert.equal(works.assemble(s,offered.id,500,'assembly:invalid').ok,false);
assert.equal(JSON.stringify(s),before,'Invalid assembly is atomic');
const quoted=works.assemblyQuote(s,offered.id,10);
assert.equal(quoted.ok,true);assert.equal(quoted.minutesRequired,1800);
const cost=s.cashCents,startingCopper=s.materials.copper;
const assembly=works.assemble(s,offered.id,10,'assembly:1');
assert.equal(assembly.ok,true);assert.equal(s.orders[0].made,10);
assert.equal(s.cashCents,cost-quoted.laborCostCents);
assert.equal(s.materials.copper,startingCopper-10);
assert.equal(s.warehouse['telegraph-key'],10);
assert.equal(works.assemble(s,offered.id,10,'assembly:1').repeated,true);
assert.equal(s.orders[0].made,10);
assert.equal(s.minutesCommitted,1800);
const old=JSON.stringify(s);
assert.equal(works.ship(s,offered.id,20,'ship:early').ok,false,'Cannot ship unmade product');
assert.equal(JSON.stringify(s),old,'Rejected shipment makes no state change');
const firstShipment=works.ship(s,offered.id,5,'ship:1');
assert.equal(firstShipment.ok,true);assert.equal(s.orders[0].status,'partial');
const second=works.assemble(s,offered.id,10,'assembly:2');
assert.equal(second.ok,true);
assert.equal(works.ship(s,offered.id,15,'ship:2').complete,true);
assert.equal(s.orders[0].status,'delivered');
const finalCash=s.cashCents;
assert.equal(works.ship(s,offered.id,15,'ship:2').repeated,true);
assert.equal(s.cashCents,finalCash,'Payment cannot be duplicated');
const reloaded=JSON.parse(JSON.stringify(s));
assert.equal(works.assemble(reloaded,offered.id,10,'assembly:2').repeated,true,'Persistent idempotent receipts survive reload');
assert.equal(JSON.stringify(reloaded),JSON.stringify(s));
const rich=s.cashCents;
assert.equal(works.purchase(s,'brass',30,'material:1').ok,true);
assert.equal(s.cashCents,rich-works.MATERIALS.brass.costCents*30);
assert.equal(works.purchase(s,'brass',30,'material:1').repeated,true);
const stocked=works.createState();
stocked.materials.copper=0;
const another=works.order(stocked,{...args,quantity:1},'accept:other');
const stockBefore=JSON.stringify(stocked);
assert.equal(works.assemble(stocked,another.id,1,'assembly:missing').ok,false);
assert.equal(JSON.stringify(stocked),stockBefore,'No partial debit when raw materials are missing');
const future=works.createState('1880-01-02');
assert.equal(works.eligibility(future,'incandescent-lamp').ok,false,'Date alone cannot grant patents or production tools');
future.licenses.push('incandescent-rights');
assert.equal(works.eligibility(future,'incandescent-lamp').ok,false,'License alone does not conjure a lamp line');
future.stations['lamp-line']=1;
assert.equal(works.eligibility(future,'incandescent-lamp').ok,true);
assert.throws(()=>works.verify({version:2}),/Unrecognized/);
assert.deepEqual(works.createState(),works.createState(),'Deterministic starting foundation');
console.log('PASS 1878 component catalogue, gates, procurement, factory assembly, warehouse delivery and reload-safe payments');
